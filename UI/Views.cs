
using KawaiiTasks.Models; // Подключаем модели проекта: Project, TaskItem, TaskState и другие сущности.
using KawaiiTasks.Services; // Подключаем сервисы для формирования отчётов, определения настроения маскота и оформления интерфейса.
using Spectre.Console; // Подключаем библиотеку для создания цветных таблиц, панелей, сеток и других элементов консольного интерфейса.
using Spectre.Console.Rendering; // Подключаем интерфейсы отображаемых элементов, включая IRenderable.

namespace KawaiiTasks.UI; // Определяем пространство имён для классов, отвечающих за пользовательский интерфейс.

// <summary>
// Класс Views отвечает за визуальное представление информации проекта.
// Здесь находятся методы для отображения шапки проекта, канбан-доски,
// таблицы задач, подробной карточки задачи и списка участников команды.
// Класс не изменяет данные проекта и не содержит бизнес-логики.
// Он получает готовые данные и преобразует их в элементы интерфейса
// с помощью библиотеки Spectre.Console.
// </summary>
public static class Views
{
    // Массив содержит варианты текстовых аватарок для участников команды.
    // Аватар выбирается на основании ID участника, поэтому при повторном отображении
    // один и тот же участник получает одинаковую аватарку.
    private static readonly string[] Avatars =
        { "(=^.w.^=)", "(*u*)", "(o.o)", "(*u*.)", "(*>u<*)" };

    /// <summary>
    /// Преобразует количество минут в удобный для чтения формат.
    /// Например, 135 минут превращаются в строку "2ч 15м".
    /// Если значение равно нулю или меньше, возвращается прочерк.
    /// </summary>
    /// <param name="minutes">Количество минут.</param>
    /// <returns>Отформатированное время.</returns>
    public static string Fmt(int minutes) =>
        // Если времени нет, показываем прочерк.
        // В противном случае отдельно вычисляем часы и оставшиеся минуты.
        minutes <= 0 ? "-" : $"{minutes / 60}ч {minutes % 60:00}м";

    /// <summary>
    /// Преобразует дату в строку установленного формата.
    /// Если дата отсутствует, возвращает прочерк.
    /// </summary>
    /// <param name="date">Дата, которая может отсутствовать.</param>
    /// <returns>Дата в формате день.месяц.год или прочерк.</returns>
    public static string Date(DateTime? date) =>
        // HasValue проверяет наличие даты.
        // Value.ToString преобразует существующую дату в формат dd.MM.yyyy.
        date.HasValue ? date.Value.ToString("dd.MM.yyyy") : "-";

    /// <summary>
    /// Ограничивает длину текста заданным количеством символов.
    /// Если текст длиннее ограничения, лишняя часть заменяется многоточием.
    /// Используется для сохранения удобной ширины таблиц и карточек.
    /// </summary>
    /// <param name="text">Исходный текст.</param>
    /// <param name="max">Максимально допустимая длина строки.</param>
    /// <returns>Исходный или сокращённый текст.</returns>
    public static string Short(string text, int max) =>
        // Если максимальная длина отрицательная или равна нулю, возвращаем пустую строку.
        // Если текст уже помещается, возвращаем его без изменений.
        // При ограничении до трёх символов обрезаем строку без многоточия.
        // В остальных случаях оставляем место для трёх точек.
        max <= 0 ? "" : text.Length <= max ? text : max <= 3 ? text[..max] : text.Substring(0, max - 3) + "...";

    /// <summary>
    /// Создаёт таблицу с единым оформлением для всего приложения.
    /// Настраивает рамку, цвет границ, разделители строк, заголовок и подпись.
    /// Метод используется другими методами класса Views.
    /// </summary>
    /// <param name="title">Название таблицы.</param>
    /// <param name="caption">Дополнительная подпись под таблицей.</param>
    /// <returns>Подготовленная таблица Spectre.Console.</returns>
    private static Table NewTable(string title, string caption)
    {
        // Создаём новый объект таблицы.
        var table = new Table
        {
            // Используем ASCII-символы для рамки.
            // Это помогает избежать проблем с отображением границ в разных терминалах.
            Border = TableBorder.Ascii,

            // Устанавливаем цвет рамки из общей цветовой темы приложения.
            BorderStyle = new Style(Theme.LavenderC),

            // Включаем горизонтальные разделители между строками.
            ShowRowSeparators = true,

            // Добавляем заголовок с декоративным оформлением.
            // Spectre.Console интерпретирует текст внутри квадратных скобок как разметку.
            Title = new TableTitle($"[{Theme.Pink}]* {title} *[/]"),

            // Добавляем подпись под таблицей.
            Caption = new TableTitle($"[{Theme.Cocoa}]{caption}[/]")
        };

        // Возвращаем полностью настроенную таблицу.
        return table;
    }

    /// <summary>
    /// Отображает верхнюю информационную часть проекта.
    /// Показывает название, описание, общий прогресс, количество задач
    /// по статусам, накопленные баллы, уровень, затраченное время
    /// и информацию о просроченных задачах.
    /// Дополнительно отображает маскота с соответствующим настроением.
    /// </summary>
    /// <param name="project">Проект, информацию о котором необходимо показать.</param>
    public static void ProjectHeader(Project project)
    {
        // Формируем сводный отчёт по проекту.
        // Сервис самостоятельно рассчитывает статистику и показатели выполнения.
        var report = ReportService.Build(project);

        // Определяем настроение маскота на основании текущего состояния проекта.
        var mood = Mascot.MoodFor(project);

        // Получаем цвет, соответствующий определённому настроению маскота.
        var moodColor = Mascot.ColorFor(mood);

        // Получаем уровень проекта и его текстовое название.
        // Метод Level возвращает два значения, которые сохраняются в отдельные переменные.
        var (level, levelName) = ReportService.Level(report.CandyPoints);

        // Определяем ширину индикатора выполнения проекта в символах.
        const int barWidth = 24;

        // Рассчитываем количество заполненных символов прогресс-бара.
        // Percent переводится в долю от общей ширины индикатора.
        // Math.Round округляет результат до ближайшего целого числа.
        // Math.Clamp ограничивает значение диапазоном от 0 до 24.
        var filled = Math.Clamp((int)Math.Round(report.Percent / 100.0 * barWidth), 0, barWidth);

        // Если проект выполнен на 100% или больше, добавляем декоративную звёздочку.
        // В остальных случаях дополнительный символ не отображается.
        var end = report.Percent >= 100 ? $" [{Theme.Lemon}]*[/]" : "";

        // Собираем прогресс-бар в виде строки с цветной разметкой Spectre.Console.
        // Заполненная часть обозначается символами #, незаполненная — символами -.
        // После индикатора выводится процент выполнения проекта.
        var bar = $"[{Theme.Cocoa}]|[/][{Theme.Mint}]{new string('#', filled)}[/][grey]{new string('-', barWidth - filled)}[/][{Theme.Cocoa}]|[/] {report.Percent:0}%{end}";

        // Получаем количество задач, ожидающих выполнения.
        var waiting = report.ByState[TaskState.Todo];

        // Получаем количество задач, находящихся в процессе выполнения.
        var active = report.ByState[TaskState.InProgress];

        // Получаем количество задач, ожидающих проверки.
        var review = report.ByState[TaskState.Review];

        // Получаем количество завершённых задач.
        var done = report.ByState[TaskState.Done];

        // Проверяем, имеются ли в проекте просроченные задачи.
        // Если они есть, формируем предупреждение с их количеством.
        // Если просроченных задач нет, оставляем строку пустой.
        var overdue = report.Overdue.Count > 0
            ? $"   [{Theme.Berry}]! Просрочено: {report.Overdue.Count}[/]"
            : "";

        // Проверяем наличие описания проекта.
        // Если описание отсутствует или состоит только из пробелов, показываем подсказку.
        // Иначе экранируем пользовательский текст через Theme.E перед выводом.
        var description = string.IsNullOrWhiteSpace(project.Description)
            ? "[grey]Описание проекта не добавлено[/]"
            : $"[grey]{Theme.E(project.Description)}[/]";

        // Формируем компактную строку со статистикой задач.
        // Для каждого статуса используется собственный цвет из общей темы оформления.
        // В конце выводится общее количество задач.
        var chips =
            $"[{Theme.StateHex(TaskState.Todo)}]({waiting})[/] " +
            $"[{Theme.StateHex(TaskState.InProgress)}]({active})[/] " +
            $"[{Theme.StateHex(TaskState.Review)}]({review})[/] " +
            $"[{Theme.StateHex(TaskState.Done)}]({done})[/]  [grey]всего: {report.Total}[/]";

        // Создаём текстовый блок с основной информацией о проекте.
        // Markup позволяет использовать цветовую разметку Spectre.Console.
        // Символы \n создают переносы строк внутри блока.
        var text = new Markup(
            // Отображаем название проекта жирным текстом с акцентным цветом.
            $"[bold {Theme.Pink}]{Theme.E(project.Name)}[/]\n" +

            // Добавляем описание проекта.
            $"{description}\n" +

            // Разделяем информацию декоративной горизонтальной линией.
            $"[{Theme.Cocoa}]------------------------------[/]\n" +

            // Выводим индикатор выполнения проекта.
            $"{bar}\n" +

            // Показываем количество задач по каждому статусу.
            $"{chips}\n" +

            // Выводим баллы, уровень, затраченное время и предупреждение о просроченных задачах.
            $"[{Theme.Lemon}]{report.CandyPoints}[/] баллов | уровень {level}: {Theme.E(levelName)}   [{Theme.Sky}]Время: {Fmt(report.TotalMinutes)}[/]{overdue}");

        // Создаём сетку для размещения маскота и информационного блока рядом друг с другом.
        var grid = new Grid();

        // Добавляем первую колонку с запретом переноса текста.
        // Она предназначена для компактного отображения ASCII-аватарки.
        grid.AddColumn(new GridColumn { NoWrap = true });

        // Добавляем вторую колонку для основной информации о проекте.
        grid.AddColumn();

        // Добавляем строку сетки.
        // В первой ячейке находится маскот, во второй — подготовленная информация.
        // Mascot.Art возвращает текстовое изображение маскота.
        var gridRow = new Markup($"[{moodColor}]{Theme.E(Mascot.Art(mood))}[/]   ");
        grid.AddRow(gridRow, text);

        // Добавляем декоративную ленту перед информационной карточкой проекта.
        Theme.Tape(Theme.Sky, 10);

        // Формируем и выводим основную страницу проекта.
        // Theme.Page отвечает за единое оформление страниц приложения.
        AnsiConsole.Write(Theme.Page(grid, "~ СТРАНИЧКА ПРОЕКТА ~", Theme.Pink));

        // Создаём дополнительную панель с фразой маскота.
        // Фраза зависит от его текущего настроения.
        var bubble = new Panel(new Markup($"[{Theme.Lavender}]~ {Theme.E(Mascot.Phrase(mood))}[/]"))
        {
            // Устанавливаем ASCII-рамку для панели.
            Border = BoxBorder.Ascii,

            // Цвет рамки соответствует настроению маскота.
            BorderStyle = new Style(Theme.FromHex(moodColor)),

            // Добавляем внутренние отступы по горизонтали и вертикали.
            Padding = new Padding(1, 0)
        };

        // Размещаем панель с фразой маскота по центру терминала.
        AnsiConsole.Write(new Align(bubble, HorizontalAlignment.Center));

        // Выводим пустую строку для визуального отделения следующих элементов интерфейса.
        AnsiConsole.WriteLine();
    }

    /// <summary>
    /// Отображает канбан-доску проекта.
    /// Каждая колонка соответствует определённому статусу задачи.
    /// Карточки сортируются сначала по приоритету, затем по ID.
    /// При недостаточной ширине терминала доска переключается
    /// с горизонтального расположения колонок на вертикальное.
    /// </summary>
    /// <param name="project">Проект, содержащий информацию об исполнителях.</param>
    /// <param name="tasks">Коллекция задач для отображения.</param>
    public static void Board(Project project, IReadOnlyCollection<TaskItem> tasks)
    {
        // Выводим декоративный заголовок канбан-доски.
        Theme.Ribbon("ДОСКА ЗАДАЧ", Theme.Lavender);

        // Получаем все существующие значения перечисления TaskState.
        // На основании этого массива будут сформированы колонки доски.
        var states = Enum.GetValues<TaskState>();

        // Создаём список визуальных элементов.
        // Каждый элемент будет представлять отдельную колонку канбан-доски.
        var cards = new List<IRenderable>();

        // Перебираем все статусы задач, чтобы сформировать отдельную колонку для каждого из них.
        foreach (var state in states)
        {
            // Отбираем задачи, соответствующие текущему статусу.
            // Сначала располагаем задачи с более высоким приоритетом.
            // При одинаковом приоритете сортируем по ID.
            // ToList создаёт готовый список для дальнейшего отображения.
            var items = tasks.Where(t => t.State == state)
                             .OrderByDescending(t => t.Priority)
                             .ThenBy(t => t.Id)
                             .ToList();

            // Создаём список элементов, которые будут находиться внутри текущей колонки.
            var lines = new List<IRenderable>();

            // Проверяем, имеются ли задачи в текущем статусе.
            if (items.Count == 0)
            {
                // Если колонка пустая, отображаем соответствующее сообщение.
                lines.Add(new Markup("[grey]- пока пусто -[/]"));

                // Добавляем декоративную ASCII-надпись, обозначающую отсутствие задач.
                lines.Add(new Markup("[grey]  ( . . )  zzz[/]"));
            }

            // Перебираем задачи текущего статуса.
            // Переменная n используется для определения положения задачи в списке.
            for (var n = 0; n < items.Count; n++)
            {
                // Получаем текущую задачу из списка.
                var task = items[n];

                // Проверяем, просрочена ли задача.
                // Если срок нарушен, добавляем цветной предупреждающий символ.
                var warn = task.IsOverdue ? $"[{Theme.Berry}]![/]" : "";

                // Проверяем наличие установленного срока выполнения.
                // Если дата существует, добавляем её к информации о задаче.
                // Если дата отсутствует, дополнительный текст не выводится.
                var due = task.Deadline.HasValue ? $" | срок: {Date(task.Deadline)}" : "";

                // Формируем первую строку карточки.
                // Показываем индикатор приоритета, предупреждение, ID и название задачи.
                // Название сокращается до 24 символов, чтобы карточка не становилась слишком широкой.
                // Theme.E защищает пользовательский текст от интерпретации как разметки Spectre.Console.
                lines.Add(new Markup($"{Theme.PriorityDot(task.Priority)} {warn}[bold]#{task.Id}[/] {Theme.E(Short(task.Title, 24))}"));

                // Формируем вторую строку карточки.
                // Отображаем имя исполнителя и срок выполнения, если он установлен.
                lines.Add(new Markup($"[grey]  {Theme.E(project.AssigneeName(task))}{Theme.E(due)}[/]"));

                // Добавляем декоративный разделитель между карточками.
                // Для последней задачи разделитель не нужен.
                lines.Add(new Markup(n < items.Count - 1 ? Theme.Dots(22) : " "));
            }

            // Создаём панель для текущего статуса.
            // Rows объединяет подготовленные элементы в последовательность строк.
            cards.Add(new Panel(new Rows(lines))
            {
                // Устанавливаем заголовок колонки с названием статуса и количеством задач.
                // Justify.Center выравнивает заголовок по центру.
                Header = new PanelHeader($" {Theme.StateLabel(state)} [grey]({items.Count})[/]", Justify.Center),

                // Используем ASCII-символы для рамки колонки.
                Border = BoxBorder.Ascii,

                // Назначаем цвет рамки в зависимости от статуса задачи.
                BorderStyle = new Style(Theme.FromHex(Theme.StateHex(state))),

                // Разрешаем панели занимать доступную ширину своей области.
                Expand = true
            });
        }

        // Проверяем ширину терминала перед выбором способа отображения доски.
        // При ширине от 108 символов можно разместить четыре колонки рядом друг с другом.
        if (Theme.Width >= 108)
        {
            // Создаём расширяемую сетку для горизонтального расположения колонок.
            var grid = new Grid { Expand = true };

            // Для каждого статуса добавляем отдельную колонку сетки.
            foreach (var _ in states)
                grid.AddColumn();

            // Размещаем все подготовленные карточки в одной строке.
            grid.AddRow(cards.ToArray());

            // Выводим сетку по центру терминала.
            AnsiConsole.Write(new Align(grid, HorizontalAlignment.Center));
        }
        else
        {
            // Если терминал узкий, выводим каждую колонку отдельно.
            // Благодаря этому содержимое остаётся читаемым без горизонтальной прокрутки.
            foreach (var card in cards)
                AnsiConsole.Write(new Align(card, HorizontalAlignment.Center));
        }

        // Добавляем декоративные звёздочки после отображения доски.
        // Math.Min ограничивает их количество значением 40 и учитывает ширину терминала.
        Theme.Sparkles(Math.Min(40, Theme.Width - 4));
    }

    /// <summary>
    /// Отображает задачи в виде таблицы.
    /// Для каждой задачи выводятся ID, название, тип, приоритет,
    /// статус, исполнитель, срок выполнения и затраченное время.
    /// Если список пуст, вместо таблицы отображается информационное сообщение.
    /// </summary>
    /// <param name="project">Проект, необходимый для определения исполнителей.</param>
    /// <param name="tasks">Коллекция задач для отображения.</param>
    public static void TaskTable(Project project, IEnumerable<TaskItem> tasks)
    {
        // Преобразуем переданную коллекцию в список.
        // Это позволяет повторно обращаться к элементам и получить их количество.
        var list = tasks.ToList();

        // Проверяем, есть ли задачи для отображения.
        if (list.Count == 0)
        {
            // Если задач нет, выводим подсказку пользователю.
            Theme.Hint("Ничего не найдено. Попробуй изменить условия поиска.");

            // Завершаем выполнение метода, поскольку таблица не требуется.
            return;
        }

        // Создаём таблицу с единым стилем оформления.
        // В подписи указываем общее количество записей.
        var table = NewTable("Список задач", $"| всего записей: {list.Count} |");

        // Разрешаем таблице занимать всю доступную ширину терминала.
        table.Expand = true;

        // Создаём заголовки всех столбцов таблицы.
        // Каждый заголовок оформляется жирным текстом с использованием акцентного цвета.
        foreach (var header in new[] { "ID", "Задача", "Тип", "Приоритет", "Статус", "Исполнитель", "Срок", "Время" })
            table.AddColumn(new TableColumn($"[bold {Theme.Pink}]{header}[/]"));

        // Перебираем все задачи, чтобы добавить каждую из них отдельной строкой.
        foreach (var t in list)
        {
            // Формируем отображение срока выполнения.
            // Если задача просрочена, добавляем предупреждающий символ и цвет.
            var due = t.IsOverdue ? $"[{Theme.Berry}]! {Date(t.Deadline)}[/]" : Date(t.Deadline);

            // Добавляем строку с информацией о текущей задаче.
            table.AddRow(
                // Отображаем ID задачи с цветовым выделением.
                $"[{Theme.Cocoa}]#{t.Id}[/]",

                // Выводим название задачи, ограничивая его длину 40 символами.
                Theme.E(Short(t.Title, 40)),

                // Получаем текстовое название типа задачи.
                // Theme.E защищает пользовательский текст от интерпретации как разметки.
                Theme.E(t.Kind.Text()),

                // Преобразуем приоритет задачи в оформленную текстовую метку.
                Theme.PriorityLabel(t.Priority),

                // Преобразуем статус задачи в цветную текстовую метку.
                Theme.StateLabel(t.State),

                // Получаем имя исполнителя через объект проекта.
                Theme.E(project.AssigneeName(t)),

                // Выводим срок выполнения с учётом возможной просрочки.
                due,

                // Преобразуем затраченное количество минут в удобный формат.
                Fmt(t.SpentMinutes));
        }

        // Выводим готовую таблицу в консоль.
        AnsiConsole.Write(table);
    }

    /// <summary>
    /// Отображает подробную карточку выбранной задачи.
    /// Показывает описание, тип, приоритет, статус, исполнителя,
    /// срок выполнения и затраченное время.
    /// Если для задачи имеются записи времени, дополнительно выводится их таблица.
    /// </summary>
    /// <param name="project">Проект, содержащий информацию об участниках команды.</param>
    /// <param name="task">Задача, подробную информацию о которой нужно показать.</param>
    public static void TaskCard(Project project, TaskItem task)
    {
        // Создаём сетку для размещения названий характеристик и их значений.
        var grid = new Grid();

        // Добавляем первую колонку для названий характеристик.
        // NoWrap запрещает перенос названий на несколько строк.
        grid.AddColumn(new GridColumn { NoWrap = true });

        // Добавляем вторую колонку для значений характеристик.
        grid.AddColumn();

        // Локальная функция Row используется только внутри метода TaskCard.
        // Она принимает название характеристики и её готовое текстовое представление.
        // Название экранируется через Theme.E, чтобы специальные символы
        // не воспринимались как команды разметки Spectre.Console.
        void Row(string key, string value) =>
            // Добавляем новую строку в сетку.
            // Слева отображается название характеристики, справа — её значение.
            grid.AddRow(new Markup($"[{Theme.Lavender}]{Theme.E(key)}[/]   "), new Markup(value));

        // Определяем отображение срока выполнения задачи.
        // Если задача просрочена, добавляем предупреждение и соответствующую подпись.
        var due = task.IsOverdue ? $"[{Theme.Berry}]! {Date(task.Deadline)} (просрочена)[/]" : Date(task.Deadline);

        // Добавляем название задачи и её ID.
        Row("> Задача", $"[bold]#{task.Id} {Theme.E(task.Title)}[/]");

        // Добавляем описание задачи.
        // Если описание отсутствует, вместо него отображается прочерк.
        // Иначе пользовательский текст экранируется через Theme.E.
        Row("[ ] Описание", string.IsNullOrWhiteSpace(task.Description) ? "[grey]-[/]" : Theme.E(task.Description));

        // Добавляем тип задачи.
        Row("* Тип", Theme.E(task.Kind.Text()));

        // Добавляем приоритет с соответствующим цветовым оформлением.
        Row("* Приоритет", Theme.PriorityLabel(task.Priority));

        // Добавляем текущий статус задачи.
        Row("Статус", Theme.StateLabel(task.State));

        // Определяем и отображаем имя назначенного исполнителя.
        Row("[участник] Исполнитель", Theme.E(project.AssigneeName(task)));

        // Отображаем установленный срок выполнения.
        Row("[#] Срок", due);

        // Показываем суммарное время, затраченное на выполнение задачи.
        Row("Затрачено времени", Fmt(task.SpentMinutes));

        // Добавляем декоративную ленту перед карточкой задачи.
        Theme.Tape(Theme.Peach);

        // Формируем и выводим оформленную страницу с характеристиками задачи.
        AnsiConsole.Write(Theme.Page(grid, "[*] СТРАНИЧКА ЗАДАЧИ [*]", Theme.Pink));

        // Проверяем наличие записей времени.
        // Если записей нет, дальнейшее построение таблицы не требуется.
        if (task.TimeLog.Count == 0)
            return;

        // Создаём таблицу записей времени.
        // В подписи указываем количество сохранённых записей.
        var log = NewTable("Записи времени", $"| записей: {task.TimeLog.Count} |");

        // Добавляем столбец с датой записи.
        log.AddColumn($"[bold {Theme.Pink}]Дата[/]");

        // Добавляем столбец с количеством затраченного времени.
        log.AddColumn($"[bold {Theme.Pink}]Время[/]");

        // Добавляем столбец с текстовой заметкой.
        log.AddColumn($"[bold {Theme.Pink}]Заметка[/]");

        // Перебираем записи времени в порядке возрастания даты.
        // Сначала отображаются самые ранние записи.
        foreach (var entry in task.TimeLog.OrderBy(e => e.Date))

            // Добавляем информацию о текущей записи в таблицу.
            // Дата форматируется, минуты переводятся в часы и минуты,
            // а пользовательская заметка экранируется перед выводом.
            log.AddRow(entry.Date.ToString("dd.MM.yyyy"), Fmt(entry.Minutes), Theme.E(entry.Note));

        // Выводим готовую таблицу записей времени.
        AnsiConsole.Write(log);
    }

    /// <summary>
    /// Отображает таблицу участников команды проекта.
    /// Для каждого участника показывает аватарку, ID, имя, роль,
    /// количество назначенных задач, количество выполненных задач
    /// и суммарное затраченное время.
    /// </summary>
    /// <param name="project">Проект, команда которого отображается.</param>
    public static void TeamTable(Project project)
    {
        // Проверяем, имеются ли участники в команде проекта.
        if (project.Team.Count == 0)
        {
            // Если команда пустая, выводим информационную подсказку.
            Theme.Hint("Команда пока пустая. Добавь первого участника в меню 'Команда'.");

            // Завершаем метод, поскольку отображать таблицу нечего.
            return;
        }

        // Создаём таблицу участников команды с общим количеством записей в подписи.
        var table = NewTable("Наша команда", $"| участников: {project.Team.Count} |");

        // Добавляем заголовки столбцов.
        // Первый столбец предназначен для текстовой аватарки участника.
        foreach (var header in new[] { "", "ID", "Имя", "Роль", "Задач", "Готово", "Время" })
            table.AddColumn(new TableColumn($"[bold {Theme.Pink}]{header}[/]"));

        // Перебираем всех участников команды проекта.
        foreach (var m in project.Team)
        {
            // Отбираем задачи, назначенные текущему участнику.
            // AssigneeId связывает задачу с конкретным участником команды.
            // ToList сохраняет результат фильтрации в отдельный список.
            var mine = project.Tasks.Where(t => t.AssigneeId == m.Id).ToList();

            // Выбираем аватарку на основании ID участника.
            // Приведение ID к long позволяет безопаснее выполнить Math.Abs
            // даже для минимального значения типа int.
            // Остаток от деления на длину массива гарантирует допустимый индекс.
            var avatar = Avatars[(int)(Math.Abs((long)m.Id) % Avatars.Length)];

            // Добавляем строку с информацией об участнике команды.
            table.AddRow(
                // Отображаем выбранную аватарку с цветовым оформлением.
                $"[{Theme.Lavender}]{Theme.E(avatar)}[/]",

                // Выводим уникальный идентификатор участника.
                $"{m.Id}",

                // Выводим имя участника.
                Theme.E(m.Name),

                // Выводим роль участника в проекте.
                Theme.E(m.Role),

                // Показываем общее количество назначенных участнику задач.
                $"{mine.Count}",

                // С помощью Count подсчитываем задачи, для которых IsDone равен true.
                $"{mine.Count(t => t.IsDone)}",

                // Суммируем затраченное участником время по всем его задачам.
                // Fmt преобразует итоговое количество минут в читаемый формат.
                Fmt(mine.Sum(t => t.SpentMinutes)));
        }

        // Выводим таблицу команды по центру терминала.
        AnsiConsole.Write(new Align(table, HorizontalAlignment.Center));
    }
