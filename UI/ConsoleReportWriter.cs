// Подключаем модели проекта: ProjectReport и связанные с ним типы данных.
using KawaiiTasks.Models;

// Подключаем сервисы, в частности ReportService, который рассчитывает уровень проекта.
using KawaiiTasks.Services;

// Подключаем библиотеку Spectre.Console для создания цветного и форматированного вывода в терминале.
using Spectre.Console;

// Объявляем пространство имён пользовательского интерфейса проекта.
namespace KawaiiTasks.UI;

/// <summary>
/// Красивый отчёт о проекте прямо в консоли — как разворот дневника.
/// Данные уже посчитаны в ProjectReport, здесь только расположение на экране. Каждый AnsiConsole.Write
/// дописывает блок в конец вывода терминала (экран при этом не очищается и прокручивается как обычный текст).
/// </summary>
public class ConsoleReportWriter : IReportWriter
{
    // Название способа формирования отчёта.
    // Свойство используется при выборе формата отчёта в других частях приложения.
    public string Name => "Консоль";

    // Формирует и выводит отчёт о проекте в консоль.
    // Параметр r содержит заранее подготовленные данные отчёта.
    // Возвращает null, поскольку результат не сохраняется в отдельный файл.
    public string? Write(ProjectReport r)
    {
        // Получаем исходный проект из объекта отчёта.
        // Это позволяет обращаться к его названию и информации об исполнителях задач.
        var project = r.Project;

        // Выводим декоративную спираль в соответствии с оформлением приложения.
        Theme.Spiral();

        // Добавляем декоративные символы-звёздочки.
        Theme.Sparkles();

        // Выводим заголовок отчёта с названием проекта.
        // Theme.Pink определяет цвет оформления заголовка.
        Theme.Ribbon($"ОТЧЁТ: {project.Name}", Theme.Pink);

        // Создаём строку с датой формирования отчёта и выравниваем её по центру.
        // Theme.Today() получает текущую дату, а Theme.E() экранирует текст
        // для безопасного отображения внутри разметки Spectre.Console.
        // Markup интерпретирует специальные цветовые теги, а Align задаёт выравнивание.
        AnsiConsole.Write(new Align(
            new Markup($"[{Theme.Cocoa}]> запись от {Theme.E(Theme.Today())} >[/]"), HorizontalAlignment.Center));

        // Добавляем пустую строку для визуального разделения заголовка и основной информации.
        AnsiConsole.WriteLine();

        // Определяем уровень проекта и его текстовое название на основании количества конфеток.
        // Метод ReportService.Level возвращает два значения, которые записываются в кортеж.
        var (level, levelName) = ReportService.Level(r.CandyPoints);

        // Создаём сетку Grid для отображения краткой сводки.
        // В ней будет две колонки: название показателя и его значение.
        var grid = new Grid();

        // Добавляем первую колонку.
        // NoWrap = true запрещает переносить текст названия показателя на следующую строку.
        grid.AddColumn(new GridColumn { NoWrap = true });

        // Добавляем вторую колонку для значений показателей.
        grid.AddColumn();

        // Локальная функция Row добавляет одну строку в таблицу сводки.
        // key — название показателя, value — его значение.
        // Локальная функция объявлена внутри Write, поэтому доступна только в этом методе.
        void Row(string key, string value) =>
            grid.AddRow(new Markup($"[{Theme.Lavender}]{Theme.E(key)}[/]   "), new Markup(value));

        // Задаём ширину индикатора прогресса в символах.
        const int barWidth = 24;

        // Вычисляем количество заполненных символов индикатора.
        // Percent — процент выполнения проекта.
        // Деление на 100 переводит процент в долю, умножение на barWidth
        // определяет количество символов, соответствующее текущему прогрессу.
        // Math.Round округляет результат, а Math.Clamp ограничивает его диапазоном от 0 до barWidth.
        var filled = Math.Clamp((int)Math.Round(r.Percent / 100.0 * barWidth), 0, barWidth);

        // Формируем строку прогресс-бара.
        // Заполненная часть отображается символами '#', незаполненная — символами '-'.
        // Цветовые теги Spectre.Console позволяют отдельно оформить рамку и заполнение.
        var bar = $"[{Theme.Cocoa}]|[/][{Theme.Mint}]{new string('#', filled)}[/][grey]{new string('-', barWidth - filled)}[/][{Theme.Cocoa}]|[/]";

        // Добавляем общее количество задач в проекте.
        Row("> Всего задач", $"{r.Total}");

        // Добавляем количество выполненных задач и процент выполнения проекта.
        // Формат 0 округляет процент до целого числа при отображении.
        Row("* Выполнено", $"{r.Done} ({r.Percent:0}%)");

        // Добавляем сформированный индикатор выполнения проекта.
        Row("Прогресс", bar);

        // Показываем количество просроченных задач.
        // Если список Overdue не пустой, число выделяется цветом Theme.Berry.
        // Если просроченных задач нет, выводится обычный ноль.
        Row("! Просрочено", r.Overdue.Count > 0 ? $"[{Theme.Berry}]{r.Overdue.Count}[/]" : "0");

        // Показываем количество задач, у которых отсутствует назначенный исполнитель.
        Row("Без исполнителя", $"{r.Unassigned}");

        // Выводим общее затраченное время.
        // Views.Fmt преобразует количество минут в удобный для чтения формат.
        Row("Затрачено времени", Views.Fmt(r.TotalMinutes));

        // Показываем накопленные конфетки и текущий уровень проекта.
        // Theme.E экранирует текстовое название уровня перед вставкой в разметку.
        Row("<> Конфетки", $"{r.CandyPoints} | уровень {level}: {Theme.E(levelName)}");

        // Добавляем дату и время формирования отчёта.
        // Формат dd.MM.yyyy HH:mm задаёт день, месяц, год, часы и минуты.
        Row("[#] Сформирован", r.GeneratedAt.ToString("dd.MM.yyyy HH:mm"));

        // Выводим декоративную ленту перед основной таблицей.
        Theme.Tape(Theme.Sky);

        // Оформляем сетку как страницу с заголовком «СВОДКА» и выводим её в консоль.
        // Theme.Page отвечает за единый визуальный стиль страниц приложения.
        AnsiConsole.Write(Theme.Page(grid, "СВОДКА", Theme.Pink));

        // Добавляем пустую строку после таблицы.
        AnsiConsole.WriteLine();

        // Диаграммы имеют смысл только тогда, когда в проекте есть хотя бы одна задача.
        if (r.Total > 0)
        {
            // Создаём столбчатую диаграмму распределения задач по статусам.
            var states = new BarChart()
                // Задаём ширину диаграммы относительно текущей ширины терминала.
                // Math.Max гарантирует минимальную ширину в 20 символов.
                .Width(Math.Max(20, Theme.Width - 8))

                // Добавляем заголовок диаграммы с декоративным оформлением.
                .Label($"[{Theme.Pink}]* Задачи по статусам *[/]")

                // Выравниваем подписи значений по центру.
                .CenterLabel();

            // Перебираем пары из словаря ByState.
            // Key содержит статус задачи, Value — количество задач с этим статусом.
            foreach (var pair in r.ByState)
                // Добавляем столбец диаграммы.
                // pair.Key.Text() преобразует статус в отображаемое название.
                // Theme.StateHex возвращает цвет, связанный с конкретным статусом.
                // Theme.FromHex преобразует цвет из HEX-формата в объект Color.
                states.AddItem(pair.Key.Text(), pair.Value, Theme.FromHex(Theme.StateHex(pair.Key)));

            // Выводим диаграмму по центру терминала.
            AnsiConsole.Write(new Align(states, HorizontalAlignment.Center));

            // Отделяем следующую диаграмму пустой строкой.
            AnsiConsole.WriteLine();

            // Создаём диаграмму распределения задач по приоритетам.
            var priorities = new BarChart()
                // Устанавливаем ширину с учётом доступного пространства терминала.
                .Width(Math.Max(20, Theme.Width - 8))

                // Добавляем заголовок диаграммы.
                .Label($"[{Theme.Pink}]* Задачи по приоритетам *[/]")

                // Центрируем подписи значений.
                .CenterLabel();

            // Перебираем пары из словаря ByPriority.
            // Key содержит приоритет, Value — количество задач с этим приоритетом.
            foreach (var pair in r.ByPriority)
                // Добавляем столбец с названием приоритета, его количеством и соответствующим цветом.
                priorities.AddItem(pair.Key.Text(), pair.Value, Theme.FromHex(Theme.PriorityHex(pair.Key)));

            // Выводим диаграмму приоритетов по центру терминала.
            AnsiConsole.Write(new Align(priorities, HorizontalAlignment.Center));

            // Добавляем пустую строку после диаграммы.
            AnsiConsole.WriteLine();
        }

        // Проверяем, есть ли в отчёте участники проекта.
        // Если список пустой, таблица команды не создаётся.
        if (r.Members.Count > 0)
        {
            // Создаём таблицу участников проекта.
            var table = new Table
            {
                // Используем ASCII-рамку, состоящую из стандартных символов.
                // Это помогает сохранить совместимость с разными терминалами.
                Border = TableBorder.Ascii,

                // Назначаем цвет рамки таблицы.
                BorderStyle = new Style(Theme.LavenderC),

                // Включаем горизонтальные разделители между строками.
                ShowRowSeparators = true
            };

            // Перебираем названия столбцов таблицы.
            // Каждый заголовок получает жирное начертание и розовый цвет.
            foreach (var header in new[] { "Участник", "Роль", "Задач", "Готово", "Время" })
                table.AddColumn(new TableColumn($"[bold {Theme.Pink}]{header}[/]"));

            // Перебираем участников, подготовленных в отчёте.
            foreach (var m in r.Members)
                // Добавляем строку с информацией об участнике:
                // имя, роль, количество назначенных задач, выполненные задачи и затраченное время.
                // Theme.E экранирует пользовательский текст для разметки Spectre.Console.
                // Views.Fmt преобразует минуты в читаемый формат.
                table.AddRow(Theme.E(m.Name), Theme.E(m.Role), $"{m.Assigned}", $"{m.Done}", Views.Fmt(m.Minutes));

            // Оформляем таблицу как отдельную страницу с заголовком «КОМАНДА».
            // Последний аргумент false передаётся в Theme.Page без изменения исходного поведения.
            AnsiConsole.Write(Theme.Page(table, "КОМАНДА", Theme.Lavender, false));
        }

        // Проверяем, имеются ли просроченные задачи.
        if (r.Overdue.Count > 0)
        {
            // Добавляем пустую строку перед отдельным блоком просроченных задач.
            AnsiConsole.WriteLine();

            // Выводим заголовок блока с использованием цвета Theme.Berry.
            AnsiConsole.MarkupLine($"[{Theme.Berry}]+- ! Просроченные задачи -+[/]");

            // Перебираем все просроченные задачи.
            foreach (var t in r.Overdue)
                // Выводим идентификатор, название, срок выполнения и имя исполнителя.
                // Views.Date форматирует дату, а project.AssigneeName(t) получает имя исполнителя задачи.
                AnsiConsole.MarkupLine($"[{Theme.Berry}]|[/] x #{t.Id} {Theme.E(t.Title)} - срок {Views.Date(t.Deadline)}, {Theme.E(project.AssigneeName(t))}");

            // Выводим нижнюю границу декоративного блока.
            AnsiConsole.MarkupLine($"[{Theme.Berry}]+-------------------------+[/]");
        }

        // Проверяем, есть ли задачи, отсортированные по затраченному времени.
        if (r.TopByTime.Count > 0)
        {
            // Отделяем блок от предыдущего содержимого пустой строкой.
            AnsiConsole.WriteLine();

            // Выводим заголовок списка задач с наибольшими затратами времени.
            AnsiConsole.MarkupLine($"[{Theme.Lavender}]+- Больше всего времени ушло на -+[/]");

            // Перебираем задачи, включённые в список TopByTime.
            foreach (var t in r.TopByTime)
                // Выводим идентификатор задачи, её название и затраченное время.
                AnsiConsole.MarkupLine($"[{Theme.Lavender}]|[/] * #{t.Id} {Theme.E(t.Title)} - {Views.Fmt(t.SpentMinutes)}");

            // Завершаем декоративный блок нижней границей.
            AnsiConsole.MarkupLine($"[{Theme.Lavender}]+--------------------------------+[/]");
        }

        // Добавляем пустую строку перед завершением отчёта.
        AnsiConsole.WriteLine();

        // Повторно выводим декоративные символы-звёздочки в конце страницы.
        Theme.Sparkles();

        // Создаём заключительную надпись с ASCII-рисунком и выравниваем её по центру.
        // Markup позволяет использовать цветовые теги Spectre.Console.
      
        AnsiConsole.Write(new Align(
            new Markup($"[{Theme.Pink}](\\_/)  конец странички  *\n(^.^)/\n(\")_(\")[/]"),
            HorizontalAlignment.Center));
        // Возвращаем null, поскольку отчёт выведен непосредственно в консоль
        // и отдельный путь к сохранённому файлу отсутствует.
        return null;
    }
}