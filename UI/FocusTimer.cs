// Подключаем пространство имён System.Diagnostics.
// Оно содержит класс Stopwatch, который используется для точного измерения прошедшего времени.
using System.Diagnostics;

// Подключаем Spectre.Console.
// Библиотека используется для динамического отображения таймера, цветов, сеток и других элементов интерфейса.
using Spectre.Console;

namespace KawaiiTasks.UI;

/// <summary>
/// Таймер для отслеживания времени работы над выбранной задачей.
/// Пользователь может остановить отсчёт нажатием любой клавиши.
/// 
/// Для отображения используется AnsiConsole.Live, который позволяет обновлять содержимое терминала
/// без постоянного добавления новых строк.
/// 
/// Основной цикл выполняется с интервалом около 250 миллисекунд.
/// Между обновлениями интерфейса программа проверяет наличие нажатой клавиши
/// через Console.KeyAvailable, не блокируя выполнение в ожидании ввода.
/// </summary>
public static class FocusTimer
{
    // Продолжительность одного рабочего цикла по методу Pomodoro — 25 минут.
    // Используется для расчёта прогресса и количества завершённых циклов.
    private const int CycleMinutes = 25;

    // Массив ASCII-рисунков котика для анимации.
    // Каждый элемент представляет собой отдельный кадр.
    // При обновлении таймера кадры последовательно сменяют друг друга,
    // создавая простую анимацию.
    private static readonly string[] Cat =
    {
        // Первый кадр: котик с закрытыми глазами.
        "  /\\_/\\\n ( -.- )\n  >   <",

        // Второй кадр: котик с открытыми глазами.
        "  /\\_/\\\n ( o.o )\n  >   <",

        // Третий кадр: повтор первого положения.
        "  /\\_/\\\n ( -.- )\n  >   <",

        // Четвёртый кадр: повтор второго положения.
        "  /\\_/\\\n ( o.o )\n  >   <"
    };

    /// <summary>
    /// Запускает таймер для выбранной задачи.
    /// 
    /// Во время работы отображается прошедшее время, название задачи,
    /// анимация котика и полоса прогресса текущего 25-минутного цикла.
    /// Любая клавиша останавливает таймер.
    /// 
    /// Возвращает количество затраченных минут.
    /// Если прошло меньше 30 секунд или ввод/вывод перенаправлены,
    /// возвращает 0.
    /// </summary>
    public static int Run(string taskTitle)
    {
        // Создаём и сразу запускаем секундомер.
        // Stopwatch измеряет реальное прошедшее время,
        // а не количество выполненных итераций цикла.
        //
        // Это важно, поскольку отрисовка интерфейса и работа компьютера
        // могут занимать разное количество времени.
        var watch = Stopwatch.StartNew();

        // Проверяем, подключён ли настоящий терминал.
        //
        // Console.IsInputRedirected возвращает true, если ввод перенаправлен,
        // например, из файла или другого процесса.
        //
        // Console.IsOutputRedirected возвращает true, если вывод направлен
        // не непосредственно в терминал.
        //
        // Интерактивная анимация требует обычного терминала,
        // поэтому при перенаправлении ввода или вывода пропускаем её.
        if (!Console.IsInputRedirected && !Console.IsOutputRedirected)
        {
            // Создаём динамическую область отображения Spectre.Console.
            // Live позволяет многократно обновлять один и тот же участок терминала.
            //
            // Markup(" ") задаёт начальное содержимое области.
            // AutoClear(true) очищает область после завершения анимации.
            //
            // Start запускает отображение и передаёт управление
            // в функцию обратного вызова, где выполняется основной цикл таймера.
            AnsiConsole.Live(new Markup(" "))
                .AutoClear(true)
                .Start(ctx =>
                {
                    // Счётчик кадров анимации.
                    // Увеличивается после каждого обновления интерфейса.
                    // Используется для смены изображения котика и количества точек.
                    var tick = 0;

                    // Выполняем цикл до тех пор, пока пользователь не нажмёт клавишу.
                    // KeyPressed проверяет буфер клавиатуры без ожидания ввода.
                    while (!KeyPressed())
                    {
                        // Выбираем текущий кадр котика.
                        //
                        // tick / 2 замедляет смену кадров:
                        // один кадр отображается в течение двух итераций.
                        //
                        // Оператор % Cat.Length возвращает индекс в пределах массива,
                        // благодаря чему анимация начинается заново после последнего кадра.
                        var cat = Cat[(tick / 2) % Cat.Length];

                        // Создаём анимированное окончание надписи "работаем".
                        // tick % 4 позволяет последовательно получить:
                        // "", ".", "..", "...".
                        var dots = new string('.', tick % 4);

                        // Получаем прошедшее время из секундомера.
                        // Формат hh:mm:ss отображает часы, минуты и секунды.
                        // Обратные слеши экранируют двоеточия в строке формата TimeSpan.
                        var elapsed = watch.Elapsed.ToString(@"hh\:mm\:ss");

                        // Задаём ширину полосы прогресса в символах.
                        // Это количество позиций, которые могут быть заполнены.
                        const int barWidth = 28;

                        // Вычисляем прогресс внутри текущего 25-минутного цикла.
                        //
                        // TotalMinutes — общее количество прошедших минут.
                        // % CycleMinutes оставляет только время текущего цикла.
                        // Деление на CycleMinutes переводит результат в долю от 0 до 1.
                        //
                        // Например, после 12,5 минут значение будет примерно 0,5.
                        var cycle = watch.Elapsed.TotalMinutes % CycleMinutes / CycleMinutes;

                        // Определяем количество заполненных символов полосы.
                        //
                        // Умножаем долю прогресса на ширину полосы.
                        // Math.Round округляет результат до ближайшего целого.
                        // Math.Clamp ограничивает значение диапазоном от 0 до barWidth.
                        var filled = Math.Clamp(
                            (int)Math.Round(cycle * barWidth),
                            0,
                            barWidth);

                        // Определяем количество полностью завершённых 25-минутных циклов.
                        // Приведение к int отбрасывает дробную часть результата.
                        var rounds = (int)(watch.Elapsed.TotalMinutes / CycleMinutes);

                        // Формируем визуальную полосу прогресса.
                        //
                        // Символы # показывают заполненную часть.
                        // Символы - показывают оставшуюся часть.
                        // Theme.Cocoa, Theme.Lemon и grey задают цвета отдельных элементов.
                        //
                        // new string('#', filled) создаёт строку из заполненных символов.
                        // barWidth - filled определяет количество оставшихся символов.
                        var bar =
                            $"[{Theme.Cocoa}]|[/]" +
                            $"[{Theme.Lemon}]{new string('#', filled)}[/]" +
                            $"[grey]{new string('-', barWidth - filled)}[/]" +
                            $"[{Theme.Cocoa}]|[/]";

                        // Создаём строку с символами-звёздочками,
                        // количество которых зависит от завершённых циклов.
                        //
                        // Math.Min ограничивает количество звёзд десятью,
                        // чтобы строка не становилась слишком длинной.
                        // Если ещё не завершён ни один цикл, отображается дефис.
                        var stars = rounds > 0
                            ? new string('*', Math.Min(rounds, 10))
                            : "-";

                        // Создаём цветной элемент с изображением котика.
                        // Theme.E экранирует ASCII-рисунок от интерпретации как разметки.
                        // После изображения добавляются пробелы для визуального разделения.
                        var art = new Markup($"[{Theme.Pink}]{Theme.E(cat)}[/]   ");

                        // Формируем информационную часть таймера.
                        // В ней отображаются прошедшее время, название задачи,
                        // полоса прогресса и подсказка об остановке.
                        var info = new Markup(
                            // Выводим прошедшее время жирным лимонным цветом.
                            $"[bold {Theme.Lemon}]{elapsed}[/]\n" +

                            // Выводим название текущей задачи серым цветом.
                            // Views.Short ограничивает длину текста 50 символами,
                            // чтобы длинное название не нарушало расположение элементов.
                            $"[grey]{Theme.E(Views.Short(taskTitle, 50))}[/]\n" +

                            // Выводим полосу прогресса и количество завершённых циклов.
                            $"{bar}  [{Theme.Cocoa}]{stars}[/]\n" +

                            // Выводим анимированную надпись и инструкцию по остановке.
                            $"[{Theme.Lavender}]работаем{dots}[/]  [grey](любая клавиша - стоп)[/]"
                        );

                        // Создаём сетку для горизонтального расположения изображения и информации.
                        // Первый столбец предназначен для котика, второй — для текста таймера.
                        var grid = new Grid();

                        // Добавляем первый столбец.
                        // NoWrap запрещает переносить изображение на дополнительные строки.
                        grid.AddColumn(new GridColumn { NoWrap = true });

                        // Добавляем второй столбец для информационного блока.
                        grid.AddColumn();

                        // Объединяем изображение и информацию в одну строку.
                        // Котик располагается слева, данные таймера — справа.
                        grid.AddRow(art, info);

                        // Создаём вертикальную последовательность отображаемых элементов.
                        // Rows позволяет разместить несколько компонентов один под другим.
                        var content = new Rows(

                            // Верхний декоративный разделитель.
                            // Align с HorizontalAlignment.Center располагает его по центру.
                            new Align(
                                new Markup($"[{Theme.Pink}]* * * * * * * * * *[/]"),
                                HorizontalAlignment.Center),

                            // Добавляем основную сетку с котиком и информацией о таймере.
                            grid,

                            // Добавляем нижний декоративный разделитель.
                            // Он оформляет блок симметрично относительно верхней части.
                            new Align(
                                new Markup($"[{Theme.Pink}]* * * * * * * * * *[/]"),
                                HorizontalAlignment.Center)
                        );

                        // Обновляем содержимое динамической области.
                        //
                        // Theme.Page оформляет содержимое в общем стиле приложения:
                        // content — элементы таймера;
                        // "ФОКУС-ТАЙМЕР" — заголовок;
                        // Theme.Pink — основной цвет;
                        // true — дополнительный параметр оформления;
                        // Padding(2, 0) — внутренние горизонтальные и вертикальные отступы.
                        //
                        // UpdateTarget заменяет содержимое предыдущего кадра новым.
                        ctx.UpdateTarget(
                            Theme.Page(
                                content,
                                "ФОКУС-ТАЙМЕР",
                                Theme.Pink,
                                true,
                                new Padding(2, 0)));

                        // Принудительно обновляем изображение в терминале.
                        // Без Refresh новое содержимое могло бы не отобразиться сразу.
                        ctx.Refresh();

                        // Приостанавливаем выполнение на 250 миллисекунд.
                        // Это ограничивает частоту обновления примерно четырьмя кадрами в секунду.
                        // Такая частота обеспечивает плавное отображение анимации
                        // без излишней нагрузки на процессор.
                        Thread.Sleep(250);

                        // Увеличиваем счётчик кадров.
                        // Он используется для следующего изображения котика и анимированных точек.
                        tick++;
                    }
                });
        }

        // Останавливаем секундомер после выхода из интерактивного режима.
        // После этого значение Elapsed перестаёт увеличиваться.
        watch.Stop();

        // Проверяем продолжительность сессии.
        // Если пользователь работал меньше 30 секунд,
        // такая сессия не записывается в статистику времени.
        // Это позволяет не засорять журнал короткими случайными запусками.
        if (watch.Elapsed.TotalSeconds < 30)
            return 0;

        // Возвращаем продолжительность работы в целых минутах.
        //
        // TotalMinutes содержит общее время в минутах с дробной частью.
        // Math.Round округляет результат до ближайшего целого.
        // MidpointRounding.AwayFromZero задаёт округление половины в большую сторону.
        //
        // Math.Max(1, ...) гарантирует, что при продолжительности от 30 секунд
        // результатом будет минимум одна минута.
        return Math.Max(
            1,
            (int)Math.Round(
                watch.Elapsed.TotalMinutes,
                MidpointRounding.AwayFromZero));
    }

    /// <summary>
    /// Проверяет, была ли нажата клавиша, не останавливая программу в ожидании ввода.
    /// 
    /// Console.KeyAvailable проверяет наличие нажатия в буфере клавиатуры.
    /// Console.ReadKey(true) считывает нажатие и удаляет его из буфера.
    /// Параметр true запрещает отображать нажатый символ в терминале.
    /// 
    /// Если клавиатура недоступна, метод возвращает true,
    /// чтобы таймер не продолжал бесконечно работать без возможности остановки.
    /// </summary>
    private static bool KeyPressed()
    {
        // Используем try-catch, поскольку работа с консолью
        // может завершиться ошибкой при перенаправленном или недоступном вводе.
        try
        {
            // Проверяем, есть ли непрочитанное нажатие клавиши.
            // Если буфер пуст, сразу возвращаем false.
            // Программа не ожидает действий пользователя и продолжает работу таймера.
            if (!Console.KeyAvailable)
                return false;

            // Считываем нажатую клавишу из буфера.
            // true означает, что символ не будет напечатан в терминале.
            Console.ReadKey(true);

            // Если клавиша была успешно считана,
            // возвращаем true и тем самым завершаем основной цикл таймера.
            return true;
        }

        // Обрабатываем ошибки, которые могут возникнуть при обращении к консоли.
        // Фильтр when позволяет перехватывать только ожидаемые типы исключений:
        // InvalidOperationException — операция невозможна в текущем состоянии консоли;
        // IOException — ошибка ввода-вывода;
        // NotSupportedException — операция не поддерживается текущей средой.
        catch (Exception ex) when (
            ex is InvalidOperationException or
            IOException or
            NotSupportedException)
        {
            // Если проверить клавиатуру не удалось,
            // считаем это сигналом к остановке таймера.
            // Это безопаснее, чем продолжать бесконечный цикл без возможности остановки.
            return true;
        }
    }
}