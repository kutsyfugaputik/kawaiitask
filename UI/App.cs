        var roles = new[] { "Разработчик", "Тестировщик", "Аналитик", "Дизайнер", "Тимлид", "> Другая роль" };

        // Предлагаем пользователю выбрать роль.
        var role = Input.Pick("Роль в проекте", roles, s => s);

