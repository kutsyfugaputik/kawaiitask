            {
                // Запрашиваем время вручную.
                // Поддерживаемый формат описан в подсказке: например, 1.5 часа или 1:30.
                var minutes = Input.AskDuration("Сколько времени? (часы: 1.5 или 1:30)");

                // Запрашиваем необязательную заметку о выполненной работе.
                var note = Input.AskOptional("Что делал(а)? (Enter - без заметки)", 100);

                // Сохраняем введённое время и заметку через сервис.
                _svc.LogTime(task, minutes, note);

                // Подтверждаем добавление времени.
                Theme.Ok($"Записано {Views.Fmt(minutes)} в задачу #{task.Id}");

                break;
            }
        }
    }

