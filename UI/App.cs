
using KawaiiTasks.Models; // Подключаем модели данных: Project, TaskItem, Member и другие сущности.
using KawaiiTasks.Services; // Подключаем сервисы бизнес-логики, фильтрации, отчётов и управления проектами.
using Spectre.Console; // Подключаем библиотеку для форматированного вывода информации в консоль.

namespace KawaiiTasks.UI; // Все компоненты пользовательского интерфейса находятся в пространстве имён UI.

/// <summary>
/// Представляет один пункт интерактивного меню.
/// Хранит отображаемую подпись, выполняемое действие и признак необходимости паузы после него.
/// </summary>
/// <param name="Label">Текст, который пользователь видит в меню.</param>
/// <param name="Run">Действие, выполняемое при выборе пункта. null означает возврат или выход.</param>
/// <param name="Pause">Нужно ли приостанавливать экран после выполнения действия.</param>
public sealed record MenuItem(string Label, Action? Run, bool Pause = true);

/// <summary>
/// Главный класс пользовательского интерфейса приложения KawaiiTasks.
/// Отвечает за интерактивный сценарий: главное меню, меню проектов,
/// управление задачами, командой, поиск и формирование отчётов.
///
/// Основной принцип работы: показать экран -> получить выбор пользователя ->
/// выполнить действие -> вернуться к меню.
///
/// Данные приложения хранятся и изменяются через ProjectService.
/// Класс App отвечает за взаимодействие с пользователем и не реализует хранение данных самостоятельно.
/// </summary>
public class App
{
    // Сервис управления проектами.
    // Через него интерфейс получает список проектов и выполняет операции изменения данных.
    // readonly запрещает заменить ссылку на сервис после создания объекта App.
    private readonly ProjectService _svc;

    // Необязательное предупреждение, полученное при запуске приложения.
    // Например, здесь может находиться сообщение о проблеме при загрузке данных.
    private readonly string? _warning;

    /// <summary>
    /// Создаёт объект пользовательского интерфейса и сохраняет необходимые зависимости.
    /// </summary>
    /// <param name="service">Сервис для работы с проектами и их данными.</param>
    /// <param name="warning">Необязательное предупреждение, которое нужно показать пользователю.</param>
    public App(ProjectService service, string? warning)
    {
        // Сохраняем переданный сервис для последующего использования во всех меню.
        _svc = service;

        // Сохраняем предупреждение, чтобы показать его при запуске.
        _warning = warning;
    }

    /// <summary>
    /// Запускает пользовательский интерфейс приложения.
    /// Подготавливает оформление терминала, показывает вступительную анимацию,
    /// выводит предупреждение при его наличии и запускает главное меню.
    /// </summary>
    public void Run()
    {
        try
        {
            // Применяем оформление терминала, если текущая консоль поддерживает изменение цветов.
            Theme.ApplyPaper();

            // Показываем вступительную анимацию приложения.
            UiAnimation.Intro();

            // Если при загрузке данных возникло предупреждение, показываем его пользователю.
            if (_warning is not null)
            {
                // Очищаем экран и отображаем стандартный заголовок приложения.
                Theme.Banner();

                // Выводим предупреждение с помощью оформления для ошибок.
                Theme.Fail(_warning);

                // Приостанавливаем выполнение, чтобы пользователь успел прочитать сообщение.
                Theme.Pause();
            }

            // Запускаем основной цикл взаимодействия с пользователем.
            // Метод завершится после выбора выхода или возврата из главного меню.
            MainLoop();

            // После завершения главного меню показываем финальное сообщение.
            Goodbye();
        }
        finally
        {
            // Блок finally выполняется независимо от того, завершился ли код успешно или возникло исключение.
            // Возвращаем стандартное оформление терминала, чтобы пользователь не оставался с изменёнными цветами.
            Theme.ResetPaper();
        }
    }

    // ------------------------------------------------------------ общие помощники

    /// <summary>
    /// Выполняет переданное действие и обрабатывает возникающие исключения.
    /// Вместо аварийного завершения приложения выводит пользователю понятное сообщение.
    /// Исключение NavigationBackException передаётся выше, поскольку оно используется для навигации.
    /// </summary>
    /// <param name="action">Действие, которое требуется выполнить.</param>
    /// <param name="pause">Нужно ли приостановить экран после выполнения или обработки ошибки.</param>
    private static void Guard(Action action, bool pause = true)
    {
        try
        {
            // Выполняем переданное действие.
            // Это может быть создание проекта, изменение задачи или другой пункт меню.
            action();
        }
        catch (NavigationBackException)
        {
            // Это специальное исключение навигации, а не ошибка приложения.
            // throw без параметров повторно выбрасывает исходное исключение с сохранением стека вызовов.
            // Внешний цикл меню перехватит его и выполнит возврат на предыдущий экран.
            throw;
        }
        catch (KawaiiException ex)
        {
            // Обрабатываем ошибки предметной области приложения.
            // Например, нарушение правил создания проекта или изменения задачи.
            Theme.Fail(ex.Message);

            // После ошибки обязательно даём пользователю время прочитать сообщение.
            pause = true;
        }
        catch (IOException ex)
        {
            // Обрабатываем ошибки ввода-вывода при работе с файлами.
            // Например, невозможность прочитать или сохранить данные.
            Theme.Fail($"Не получилось поработать с файлом: {ex.Message}");

            // В случае ошибки записи или чтения также приостанавливаем экран.
            pause = true;
        }
        catch (UnauthorizedAccessException ex)
        {
            // Обрабатываем ситуации, когда приложению не хватает прав доступа к файлу или папке.
            Theme.Fail($"Нет доступа к файлу: {ex.Message}");

            // Пользователь должен успеть прочитать сообщение о проблеме с доступом.
            pause = true;
        }
        catch (Exception ex)
        {
            // Последний обработчик перехватывает остальные непредусмотренные исключения.
            // Он предотвращает неконтролируемое завершение пользовательского сценария.
            Theme.Fail($"Что-то пошло не так: {ex.Message}");

            // После непредвиденной ошибки также делаем паузу.
            pause = true;
        }

        // Если пауза необходима, ждём действия пользователя перед переходом к следующему экрану.
        // При успешном выполнении учитывается исходное значение параметра pause.
        if (pause) Theme.Pause();
    }

    /// <summary>
    /// Показывает список задач и позволяет пользователю выбрать одну из них.
    /// Если задач в проекте нет, возвращает null.
    /// </summary>
    /// <param name="project">Проект, из которого выбирается задача.</param>
    /// <param name="title">Заголовок меню выбора.</param>
    /// <returns>Выбранная задача или null, если список пуст.</returns>
    private static TaskItem? PickTask(Project project, string title)
    {
        // Проверяем, есть ли в проекте хотя бы одна задача.
        if (project.Tasks.Count == 0)
        {
            // Сообщаем пользователю, почему выбрать задачу невозможно.
            Theme.Hint("Задач пока нет - сначала добавь первую *");

            // Возвращаем null, чтобы вызывающий метод мог завершить операцию без ошибки.
            return null;
        }

        // Создаём список пар: объект задачи и текст, который будет показан в меню.
        // Tuple позволяет хранить значение и его отображаемую подпись вместе.
        var choices = new List<(TaskItem? Task, string Label)>();

        // Перебираем задачи в порядке возрастания идентификатора.
        // Это делает список выбора предсказуемым для пользователя.
        foreach (var t in project.Tasks.OrderBy(t => t.Id))

            // Добавляем задачу и формируем её краткое представление:
            // ID, сокращённое название и текстовое обозначение статуса.
            choices.Add((t, $"#{t.Id} {Views.Short(t.Title, 45)} - {t.State.Text()}"));

        // Показываем меню выбора.
        // В качестве подписи используется Label, а наружу возвращается связанный объект Task.
        // Свойство Task извлекает выбранную задачу из кортежа.
        return Input.Pick(title, choices, c => c.Label).Task;
    }

    /// <summary>
    /// Показывает список участников команды и позволяет выбрать одного из них.
    /// Первый пункт представляет отсутствие конкретного участника и возвращает null.
    /// </summary>
    /// <param name="project">Проект, участники которого отображаются.</param>
    /// <param name="noneLabel">Подпись пункта, означающего отсутствие выбора участника.</param>
    /// <returns>Выбранный участник или null.</returns>
    private static Member? PickMember(Project project, string noneLabel)
    {
        // Создаём список вариантов выбора.
        // Первый элемент содержит null и специальную подпись, например «Любой исполнитель».
        var choices = new List<(Member? Member, string Label)> { (null, noneLabel) };

        // Добавляем в список всех участников команды.
        foreach (var m in project.Team)

            // Для каждого участника показываем имя и его роль в проекте.
            choices.Add((m, $"{m.Name} - {m.Role}"));

        // Показываем меню и возвращаем объект выбранного участника.
        // Если пользователь выбрал первый пункт, результатом будет null.
        return Input.Pick("Кого выберем?", choices, c => c.Label).Member;
    }

    // ------------------------------------------------------------ главное меню

    /// <summary>
    /// Главное меню приложения.
    /// Показывает список проектов и служебные действия.
    /// Цикл продолжается до тех пор, пока пользователь не выберет выход.
    /// </summary>
    private void MainLoop()
    {
        // Бесконечный цикл позволяет возвращаться к главному меню после каждого действия.
        while (true)
        {
            // Очищаем терминал и отображаем стандартную шапку приложения.
            Theme.Banner();

            // Показываем приветствие с помощью графического компонента Mascot.
            AnsiConsole.Write(Mascot.Greeting());

            // Добавляем пустую строку для визуального разделения приветствия и меню.
            AnsiConsole.WriteLine();

            // Создаём коллекцию пунктов главного меню.
            var items = new List<MenuItem>();

            // Получаем копию списка проектов через ToList().
            // Это позволяет безопасно перебирать текущий набор элементов при построении меню.
            foreach (var project in _svc.Projects.ToList())
            {
                // Сохраняем текущий проект в отдельную переменную.
                // Она используется в лямбда-выражении, которое будет выполнено позднее.
                var p = project;

                // Подсчитываем количество выполненных задач в текущем проекте.
                var done = p.Tasks.Count(t => t.IsDone);

                // Добавляем пункт меню с названием проекта и прогрессом выполнения.
                // Лямбда запускает меню выбранного проекта.
                // false означает, что после перехода внутрь проекта не требуется дополнительная пауза.
                items.Add(new MenuItem($"* {p.Name}  ({done}/{p.Tasks.Count})", () => ProjectLoop(p), false));
            }

            // Добавляем пункт создания нового проекта.
            // При выборе будет вызван метод CreateProject.
            items.Add(new MenuItem("* Создать проект", CreateProject));

            // Добавляем пункт создания демонстрационного проекта с готовыми данными.
            items.Add(new MenuItem("[*] Добавить демо-проект", AddDemo));

            // Пункт удаления показываем только тогда, когда в приложении есть проекты.
            if (_svc.Projects.Count > 0)
                items.Add(new MenuItem("x Удалить проект", DeleteProject));

            // Добавляем пункт выхода.
            // null вместо действия означает, что дополнительная операция не выполняется.
            // null вместо действия означает, что дополнительная операция не выполняется.
            items.Add(new MenuItem("(..w\\ ..)/ Выйти", null));

            // Переменная будет хранить выбранный пункт меню.
            MenuItem choice;

            try
            {
                // Показываем главное меню и получаем выбор пользователя.
                // allowBack: false отключает отдельный вариант возврата, так как здесь предусмотрен выход.
                choice = Input.Pick("Что будем делать?", items, i => i.Label, allowBack: false);
            }
            catch (NavigationBackException)
            {
                // Если механизм ввода сообщил о возврате, завершаем главное меню.
                return;
            }

            // Если действие отсутствует, пользователь выбрал пункт выхода.
            if (choice.Run is null) return;

            // Выполняем выбранное действие через общий обработчик ошибок.
            try { Guard(choice.Run, choice.Pause); }

            // Если действие инициировало навигационный возврат,
            // перехватываем его здесь и начинаем следующую итерацию главного меню.
            catch (NavigationBackException) { /* Завершаем текущий ввод и возвращаемся в главное меню. */ }
        }
    }

    /// <summary>
    /// Запрашивает название и описание нового проекта и передаёт данные сервису.
    /// </summary>
    private void CreateProject()
    {
        // Запрашиваем название проекта.
        // Максимальная длина берётся из константы сервиса ProjectService.
        var name = Input.Ask("Название проекта", ProjectService.MaxProjectName);

        // Запрашиваем необязательное описание.
        // Пустой ввод позволяет создать проект без описания.
        var description = Input.AskOptional("Короткое описание (Enter - пропустить)", ProjectService.MaxProjectDescription);

        // Показываем анимацию процесса создания проекта.
        UiAnimation.Loading("Создаём проект", 350);

        // Передаём введённые данные сервису, который проверяет их и сохраняет проект.
        var project = _svc.CreateProject(name, description);

        // Выводим сообщение об успешном создании проекта.
        Theme.Ok($"Проект '{project.Name}' создан!");
    }

    /// <summary>
    /// Создаёт демонстрационный проект с заранее подготовленными задачами и командой.
    /// </summary>
    private void AddDemo()
    {
        // Показываем анимацию подготовки демонстрационных данных.
        UiAnimation.Loading("Подготавливаем демо-проект", 350);

        // Просим сервис создать демонстрационный проект и сохранить его.
        _svc.AddDemoProject();

        // Сообщаем пользователю об успешном добавлении примера проекта.
        Theme.Ok("Демо-проект добавлен - загляни внутрь, там уже есть команда и задачи!");
    }

    /// <summary>
    /// Позволяет выбрать проект, подтвердить удаление и удалить его вместе с задачами.
    /// </summary>
    private void DeleteProject()
    {
        // Подготавливаем список вариантов выбора.
        // В каждом элементе хранятся ссылка на проект и его отображаемое название.
        var choices = new List<(Project? Project, string Label)>();

        // Добавляем все существующие проекты.
        foreach (var p in _svc.Projects)

            // В меню показываем название проекта, а в результате сохраняем сам объект.
            choices.Add((p, $"* {p.Name}"));

        // Предлагаем пользователю выбрать проект для удаления.
        var picked = Input.Pick("Какой проект удалить?", choices, c => c.Label).Project;

        // Если выбор отсутствует, прекращаем операцию.
        if (picked is null) return;

        // Запрашиваем подтверждение, поскольку удаление затрагивает весь проект и его задачи.
        if (!Input.Confirm($"Точно удалить '{picked.Name}' со всеми задачами?"))
        {
            // Сообщаем, что операция отменена.
            Theme.Hint("Ничего не удалили <3");

            // Выходим без изменения данных.
            return;
        }

        // Показываем короткую анимацию удаления.
        UiAnimation.Loading("Удаляем проект", 250);

        // Передаём выбранный проект сервису для удаления и сохранения изменений.
        _svc.DeleteProject(picked);

        // Сообщаем об успешном завершении операции.
        Theme.Ok("Проект удалён.");
    }

    // Показываем финальное сообщение и путь к файлу хранения данных.
    // Выражение-метод сокращает запись метода, состоящего из одного вызова.
    private void Goodbye() => Theme.Goodbye(_svc.StoragePath);

    // ------------------------------------------------------------ меню проекта

    /// <summary>
    /// Открывает меню выбранного проекта.
    /// Пользователь может просматривать и изменять задачи, управлять командой,
    /// выполнять поиск и формировать отчёты.
    /// </summary>
    /// <param name="p">Проект, с которым пользователь работает в текущем меню.</param>
    private void ProjectLoop(Project p)
    {
        // Цикл сохраняет меню проекта открытым после выполнения отдельной операции.
        while (true)
        {
            // Очищаем экран и показываем общую шапку приложения.
            Theme.Banner();

            // Отображаем название проекта и его основные показатели.
            Views.ProjectHeader(p);

            // Создаём список доступных действий внутри проекта.
            var items = new List<MenuItem>
            {
                // Открываем визуальную доску задач проекта.
                new("Доска задач", () => Views.Board(p, p.Tasks)),

                // Показываем все задачи в табличном представлении.
                new("> Все задачи (таблица)", () => ShowTable(p)),

                // Запускаем сценарий добавления задачи.
                new("+ Добавить задачу", () => AddTask(p)),

                // Запускаем редактирование существующей задачи.
                new("> Изменить задачу", () => EditTask(p)),

                // Позволяем изменить статус задачи.
                new("Сменить статус", () => ChangeState(p)),

                // Назначаем задаче исполнителя или снимаем назначение.
                new("Назначить исполнителя", () => Assign(p)),

                // Устанавливаем или изменяем срок выполнения.
                new("Установить срок", () => SetDeadline(p)),

                // Открываем учёт затраченного времени.
                new("Учет времени", () => TrackTime(p)),

                // Открываем сценарий поиска, фильтрации и сортировки.
                new("Поиск и фильтры", () => SearchTasks(p)),

                // Открываем отдельное меню управления командой.
                // false отключает дополнительную паузу после перехода в подменю.
                new("Команда", () => TeamMenu(p), false),

                // Формируем статистику проекта и предлагаем сохранить отчёт.
                new("Отчет о проекте", () => ShowReport(p)),

                // Запускаем удаление выбранной задачи.
                new("x Удалить задачу", () => DeleteTask(p)),

                // Пункт возврата к списку проектов.
                // Отсутствие действия обозначает навигационный выход из текущего меню.
                new("<- К списку проектов", null)
            };

            // Переменная для хранения выбранного пункта меню.
            MenuItem choice;

            try
            {
                // Показываем меню текущего проекта.
                // В качестве заголовка используется название проекта.
                choice = Input.Pick($"Проект '{p.Name}' - что делаем?", items, i => i.Label, allowBack: false);
            }
            catch (NavigationBackException)
            {
                // Возвращаемся из меню проекта в главное меню.
                return;
            }

            // Если выбран пункт без действия, завершаем текущий цикл меню.
            if (choice.Run is null) return;

            // Запускаем выбранную операцию с централизованной обработкой исключений.
            try { Guard(choice.Run, choice.Pause); }

            // Специальное исключение означает возврат к меню проекта.
            catch (NavigationBackException) { /* Возврат к меню проекта. */ }
        }
    }

