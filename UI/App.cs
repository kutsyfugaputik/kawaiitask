    /// <summary>
    /// Последовательно запрашивает параметры поиска и фильтрации,
    /// создаёт объект TaskFilter и показывает найденные задачи в таблице.
    /// </summary>
    /// <param name="p">Проект, задачи которого требуется найти.</param>
    private void SearchTasks(Project p)
    {
        // Проверяем, есть ли задачи, среди которых можно выполнять поиск.
        if (p.Tasks.Count == 0)
        {
            // Если задач нет, сообщаем об этом пользователю.
            Theme.Hint("Пока нечего искать - задач нет.");

            // Завершаем сценарий поиска.
            return;
        }

        // Создаём объект с параметрами фильтрации.
        // Вначале заполняем текстовый запрос, остальные свойства используют значения по умолчанию.
        var filter = new TaskFilter
        {
            // Запрашиваем слово или фразу для поиска.
            // Пользователь может пропустить ввод, нажав Enter.
            Text = Input.AskOptional("Что ищем? (слово из названия, описания или имя; Enter - пропустить)", 60)
        };

        // Предлагаем выбрать несколько статусов одновременно.
        // Если пользователь ничего не выбрал, фильтр по статусу не применяется.
        filter.States = Input.PickMany(
            "Какие статусы показать? (пустой выбор = все)",
            Enum.GetValues<TaskState>(),
            state => state.Text());

        // Предлагаем выбрать конкретный приоритет или оставить все приоритеты.
        // При выборе варианта «Любой» свойство OnlyPriority останется null.
        filter.OnlyPriority = Input.PickOrAny("Приоритет", Enum.GetValues<Priority>(), x => x.Text(), "* Любой");

        // Если в команде есть участники, предлагаем выбрать исполнителя.
        if (p.Team.Count > 0)

            // Сохраняем ID выбранного участника.
            // Если выбран пункт «Любой исполнитель», результат будет null.
            filter.AssigneeId = PickMember(p, "* Любой исполнитель")?.Id;

        // Спрашиваем, нужно ли оставить только просроченные задачи.
        filter.OnlyOverdue = Input.Confirm("Показать только просроченные?");

        // Предлагаем выбрать способ сортировки найденных задач.
        // SortLabel преобразует значения SortKey в удобные подписи меню.
        filter.Sort = Input.Pick("Как отсортировать?", Enum.GetValues<SortKey>(), SortLabel);

        // Передаём проект и собранные параметры сервису TaskQuery.
        // Метод Apply выполняет поиск, фильтрацию и сортировку.
        var result = TaskQuery.Apply(p, filter);

        // Добавляем пустую строку перед результатами.
        AnsiConsole.WriteLine();

        // Показываем количество найденных задач.
        Theme.Hint($"Найдено задач: {result.Count}");

        // Отображаем найденные задачи в таблице.
        Views.TaskTable(p, result);
    }

    /// <summary>
    /// Открывает меню управления участниками команды проекта.
    /// Позволяет добавлять и удалять участников.
    /// </summary>
    /// <param name="p">Проект, командой которого необходимо управлять.</param>
    private void TeamMenu(Project p)
    {
        // Цикл позволяет выполнять несколько операций с командой без повторного открытия меню проекта.
        while (true)
        {
            // Очищаем экран и отображаем стандартную шапку.
            Theme.Banner();

            // Выводим заголовок с названием текущего проекта.
            // Theme.E экранирует текст для безопасного использования в разметке Spectre.Console.
            AnsiConsole.MarkupLine($"[{Theme.Pink}]КОМАНДА ПРОЕКТА: {Theme.E(p.Name)}[/]");

            // Показываем таблицу текущих участников команды.
            Views.TeamTable(p);

            // Добавляем пустую строку перед пунктами меню.
            AnsiConsole.WriteLine();

            // Формируем доступные действия с командой.
            var items = new List<MenuItem>
            {
                // Переход к добавлению участника.
                new("+ Добавить участника", () => AddMember(p)),

                // Переход к удалению участника.
                new("x Убрать участника", () => RemoveMember(p)),

                // Возврат в меню проекта.
                new("<- Назад", null)
            };

            // Переменная для хранения выбранного пункта.
            MenuItem choice;

            try
            {
                // Показываем меню команды.
                choice = Input.Pick("Что делаем с командой?", items, i => i.Label, allowBack: false);
            }
            catch (NavigationBackException)
            {
                // Если механизм навигации сообщил о возврате, закрываем меню команды.
                return;
            }

            // Пункт без действия означает возврат в меню проекта.
            if (choice.Run is null) return;

            // Выполняем выбранную операцию с централизованной обработкой ошибок.
            try { Guard(choice.Run, choice.Pause); }

            // Перехватываем специальный сигнал возврата, чтобы снова показать меню команды.
            catch (NavigationBackException) { /* Возврат к меню команды. */ }
        }
    }

