    /// <param name="p">Проект, в котором находится задача.</param>
    private void TrackTime(Project p)
    {
        // Предлагаем выбрать задачу, для которой требуется записать время.
        var task = PickTask(p, "Для какой задачи считаем время?");

        // Если задач нет, дальнейшая работа не выполняется.
        if (task is null) return;

        // Показываем карточку выбранной задачи, чтобы пользователь видел её данные.
        Views.TaskCard(p, task);

        // Добавляем визуальный отступ после карточки.
        AnsiConsole.WriteLine();

        // Создаём варианты действий для учёта времени.
        var options = new[] { "Запустить таймер", "> Добавить время вручную", "<- Назад" };

        // Получаем выбор пользователя.
        // allowBack: false означает, что возврат представлен отдельным пунктом массива.
        var picked = Input.Pick("Что сделаем?", options, s => s, allowBack: false);

        // Определяем выбранный вариант по его индексу в массиве options.
        switch (Array.IndexOf(options, picked))
        {
            case 0:
            {
                // Запускаем таймер фокусировки для выбранной задачи.
                // Метод возвращает количество минут, прошедших с момента запуска.
                var minutes = FocusTimer.Run(task.Title);

