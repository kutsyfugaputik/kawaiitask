        if (role == roles[^1])

            // Если да, запрашиваем собственное название роли.
            // Индекс ^1 обозначает последний элемент массива.
            role = Input.Ask("Какая роль?", 30);

        // Показываем анимацию добавления участника.
        UiAnimation.Loading("Добавляем участника", 250);

        // Передаём имя и роль сервису управления проектами.
        // Сервис создаёт участника, добавляет его в команду и сохраняет данные.
        var member = _svc.AddMember(p, name, role);

        // Подтверждаем добавление, показывая имя и роль участника.
        Theme.Ok($"{member.Name} ({member.Role}) теперь в команде!");
    }

    /// <summary>
    /// Удаляет выбранного участника из команды после подтверждения пользователя.
    /// </summary>
    /// <param name="p">Проект, из команды которого удаляется участник.</param>
    private void RemoveMember(Project p)
    {
        // Проверяем, есть ли участники, которых можно удалить.
        if (p.Team.Count == 0)
        {
            // Если команда пуста, сообщаем об этом пользователю.
            Theme.Hint("Убирать некого - команда пуста.");

            // Завершаем операцию.
            return;
        }

        // Предлагаем выбрать участника.
        // Вариант «Не убирать участников» возвращает null.
        var member = PickMember(p, "Не убирать участников");

        // Если пользователь выбрал вариант без удаления, прекращаем операцию.
        if (member is null) return;

        // Запрашиваем подтверждение.
        // Предупреждаем, что задачи участника останутся, но потеряют назначенного исполнителя.
        if (!Input.Confirm($"Убрать {member.Name} из команды? Его задачи останутся без исполнителя."))
        {
            // Сообщаем, что удаление отменено.
            Theme.Hint("Всё осталось как было <3");

            return;
        }

        // Передаём сервису проект и участника для удаления.
        // Сервис отвечает за обновление связанных данных и сохранение изменений.
        _svc.RemoveMember(p, member);

        // Подтверждаем удаление участника.
        Theme.Ok($"{member.Name} больше не в команде.");
    }

    /// <summary>
    /// Формирует отчёт по проекту, выводит его в консоль и предлагает сохранить в Markdown.
    /// Для разных способов вывода используются реализации интерфейса IReportWriter.
    /// </summary>
    /// <param name="p">Проект, по которому формируется отчёт.</param>
    private void ShowReport(Project p)
    {
        // Собираем статистику проекта.
        // Build возвращает готовый объект ProjectReport, который содержит рассчитанные показатели.
        var report = ReportService.Build(p);

        // Создаём объект вывода отчёта в консоль.
        // Переменная имеет тип интерфейса IReportWriter, а не конкретного класса.
        // Это позволяет работать с разными способами формирования отчётов через общий контракт.
        IReportWriter console = new ConsoleReportWriter();

        // Передаём подготовленный отчёт консольному обработчику.
        console.Write(report);

        // Добавляем визуальный отступ после консольного отчёта.
        AnsiConsole.WriteLine();

        // Спрашиваем пользователя, нужно ли сохранить отчёт в Markdown-файл.
        // Если пользователь отказывается, завершаем метод.
        if (!Input.Confirm("Сохранить отчёт в Markdown-файл?")) return;

        // Создаём обработчик Markdown-отчётов.
        // В качестве папки сохранения передаём путь, предоставленный ProjectService.
        IReportWriter markdown = new MarkdownReportWriter(_svc.ReportsFolder);

        // Формируем Markdown-файл и получаем путь к сохранённому документу.
        var path = markdown.Write(report);

        // Показываем пользователю результат сохранения.
        Theme.Ok($"Отчёт сохранён: {path}");
    }

    /// <summary>
    /// Удаляет выбранную задачу после подтверждения пользователя.
    /// </summary>
    /// <param name="p">Проект, из которого требуется удалить задачу.</param>
    private void DeleteTask(Project p)
    {
        // Предлагаем пользователю выбрать задачу для удаления.
        var task = PickTask(p, "Какую задачу удаляем?");

        // Если задач нет или выбор отсутствует, прекращаем операцию.
        if (task is null) return;

        // Запрашиваем подтверждение удаления.
        // В сообщении показываем идентификатор и название задачи.
        if (!Input.Confirm($"Удалить задачу #{task.Id} '{task.Title}'?"))
        {
            // Сообщаем, что задача осталась в проекте.
            Theme.Hint("Задача осталась на месте <3");

            return;
        }

        // Показываем анимацию удаления.
        UiAnimation.Loading("Удаляем задачу", 250);

        // Передаём проект и задачу сервису для удаления и сохранения изменений.
        _svc.DeleteTask(p, task);

        // Подтверждаем успешное удаление.
        Theme.Ok("Задача удалена.");
    }
