                if (minutes == 0)
                {
                    // Сообщаем, почему время не было добавлено.
                    Theme.Hint("Прошло меньше 30 секунд - запись не создана.");

                    // Завершаем текущую операцию.
                    return;
                }

                // Предлагаем добавить пояснение к записи времени.
                var note = Input.AskOptional("Что делал(а)? (Enter - без заметки)", 100);

                // Передаём количество минут и заметку сервису учёта времени.
                _svc.LogTime(task, minutes, note);

                // Форматируем длительность и подтверждаем сохранение записи.
                Theme.Ok($"Записано {Views.Fmt(minutes)} в задачу #{task.Id}");

