    /// <summary>
    /// Создаёт новую задачу с заданными пользователем параметрами.
    /// </summary>
    /// <param name="p">Проект, в который добавляется задача.</param>
    private void AddTask(Project p)
    {
        // Запрашиваем название задачи с ограничением длины из модели TaskItem.
        var title = Input.Ask("Название задачи", TaskItem.MaxTitle);

        // Запрашиваем необязательное описание задачи.
        var description = Input.AskOptional("Описание (Enter - пропустить)", TaskItem.MaxDescription);

        // Предлагаем выбрать приоритет из всех значений перечисления Priority.
        // Метод Text() преобразует техническое значение перечисления в понятную подпись.
        var priority = Input.Pick("Приоритет", Enum.GetValues<Priority>(), x => x.Text());

        // Предлагаем выбрать тип задачи из перечисления TaskKind.
        var kind = Input.Pick("Тип задачи", Enum.GetValues<TaskKind>(), x => x.Text());

        // По умолчанию задача создаётся без назначенного исполнителя.
        Member? assignee = null;

        // Если в проекте есть участники, предлагаем выбрать исполнителя.
        if (p.Team.Count > 0)
            assignee = PickMember(p, "(x_x) Пока никому");

        // Запрашиваем необязательный срок выполнения задачи.
        var deadline = Input.AskDate("Срок выполнения");

        // Показываем анимацию добавления.
        UiAnimation.Loading("Добавляем задачу", 300);

        // Передаём все параметры сервису.
        // assignee?.Id безопасно получает ID участника или null, если исполнитель не выбран.
        // Сервис создаёт задачу, добавляет её в проект и сохраняет данные.
        var task = _svc.AddTask(p, title, description, priority, kind, assignee?.Id, deadline);

        // Выводим подтверждение с идентификатором и названием созданной задачи.
        Theme.Ok($"Задача #{task.Id} '{task.Title}' добавлена!");
    }

    /// <summary>
    /// Позволяет изменить одно из основных полей существующей задачи:
    /// название, описание, приоритет или тип.
    /// </summary>
    /// <param name="p">Проект, в котором находится задача.</param>
    private void EditTask(Project p)
    {
        // Предлагаем выбрать задачу для редактирования.
        var task = PickTask(p, "Какую задачу правим?");

        // Если задач нет или выбор не сделан, завершаем операцию.
        if (task is null) return;

        // Формируем список редактируемых полей.
        // Порядок элементов соответствует вариантам в switch ниже.
        var fields = new[] { "> Название", "[ ] Описание", "* Приоритет", "* Тип" };

        // Получаем выбранное пользователем поле.
        var field = Input.Pick("Что поменяем?", fields, s => s);

        // Индекс выбранной строки в массиве определяет, какое свойство задачи будет изменено.
        switch (Array.IndexOf(fields, field))
        {
            case 0:
            {
                // Запрашиваем новое название, показывая текущее значение.
                var title = Input.Ask($"Новое название (сейчас: {task.Title})", TaskItem.MaxTitle);

                // Выполняем переименование и сохраняем изменения через ProjectService.
                _svc.Update(() => task.Rename(title));

                // Завершаем обработку выбранного варианта.
                break;
            }
            case 1:
            {
                // Запрашиваем новое описание.
                // Пустой ввод позволяет очистить существующее описание.
                var text = Input.AskOptional("Новое описание (Enter - очистить)", TaskItem.MaxDescription);

                // Вызываем метод модели Describe и сохраняем изменения.
                _svc.Update(() => task.Describe(text));

                break;
            }
            case 2:
            {
                // Предлагаем выбрать новый приоритет задачи.
                var priority = Input.Pick("Новый приоритет", Enum.GetValues<Priority>(), x => x.Text());

                // Изменяем свойство Priority через сервис, чтобы изменение было сохранено.
                _svc.Update(() => task.Priority = priority);

                break;
            }
            default:
            {
                // Для оставшегося варианта запрашиваем новый тип задачи.
                var kind = Input.Pick("Новый тип", Enum.GetValues<TaskKind>(), x => x.Text());

                // Обновляем тип задачи и сохраняем данные.
                _svc.Update(() => task.Kind = kind);

                break;
            }
        }

        // Сообщаем, что редактирование выбранной задачи завершено.
        Theme.Ok($"Задача #{task.Id} обновлена!");
    }

    /// <summary>
    /// Изменяет статус выбранной задачи и рассчитывает разницу игровых баллов.
    /// </summary>
    /// <param name="p">Проект, содержащий задачу.</param>
    private void ChangeState(Project p)
    {
        // Предлагаем пользователю выбрать задачу.
        var task = PickTask(p, "Какой задаче меняем статус?");

        // Если выбрать задачу невозможно, прекращаем операцию.
        if (task is null) return;

        // Получаем все возможные статусы, кроме текущего статуса задачи.
        // ToList() материализует результаты фильтрации в список.
        var options = Enum.GetValues<TaskState>().Where(s => s != task.State).ToList();

        // Предлагаем выбрать новый статус.
        var state = Input.Pick($"Сейчас: {task.State.Text()}. Какой статус теперь?", options, s => s.Text());

        // Запоминаем общее количество игровых баллов проекта до изменения статуса.
        // Это необходимо, чтобы определить разницу после выполнения операции.
        var before = ReportService.CandyPoints(p);

        // Передаём сервису изменение статуса.
        // Сервис отвечает за обновление задачи и сохранение данных.
        _svc.ChangeState(task, state);

        // Вычисляем изменение количества баллов.
        // Положительное значение означает получение награды, отрицательное — потерю баллов.
        var gained = ReportService.CandyPoints(p) - before;

        // Подтверждаем изменение статуса.
        Theme.Ok($"Задача #{task.Id} теперь '{state.Text()}'");

        // Если баллов стало больше, запускаем анимацию награды.
        if (gained > 0)
            UiAnimation.Reward(gained);

        // Если баллов стало меньше, показываем информационное сообщение.
        else if (gained < 0)
            Theme.Hint("Конфетки вернулись обратно в баночку... но ты ещё заработаешь их <3");
    }

