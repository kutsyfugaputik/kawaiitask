            return;
        }

        // Выбираем задачу, для которой требуется изменить исполнителя.
        var task = PickTask(p, "Кому назначаем задачу?");

        // Если список задач пуст, прекращаем операцию.
        if (task is null) return;

        // Выбираем участника.
        // Специальный первый пункт позволяет снять исполнителя с задачи.
        var member = PickMember(p, "(x_x) Снять исполнителя");

