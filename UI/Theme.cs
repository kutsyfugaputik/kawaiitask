    /// <summary>
    /// Приостанавливает выполнение программы до нажатия пользователем любой клавиши.
    /// Если ввод перенаправлен, метод не ожидает нажатия и сразу завершается.
    /// В случае недоступности ReadKey используется альтернативное ожидание через ReadLine.
    /// </summary>
    public static void Pause()
    {
        // Проверяем, доступен ли интерактивный ввод с клавиатуры.
        // При перенаправлении ввода ожидание нажатия клавиши невозможно.
        if (Console.IsInputRedirected) return;

        // Добавляем пустую строку перед подсказкой.
        AnsiConsole.WriteLine();

        // Выводим декоративную разделительную линию.
        // Math.Min ограничивает её длину значением 60 символов.
        AnsiConsole.MarkupLine(Dots(Math.Min(Width, 60)));

        // Показываем пользователю сообщение о необходимости нажать любую клавишу.
        AnsiConsole.Markup($"[grey]нажми любую клавишу, чтобы продолжить[/] [{Pink}]*[/]");

        try
        {
            // Ожидаем нажатия любой клавиши.
            // Параметр true запрещает отображать нажатый символ в консоли.
            Console.ReadKey(true);
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or NotSupportedException)
        {
            // Если ReadKey недоступен, используем запасной способ ожидания.
            // Например, это может произойти в некоторых консолях отладки IDE.
            try
            {
                // Ожидаем ввода строки и нажатия Enter.
                // Этот способ подходит для терминалов, где ReadKey не поддерживается.
                Console.ReadLine();
            }
            catch (IOException)
            {
                // Если интерактивный ввод недоступен полностью,
                // пропускаем ожидание и продолжаем выполнение программы.
            }
        }

        // Добавляем пустую строку после ожидания для визуального разделения интерфейса.
        AnsiConsole.WriteLine();
    }

