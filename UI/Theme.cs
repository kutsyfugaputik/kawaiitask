using System.Text; // Подключаем StringBuilder для эффективного формирования длинных строк.
using KawaiiTasks.Models; // Подключаем модели проекта, содержащие перечисления Priority и TaskState.
using Spectre.Console; // Подключаем библиотеку для цветного вывода, таблиц, панелей, рамок и других элементов интерфейса.
using Spectre.Console.Rendering; // Подключаем интерфейсы отображаемых элементов, включая IRenderable.

namespace KawaiiTasks.UI; // Определяем пространство имён, объединяющее компоненты пользовательского интерфейса приложения.

/// <summary>
/// Класс Theme является центральной системой оформления приложения Kawaii Tasks.
/// Здесь определяются цвета, стили текста, декоративные элементы и общие методы отображения.
/// Класс используется другими компонентами интерфейса, чтобы все экраны имели единый внешний вид.
///
/// Цвета задаются в формате HEX (#RRGGBB), а Spectre.Console преобразует разметку
/// в управляющие последовательности ANSI, которые понимает терминал.
/// Класс также управляет фоновым цветом консоли и восстанавливает исходное оформление
/// при завершении работы приложения.
/// </summary>
public static class Theme
{
    // ------------------------------------------------------------ ПАЛИТРА ЦВЕТОВ

    // Определяем основные цвета приложения в формате HEX (#RRGGBB).
    // Каждая пара символов отвечает за интенсивность красного (R), зелёного (G) и синего (B) каналов.
    // Значения можно напрямую использовать в разметке Spectre.Console: $"[{Pink}]Текст[/]".

    public const string Pink = "#ff9ecb"; // Основной розовый цвет: заголовки, акценты и декоративные элементы.
    public const string Lavender = "#c3a6ff"; // Лавандовый цвет: второстепенные заголовки, подписи и рамки.
    public const string Mint = "#8fe3c0"; // Мятный цвет: успешные действия, завершённые задачи и положительные результаты.
    public const string Peach = "#ffc09f"; // Персиковый цвет: дополнительные акценты и декоративные элементы.
    public const string Sky = "#8fd3f4"; // Голубой цвет: информационные сообщения и вспомогательные элементы.
    public const string Lemon = "#ffe680"; // Жёлтый цвет: предупреждения, баллы и выделение важных показателей.
    public const string Berry = "#ff6f91"; // Ягодный цвет: ошибки, просроченные задачи и предупреждения.

    // Дополнительные оттенки используются для оформления ретро-дневника.
    public const string Cocoa = "#d4b595"; // Цвет какао применяется для разделителей, дат и декоративных линий.
    public const string Rose = "#e8a0bf"; // Приглушённый розовый оттенок для дополнительных элементов оформления.

    // Цвета самого терминала, а не отдельных элементов интерфейса.
    // Они устанавливаются через ANSI OSC-команды в методе ApplyPaper().
    public const string PaperBg = "#000000"; // Цвет фона терминала: чёрный.
    public const string PaperFg = "#f3e6d8"; // Основной цвет текста терминала: светлый бежевый.

    /// <summary>
    /// Определяет, разрешено ли приложению изменять стандартные цвета терминала.
    /// Значение true включает пользовательское оформление.
    /// Значение false оставляет исходные настройки терминала без изменений.
    /// </summary>
    public static bool UseCustomBackground = true;

    // ------------------------------------------------------------ ЦВЕТА ДЛЯ SPECTRE.CONSOLE

    // Создаём объекты Color на основании HEX-значений.
    // Строки Pink, Lavender, Mint и Cocoa используются в текстовой разметке,
    // а объекты с суффиксом C предназначены для методов Spectre.Console,
    // которые принимают тип Color вместо обычной строки.

    public static readonly Color PinkC = FromHex(Pink); // Объект Color для основного розового цвета.
    public static readonly Color LavenderC = FromHex(Lavender); // Объект Color для лавандового цвета.
    public static readonly Color MintC = FromHex(Mint); // Объект Color для мятного цвета.
    public static readonly Color CocoaC = FromHex(Cocoa); // Объект Color для оттенка какао.

    /// <summary>
    /// Преобразует HEX-цвет в объект Color библиотеки Spectre.Console.
    /// Например, значение "#ff9ecb" преобразуется в RGB(255, 158, 203).
    /// Метод используется при настройке цветов рамок, текста и других элементов интерфейса.
    /// </summary>
    /// <param name="hex">Цвет в шестнадцатеричном формате #RRGGBB.</param>
    /// <returns>Объект Color с соответствующими значениями RGB.</returns>
    public static Color FromHex(string hex)
    {
        // Удаляем символ # в начале строки, если он присутствует.
        // После этого остаются ровно шесть шестнадцатеричных символов для RGB.
        hex = hex.TrimStart('#');

        // Создаём объект Color на основании трёх цветовых каналов.
        return new Color(
            // Извлекаем первые два символа строки и преобразуем их в десятичное значение красного канала.
            Convert.ToByte(hex.Substring(0, 2), 16),

            // Извлекаем следующие два символа и получаем значение зелёного канала.
            Convert.ToByte(hex.Substring(2, 2), 16),

            // Извлекаем последние два символа и получаем значение синего канала.
            Convert.ToByte(hex.Substring(4, 2), 16));
    }

    /// <summary>
    /// Экранирует пользовательский текст перед передачей в разметку Spectre.Console.
    /// Это необходимо, чтобы квадратные скобки внутри названий задач, описаний и имён
    /// не воспринимались библиотекой как команды форматирования.
    ///
    /// Например, текст "Баг [срочно]" без экранирования может нарушить обработку разметки.
    /// Markup.Escape преобразует специальные символы в безопасное представление.
    /// </summary>
    /// <param name="text">Исходный текст пользователя. Может отсутствовать.</param>
    /// <returns>Безопасная строка для использования в разметке Spectre.Console.</returns>
    public static string E(string? text) => Markup.Escape(text ?? "");

    // ------------------------------------------------------------ УПРАВЛЕНИЕ ЦВЕТАМИ ОКНА ТЕРМИНАЛА (OSC 10/11)

    // Храним состояние настройки оформления терминала.
    // Эти поля нужны, чтобы не изменять настройки повторно и правильно восстанавливать исходные цвета.

    private static bool _paperApplied; // Показывает, выполнялась ли первоначальная настройка оформления терминала.
    private static bool _paperOn; // Показывает, были ли успешно отправлены OSC-команды изменения цветов.
    private static bool _consoleColorsCaptured; // Показывает, были ли сохранены исходные цвета классической консоли.
    private static ConsoleColor _oldBackground; // Хранит исходный цвет фона Windows-консоли.
    private static ConsoleColor _oldForeground; // Хранит исходный цвет текста Windows-консоли.

    /// <summary>
    /// Изменяет оформление терминала на пользовательское.
    /// Для Windows используется стандартный Console API, а для современных терминалов
    /// дополнительно применяются OSC-последовательности ANSI.
    ///
    /// Исходные цвета сохраняются, чтобы восстановить их при завершении приложения.
    /// Если терминал не поддерживает изменение оформления, программа продолжает работу
    /// без пользовательского фона.
    /// </summary>
    public static void ApplyPaper()
    {
        // Проверяем, можно ли применять пользовательское оформление.
        // UseCustomBackground отключает настройку по желанию разработчика.
        // _paperApplied предотвращает повторное сохранение уже изменённых цветов.
        // Console.IsOutputRedirected определяет, направлен ли вывод в файл или другой поток.
        if (!UseCustomBackground || _paperApplied || Console.IsOutputRedirected) return;

        // Помечаем настройку как выполненную до начала изменения цветов.
        // Это защищает от повторного вызова даже в случае возникновения исключения.
        _paperApplied = true;

        try
        {
            // Проверяем, запущено ли приложение в операционной системе Windows.
            if (OperatingSystem.IsWindows())
            {
                // Сохраняем текущий цвет фона консоли.
                // Это необходимо для восстановления первоначального оформления.
                _oldBackground = Console.BackgroundColor;

                // Сохраняем текущий цвет текста консоли.
                _oldForeground = Console.ForegroundColor;

                // Отмечаем, что исходные цвета успешно сохранены.
                _consoleColorsCaptured = true;

                // Устанавливаем чёрный фон классической Windows-консоли.
                Console.BackgroundColor = ConsoleColor.Black;

                // Устанавливаем серый цвет текста.
                Console.ForegroundColor = ConsoleColor.Gray;

                // Очищаем экран, чтобы новые цвета применились ко всей видимой области.
                Console.Clear();
            }

            // Определяем, поддерживает ли текущий терминал OSC-последовательности.
            // Современные терминалы понимают специальные команды изменения цвета окна.
            var supportsOsc = !OperatingSystem.IsWindows() ||

                // WT_SESSION обычно присутствует при запуске приложения в Windows Terminal.
                // Если переменная существует и не пустая, считаем, что терминал поддерживает OSC.
                !string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("WT_SESSION")) ||

                // ConEmuANSI со значением ON указывает на поддержку ANSI-последовательностей в ConEmu.
                // StringComparison.OrdinalIgnoreCase позволяет не учитывать регистр символов.
                string.Equals(Environment.GetEnvironmentVariable("ConEmuANSI"), "ON", StringComparison.OrdinalIgnoreCase) ||

                // ANSICON используется некоторыми старыми Windows-консолями для поддержки ANSI-цветов.
                !string.IsNullOrWhiteSpace(Environment.GetEnvironmentVariable("ANSICON"));

            // Если поддержка OSC обнаружена, отправляем команды изменения цветов терминала.
            if (supportsOsc)
            {
                // \u001b — управляющий символ ESC, начинающий ANSI-последовательность.
                // ]11 устанавливает цвет фона терминала.
                // PaperBg задаёт новый цвет фона.
                // \u0007 завершает команду специальным символом BEL.
                // ]10 устанавливает основной цвет текста терминала.
                // PaperFg задаёт светлый цвет текста.
                Console.Write($"\u001b]11;{PaperBg}\u0007\u001b]10;{PaperFg}\u0007");

                // Отмечаем, что команды изменения оформления были отправлены.
                _paperOn = true;
            }

            // Регистрируем обработчик завершения процесса.
            // ResetPaper будет вызван при обычном завершении программы.
            AppDomain.CurrentDomain.ProcessExit += (_, _) => ResetPaper();

            // Регистрируем обработчик сочетания Ctrl+C.
            // Он позволяет восстановить оформление терминала при прерывании работы программы.
            Console.CancelKeyPress += (_, _) => ResetPaper();
        }
        catch (Exception ex) when (ex is IOException or InvalidOperationException or PlatformNotSupportedException)
        {
            // Перехватываем ожидаемые ошибки взаимодействия с терминалом.
            // Некоторые среды выполнения запрещают изменять цвета или очищать экран.
            // Отсутствие декоративного оформления не должно мешать запуску приложения.
        }
    }

    /// <summary>
    /// Восстанавливает стандартное оформление терминала.
    /// Метод возвращает исходные цвета фона и текста, сохранённые в ApplyPaper().
    /// Вызывается автоматически при завершении приложения и может использоваться вручную.
    /// </summary>
    public static void ResetPaper()
    {
        // Если пользовательское оформление не применялось и исходные цвета не сохранялись,
        // восстановление не требуется.
        if (!_paperOn && !_consoleColorsCaptured) return;

        try
        {
            // Проверяем, применялись ли OSC-команды изменения цветов терминала.
            if (_paperOn)

                // Отправляем команды восстановления настроек терминала.
                // ESC ] 111 BEL сбрасывает пользовательский цвет фона к стандартному.
                // ESC ] 110 BEL сбрасывает пользовательский цвет текста к стандартному.
                Console.Write("\u001b]111\u0007\u001b]110\u0007");

            // Сбрасываем флаг применения OSC-оформления.
            _paperOn = false;

            // Проверяем, сохранены ли первоначальные цвета Windows-консоли.
            if (_consoleColorsCaptured)
            {
                // Восстанавливаем исходный цвет фона.
                Console.BackgroundColor = _oldBackground;

                // Восстанавливаем исходный цвет текста.
                Console.ForegroundColor = _oldForeground;

                // Сбрасываем флаг, чтобы повторно не восстанавливать те же значения.
                _consoleColorsCaptured = false;
            }
        }
        catch (Exception ex) when (ex is IOException or InvalidOperationException or PlatformNotSupportedException)
        {
            // Игнорируем ошибки восстановления оформления.
            // Завершение программы не должно зависеть от возможности изменить цвета терминала.
        }
    }

    // ------------------------------------------------------------ ПРИОРИТЕТЫ И СТАТУСЫ ЗАДАЧ

    /// <summary>
    /// Возвращает HEX-цвет, соответствующий приоритету задачи.
    /// Каждый уровень приоритета имеет собственный цвет для визуального различения.
    /// </summary>
    /// <param name="p">Приоритет задачи.</param>
    /// <returns>HEX-код цвета приоритета.</returns>
    public static string PriorityHex(Priority p) => p switch
    {
        // Низкий приоритет отображается мятным цветом.
        Priority.Low => Mint,

        // Средний приоритет отображается голубым цветом.
        Priority.Medium => Sky,

        // Высокий приоритет отображается персиковым цветом.
        Priority.High => Peach,

        // Все остальные значения получают ягодный цвет.
        _ => Berry
    };

    /// <summary>
    /// Возвращает HEX-цвет, соответствующий статусу задачи.
    /// Используется для оформления колонок канбан-доски и текстовых меток.
    /// </summary>
    /// <param name="s">Текущий статус задачи.</param>
    /// <returns>HEX-код цвета статуса.</returns>
    public static string StateHex(TaskState s) => s switch
    {
        // Ожидающие выполнения задачи отображаются лавандовым цветом.
        TaskState.Todo => Lavender,

        // Задачи в процессе выполнения отображаются жёлтым цветом.
        TaskState.InProgress => Lemon,

        // Задачи на проверке отображаются голубым цветом.
        TaskState.Review => Sky,

        // Завершённые задачи отображаются мятным цветом.
        _ => Mint
    };

    /// <summary>
    /// Возвращает короткий текстовый символ для обозначения статуса задачи.
    /// Значок используется вместе с названием статуса в интерфейсе.
    /// </summary>
    /// <param name="s">Статус задачи.</param>
    /// <returns>Текстовый символ статуса.</returns>
    public static string StateIcon(TaskState s) => s switch
    {
        // Пустой кружок обозначает задачу, ожидающую выполнения.
        TaskState.Todo => "o",

        // Волнистый символ обозначает задачу в процессе выполнения.
        TaskState.InProgress => "~",

        // Буква R обозначает этап проверки (Review).
        // Используется ASCII-символ, чтобы избежать проблем с отображением в старых терминалах.
        TaskState.Review => "R",

        // Для завершённых задач используется короткая отметка OK.
        _ => "OK"
    };

    /// <summary>
    /// Возвращает текстовое представление приоритета с помощью звёздочек.
    /// Чем выше приоритет, тем больше звёздочек отображается.
    /// </summary>
    /// <param name="p">Приоритет задачи.</param>
    /// <returns>Строка со звёздочками.</returns>
    public static string PriorityStars(Priority p) => p switch
    {
        // Низкий приоритет: одна звёздочка.
        Priority.Low => "*...",

        // Средний приоритет: две звёздочки.
        Priority.Medium => "**..",

        // Высокий приоритет: три звёздочки.
        Priority.High => "***.",

        // Для остальных значений отображаются четыре звёздочки.
        _ => "****"
    };

    // ------------------------------------------------------------ ГОТОВЫЕ ТЕКСТОВЫЕ МЕТКИ

    // Формируем цветную метку приоритета.
    // PriorityHex определяет цвет, E экранирует название приоритета,
    // а [/ ] завершает цветовую разметку Spectre.Console.
    public static string PriorityTag(Priority p) => $"[{PriorityHex(p)}]{E(p.Text())}[/]";

    // Формируем цветную метку статуса задачи.
    // Цвет выбирается по статусу, а текстовое название берётся из метода расширения Text().
    public static string StateTag(TaskState s) => $"[{StateHex(s)}]{E(s.Text())}[/]";

    // Создаём небольшой цветной маркер приоритета в виде звёздочки.
    // Используется в карточках задач и канбан-доске.
    public static string PriorityDot(Priority p) => $"[{PriorityHex(p)}]*[/]";

    // Формируем полную метку приоритета со звёздочками и его текстовым названием.
    // Сначала выводится цветной индикатор, затем понятное пользователю название.
    public static string PriorityLabel(Priority p) => $"[{PriorityHex(p)}]{PriorityStars(p)}[/] {E(p.Text())}";

    // Формируем полную метку статуса с символом и текстовым названием.
    // StateHex отвечает за цвет, StateIcon — за значок, а Text() — за название статуса.
    public static string StateLabel(TaskState s) => $"[{StateHex(s)}]{StateIcon(s)} {E(s.Text())}[/]";

    // ------------------------------------------------------------ ДЕКОРАТИВНЫЕ ЭЛЕМЕНТЫ

    /// <summary>
    /// Возвращает ширину терминала с ограничением минимального и максимального значения.
    /// Spectre.Console получает доступную ширину через профиль консоли.
    /// Ограничение помогает сохранять корректное оформление при маленьком
    /// или очень широком окне терминала.
    /// </summary>
    public static int Width => Math.Clamp(AnsiConsole.Profile.Width, 20, 120);

    // Массив содержит последовательность символов для декоративной полосы.
    // Символы повторяются, чтобы можно было сформировать линию любой необходимой длины.
    private static readonly string[] SparkleTokens =
        { "*", "|", ".", "|", "*", "|", ".", "|", "*", "|", ".", "|", "*", "|", ".", "|" };

    // Массив содержит цвета, которые циклически применяются к декоративным символам.
    // Благодаря этому каждый элемент полосы может иметь собственный оттенок.
    private static readonly string[] SparkleColors = { Pink, Lavender, Sky, Mint, Peach, Lemon };

    /// <summary>
    /// Формирует декоративную строку из звёздочек, вертикальных линий и точек.
    /// Каждый элемент занимает две позиции: символ и пробел.
    /// Метод возвращает строку с разметкой Spectre.Console, но самостоятельно её не выводит.
    /// Параметр offset позволяет изменять начальный элемент декоративной последовательности.
    /// </summary>
    /// <param name="width">Максимальная ширина декоративной строки.</param>
    /// <param name="offset">Смещение начальной позиции в массивах символов и цветов.</param>
    /// <returns>Готовая строка с цветовой разметкой.</returns>
    public static string SparkleMarkup(int width, int offset = 0)
    {
        // Создаём StringBuilder для последовательного формирования строки.
        // Он эффективнее обычной конкатенации при большом количестве добавлений.
        var sb = new StringBuilder();

        // Храним количество уже занятых символов строки.
        var used = 0;

        // Начинаем перебор с переданного смещения.
        var i = offset;

        // Продолжаем добавление элементов, пока остаётся место минимум для двух символов.
        while (used + 2 <= width)
        {
            // Получаем очередной декоративный символ.
            // Оператор % позволяет циклически обращаться к массиву SparkleTokens.
            var token = SparkleTokens[i % SparkleTokens.Length];

            // Добавляем символ с соответствующим цветом и пробел после него.
            // Индекс цвета также вычисляется циклически.
            sb.Append($"[{SparkleColors[i % SparkleColors.Length]}]{token}[/] ");

            // Увеличиваем счётчик занятой ширины на две позиции.
            used += 2;

            // Переходим к следующему символу и цвету.
            i++;
        }

        // Удаляем лишние пробелы в конце сформированной строки.
        // Возвращаем результат без самостоятельного вывода в консоль.
        return sb.ToString().TrimEnd();
    }

    /// <summary>
    /// Выводит декоративную полосу из звёздочек и точек по центру терминала.
    /// Если ширина не передана, используется текущая ширина окна.
    /// </summary>
    /// <param name="width">Необязательная ширина декоративной полосы.</param>
    public static void Sparkles(int? width = null) =>

        // Формируем декоративную строку и ограничиваем её текущей шириной терминала.
        // Markup преобразует цветовые метки в оформленный текст.
        // Align размещает результат по центру экрана.
        AnsiConsole.Write(new Align(new Markup(SparkleMarkup(Math.Min(width ?? Width, Width))), HorizontalAlignment.Center));

    // Align с HorizontalAlignment.Center автоматически рассчитывает левый отступ,
    // чтобы размещаемый элемент находился по центру доступной области терминала.

    /// <summary>
    /// Выводит декоративные отверстия от переплёта блокнота.
    /// Количество повторений зависит от ширины терминала.
    /// </summary>
    public static void Spiral()
    {
        // Создаём строку из повторяющихся элементов "o---".
        // Enumerable.Repeat повторяет заданную последовательность нужное количество раз.
        // Math.Max гарантирует, что будет отображено не менее четырёх элементов.
        // TrimEnd удаляет лишние пробелы в конце строки.
        var holes = string.Concat(Enumerable.Repeat("o---", Math.Max(4, Width / 4))).TrimEnd();

        // Выводим декоративную линию лавандовым цветом по центру терминала.
        AnsiConsole.Write(new Align(new Markup($"[{Lavender}]{holes}[/]"), HorizontalAlignment.Center));
    }

    /// <summary>
    /// Выводит декоративную полоску скотча над карточкой или другим элементом интерфейса.
    /// Если цвет не указан, используется персиковый оттенок.
    /// </summary>
    /// <param name="color">Необязательный HEX-код цвета полоски.</param>
    /// <param name="length">Количество символов в полоске.</param>
    public static void Tape(string? color = null, int length = 14) =>

        // Создаём строку из символов / указанной длины.
        // color ?? Peach означает использование персикового цвета,
        // если вызывающий метод не передал собственный цвет.
        // Align размещает декоративную полоску по центру терминала.
        AnsiConsole.Write(new Align(
            new Markup($"[{color ?? Peach}]{new string('/', length)}[/]"), HorizontalAlignment.Center));

    /// <summary>
    /// Создаёт цветную пунктирную линию для разделения элементов интерфейса.
    /// Метод возвращает строку, которую можно встроить в другую разметку.
    /// </summary>
    /// <param name="length">Количество символов в линии.</param>
    /// <returns>Строка с цветным разделителем.</returns>
    public static string Dots(int length) => $"[{Cocoa}]{new string('-', length)}[/]";

    /// <summary>
    /// Создаёт декоративную ленту с названием раздела.
    /// Название располагается по центру между двумя симметричными участками рамки.
    /// </summary>
    /// <param name="title">Текст заголовка ленты.</param>
    /// <param name="color">Необязательный цвет оформления.</param>
    public static void Ribbon(string title, string? color = null)
    {
        // Определяем цвет ленты.
        // Если цвет не передан, используем лавандовый.
        var c = color ?? Lavender;

        // Добавляем декоративные звёздочки и пробелы вокруг названия.
        var text = $" * {title} * ";

        // Рассчитываем длину боковых частей рамки.
        // Math.Max гарантирует минимальную длину в два символа.
        // Деление на два позволяет симметрично распределить рамку относительно заголовка.
        var side = Math.Max(2, (Width - text.Length - 4) / 2);

        // Создаём боковую часть ленты из символов =.
        var bar = new string('=', side);

        // Собираем всю декоративную строку и выводим её по центру терминала.
        // Theme.E здесь не используется, поэтому текст title передаётся в Markup напрямую.
        AnsiConsole.Write(new Align(
            new Markup($"[{c}]|{bar}|{E(text)}|{bar}|[/]"), HorizontalAlignment.Center));
    }

    /// <summary>
    /// Создаёт оформленную страницу приложения с рамкой и заголовком.
    /// Panel помещает переданное содержимое внутрь рамки.
    /// Align выравнивает готовую панель по центру терминала.
    /// Возвращается IRenderable, поэтому результат можно использовать
    /// внутри других компонентов Spectre.Console.
    /// </summary>
    /// <param name="content">Содержимое страницы: текст, таблица, сетка или другой элемент интерфейса.</param>
    /// <param name="title">Необязательный заголовок страницы.</param>
    /// <param name="color">Необязательный цвет рамки и заголовка.</param>
    /// <param name="dbl">Параметр исходной сигнатуры. В текущей реализации не используется.</param>
    /// <param name="padding">Необязательные внутренние отступы страницы.</param>
    /// <returns>Готовый визуальный элемент страницы.</returns>
    public static IRenderable Page(IRenderable content, string? title = null, string? color = null,
        bool dbl = true, Padding? padding = null)
    {
        // Определяем цвет оформления страницы.
        // Если цвет не передан, используем основной розовый оттенок.
        var c = color ?? Pink;

        // Создаём панель, которая будет содержать переданный элемент интерфейса.
        var panel = new Panel(content)
        {
            // Используем ASCII-рамку для совместимости с различными терминалами.
            Border = BoxBorder.Ascii,

            // Преобразуем HEX-цвет в объект Color и устанавливаем его для рамки.
            BorderStyle = new Style(FromHex(c)),

            // Определяем внутренние отступы.
            // Если пользовательские отступы не переданы, используем стандартные.
            Padding = padding ?? new Padding(2, 0)
        };

        // Проверяем, был ли передан заголовок страницы.
        if (title is not null)

            // Создаём заголовок панели.
            // E экранирует текст, чтобы специальные символы не нарушали разметку.
            // Justify.Center располагает заголовок по центру рамки.
            panel.Header = new PanelHeader($"[{c}] {E(title)} [/]", Justify.Center);

        // Возвращаем панель, выровненную по центру терминала.
        return new Align(panel, HorizontalAlignment.Center);
    }

    /// <summary>
    /// Возвращает текущую дату в удобном формате на русском языке.
    /// Название дня недели и месяца формируются с учётом культуры ru-RU.
    /// Если форматирование с русской культурой невозможно, используется числовой формат даты.
    /// </summary>
    /// <returns>Дата в формате "суббота, 21 ноября" или "21.11.2026".</returns>
    public static string Today()
    {
        try
        {
            // Получаем текущую системную дату и форматируем её с использованием русской культуры.
            // dddd — полное название дня недели.
            // d — номер дня месяца.
            // MMMM — полное название месяца.
            return DateTime.Now.ToString("dddd, d MMMM", new CultureInfo("ru-RU"));
        }
        catch (Exception ex) when (ex is ArgumentException)
        {
            // Если создание или применение культуры завершилось ошибкой,
            // используем универсальный числовой формат даты.
            return DateTime.Now.ToString("dd.MM.yyyy");
        }
    }

