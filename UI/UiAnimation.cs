
using Spectre.Console; // Подключаем Spectre.Console для создания анимаций, цветного текста, панелей и динамического обновления содержимого терминала.

namespace KawaiiTasks.UI; // Определяем пространство имён пользовательского интерфейса приложения.

// <summary>
// Класс UiAnimation содержит декоративные ASCII-анимации приложения.
// Здесь реализованы загрузочный индикатор, заставка при запуске
// и визуальный эффект получения баллов.
// Анимации не влияют на бизнес-логику и не изменяют данные проекта.
// Если ввод или вывод перенаправлен, анимации автоматически отключаются.
// </summary>
public static class UiAnimation
{
    // <summary>
    // Собственный класс спиннера, который определяет внешний вид
    // и скорость вращения загрузочного индикатора.
    // Используются ASCII-символы, чтобы анимация отображалась
    // даже в терминалах с ограниченной поддержкой Unicode.
    // </summary>
    private sealed class StarSpinner : Spinner
    {
        // Определяем интервал между сменами кадров анимации.
        // 140 миллисекунд — время отображения одного символа.
        public override TimeSpan Interval => TimeSpan.FromMilliseconds(140);

        // Указываем, что спиннер использует обычные ASCII-символы,
        // а не Unicode-символы, требующие специальной поддержки терминала.
        public override bool IsUnicode => false;

        // Возвращаем последовательность символов, из которых состоит анимация.
        // Spectre.Console последовательно переключает эти символы,
        // создавая эффект вращающегося индикатора.
        public override IReadOnlyList<string> Frames => new[] { "-", "\\", "|", "/" };
    }

    // Проверяем, работает ли приложение непосредственно в интерактивном терминале.
    // Console.IsInputRedirected возвращает true, если ввод перенаправлен из файла или канала.
    // Console.IsOutputRedirected возвращает true, если вывод направлен не в обычную консоль.
    // Если хотя бы одно условие выполнено, анимации отключаются.
    private static bool Interactive => !Console.IsInputRedirected && !Console.IsOutputRedirected;

    /// <summary>
    /// Показывает кратковременный загрузочный индикатор с текстовым сообщением.
    /// Используется для визуального сопровождения операций приложения.
    /// Если анимация недоступна или её продолжительность не положительная,
    /// метод завершается без отображения спиннера.
    /// </summary>
    /// <param name="message">Текст, отображаемый рядом с индикатором загрузки.</param>
    /// <param name="durationMs">Продолжительность отображения в миллисекундах. По умолчанию 350 мс.</param>
    public static void Loading(string message, int durationMs = 350)
    {
        // Проверяем, нужно ли вообще запускать анимацию.
        // При нулевой или отрицательной продолжительности либо неинтерактивном режиме
        // сразу завершаем метод.
        if (durationMs <= 0 || !Interactive) return;

        try
        {
            // Создаём компонент Status для отображения загрузочного индикатора.
            // Spinner задаёт используемый тип анимации.
            // SpinnerStyle определяет цвет вращающегося символа.
            // Start запускает индикатор на время выполнения переданного действия.
            AnsiConsole.Status()
                .Spinner(new StarSpinner())
                .SpinnerStyle(new Style(Theme.PinkC))
                .Start($"[{Theme.Lavender}]{Theme.E(message)}...[/]", _ => Thread.Sleep(durationMs));
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or NotSupportedException)
        {
            // Перехватываем только ожидаемые ошибки работы консольного интерфейса.
            // InvalidOperationException возникает при недопустимом состоянии консоли.
            // IOException может возникнуть при проблемах с вводом или выводом.
            // NotSupportedException означает, что используемая операция не поддерживается.
            // Анимация декоративная, поэтому её сбой не должен останавливать приложение.
        }
    }

    /// <summary>
    /// Показывает стартовую заставку приложения.
    /// Во время анимации отображаются котик, текстовые этапы запуска
    /// и постепенно заполняющийся индикатор прогресса.
    /// Содержит 25 кадров с интервалом 60 миллисекунд.
    /// </summary>
    public static void Intro()
    {
        // Проверяем возможность отображения анимации.
        // Если приложение работает с перенаправленным вводом или выводом,
        // заставка не запускается.
        if (!Interactive) return;

        try
        {
            // Создаём массив текстовых этапов заставки.
            // На каждом этапе пользователю показывается соответствующее сообщение.
            var steps = new[]
            {
                "достаем дневничок",
                "готовим рабочее место",
                "проверяем задачи",
                "открываем приложение"
            };

            // Определяем максимальное количество заполненных символов прогресс-бара.
            const int total = 24;

            // Создаём интерактивную область терминала.
            // Live позволяет обновлять содержимое без последовательной печати каждого кадра.
            // AutoClear(true) очищает область после завершения анимации.
            // Start запускает переданный метод, в котором выполняется последовательность кадров.
            AnsiConsole.Live(new Markup(" ")).AutoClear(true).Start(ctx =>
            {
                // Перебираем кадры от 0 до 24 включительно.
                // Получается 25 кадров анимации.
                for (var i = 0; i <= total; i++)
                {
                    // Определяем текущий текстовый этап.
                    // Умножение номера кадра на количество этапов
                    // позволяет равномерно распределить сообщения по времени заставки.
                    // Math.Min не позволяет выйти за пределы массива steps.
                    var step = steps[Math.Min(steps.Length - 1, i * steps.Length / (total + 1))];

                    // Формируем строку прогресс-бара.
                    // Символы # показывают выполненную часть,
                    // а символы - обозначают оставшуюся часть.
                    // Цвета задаются через тему оформления приложения.
                    var bar = $"[{Theme.Cocoa}]|[/][{Theme.Pink}]{new string('#', i)}[/][grey]{new string('-', total - i)}[/][{Theme.Cocoa}]|[/]";

                    // Меняем выражение мордочки котика в зависимости от текущего кадра.
                    // Остаток от деления на 6 позволяет чередовать два выражения.
                    // Первые три кадра цикла показывают открытые глаза,
                    // следующие три — закрытые.
                    var cat = i % 6 < 3 ? "( ^.^ )" : "( -.- )";

                    // Собираем содержимое текущего кадра.
                    // Markup позволяет использовать цветовое оформление Spectre.Console.
                    // Символы \n отвечают за переносы строк.
                    var body = new Markup(
                        // Добавляем декоративный ряд звёздочек в верхней части заставки.
                        $"[{Theme.Pink}] *  *  *  *  *  *  *[/]\n\n" +

                        // Формируем ASCII-изображение котика.
                        // Theme.E экранирует текстовое изображение от интерпретации как разметки.
                        $"[{Theme.Pink}]  /\\_/\\\n {Theme.E(cat)}\n  >   <[/]\n\n" +

                        // Выводим сообщение текущего этапа и прогресс-бар.
                        $"{Theme.Lavender}{Theme.E(step)}...[/]\n{bar}\n\n" +

                        // Добавляем нижний декоративный ряд звёздочек.
                        $"[{Theme.Pink}] *  *  *  *  *  *  *[/]");

                    // Обновляем содержимое интерактивной области.
                    // Theme.Page оформляет кадр в виде страницы приложения.
                    // Параметры задают заголовок, цвет оформления и внутренние отступы.
                    ctx.UpdateTarget(Theme.Page(body, "KAWAII TASKS", Theme.Pink, true, new Padding(3, 0)));

                    // Принудительно обновляем отображение текущего кадра в терминале.
                    ctx.Refresh();

                    // Приостанавливаем выполнение на 60 миллисекунд.
                    // Это определяет скорость смены кадров анимации.
                    Thread.Sleep(60);
                }
            });
        }
        catch (Exception ex) when (ex is InvalidOperationException or IOException or NotSupportedException)
        {
            // Перехватываем ожидаемые ошибки отображения заставки.
            // Запуск приложения не должен зависеть от успешного выполнения анимации.
        }
    }

    /// <summary>
    /// Показывает визуальный эффект получения награды.
    /// Отображает последовательность кадров со звёздочками,
    /// меняющимися цветами и количеством полученных баллов.
    /// Итоговое сообщение выводится даже при отключённой анимации.
    /// </summary>
    /// <param name="points">Количество полученных баллов.</param>
    public static void Reward(int points)
    {
        // Проверяем количество полученных баллов.
        // Если значение равно нулю или отрицательное, награда не отображается.
        if (points <= 0) return;

        // Запускаем визуальный эффект только при работе в интерактивном терминале.
        if (Interactive)
        {
            try
            {
                // Создаём массив кадров анимации.
                // Каждый элемент содержит отдельное расположение звёздочек и символов.
                // При последовательном отображении элементов создаётся эффект салюта.
                var frames = new[]
                {
                    "          *          ",
                    "       *  +  *       ",
                    "    +  *  +  *  +    ",
                    "  *  +  *  +  *  +  *",
                    " .  *  +  *  +  *  . ",
                    "  +  .  *  +  .  +  "
                };

                // Создаём массив цветов для оформления кадров.
                // Каждый цвет соответствует отдельному элементу темы приложения.
                var colors = new[] { Theme.Pink, Theme.Lemon, Theme.Mint, Theme.Sky, Theme.Lavender, Theme.Peach };

                // Создаём интерактивную область для анимации.
                // AutoClear(true) очищает её после завершения эффекта.
                // Start запускает последовательное отображение кадров.
                AnsiConsole.Live(new Markup(" ")).AutoClear(true).Start(ctx =>
                {
                    // Повторяем последовательность кадров два раза.
                    // Умножение количества кадров на 2 задаёт общую продолжительность эффекта.
                    for (var i = 0; i < frames.Length * 2; i++)
                    {
                        // Выбираем текущий кадр.
                        // Оператор % позволяет повторно использовать массив frames,
                        // не выходя за пределы его индексов.
                        var frame = frames[i % frames.Length];

                        // Выбираем цвет текущего кадра.
                        // Цвета также переключаются циклически.
                        var color = colors[i % colors.Length];

                        // Обновляем отображаемое содержимое анимации.
                        // В верхней строке находятся декоративные символы,
                        // в нижней — изображение котика и количество полученных баллов.
                        // Align размещает весь блок по центру терминала.
                        ctx.UpdateTarget(new Align(new Markup(
                            $"[{color}]{Theme.E(frame)}[/]\n[{Theme.Lemon}](^_^)/  +{points}[/]"),
                            HorizontalAlignment.Center));

                        // Обновляем изображение в терминале.
                        ctx.Refresh();

                        // Задерживаем выполнение на 90 миллисекунд перед следующим кадром.
                        Thread.Sleep(90);
                    }
                });
            }
            catch (Exception ex) when (ex is InvalidOperationException or IOException or NotSupportedException)
            {
                // Если анимация не может быть отображена, приложение продолжает работу.
                // Получение баллов не зависит от успешного воспроизведения визуального эффекта.
            }
        }

        // Выводим итоговое сообщение о полученной награде.
        // Эта строка выполняется независимо от того, запускалась ли анимация.
        AnsiConsole.MarkupLine($"[{Theme.Lemon}]  * +{points} очков прогресса![/]");
    }
}
