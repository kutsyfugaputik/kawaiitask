// Подключаем пространство имён для работы с форматами чисел и дат.
// Оно позволяет задавать единые правила разбора значений независимо от настроек компьютера.
using System.Globalization;

// Подключаем библиотеку Spectre.Console.
// Она используется для создания интерактивных запросов, списков выбора и цветного оформления терминала.
using Spectre.Console;

namespace KawaiiTasks.UI;

// <summary>
// Исключение, обозначающее запрос пользователя на возврат в предыдущее меню.
// Используется как механизм навигации из глубоко вложенных методов ввода.
// Исключение проходит через последовательность вызовов и обрабатывается в циклах меню,
// например в App.ProjectLoop и других методах управления интерфейсом.
// </summary>
public sealed class NavigationBackException : Exception
{
    // Вызываем конструктор базового класса Exception
    // и передаём ему сообщение, описывающее причину возникновения исключения.
    public NavigationBackException() : base("Возврат в предыдущее меню.") { }
}

// <summary>
// Центральный класс для получения и проверки пользовательского ввода.
// Содержит методы для ввода строк, дат, продолжительности времени,
// выбора вариантов и подтверждения действий.
// Также обеспечивает единый механизм возврата в предыдущее меню.
// 
// Spectre.Console самостоятельно управляет отображением интерактивных запросов.
// TextPrompt получает строку после нажатия Enter,
// а SelectionPrompt позволяет перемещаться по вариантам с помощью клавиатуры.
// Класс Input определяет, какие данные запрашивать и как проверять ответы пользователя.
// </summary>
public static class Input
{
    // Объявляем закрытую обобщённую запись Choice<T>.
    // Она представляет один пункт списка выбора и хранит:
    // Value — реальное значение выбранного объекта;
    // Label — текст, который будет показан пользователю;
    // IsBack — признак того, что пункт предназначен для возврата назад.
    //
    // Обобщённый тип T позволяет использовать эту структуру
    // с разными типами данных: задачами, категориями, проектами и перечислениями.
    // Значение IsBack по умолчанию равно false.
    private sealed record Choice<T>(T Value, string Label, bool IsBack = false);

    // Массив допустимых форматов дат.
    // Благодаря нескольким вариантам пользователь может вводить дату
    // как с ведущими нулями, так и без них.
    // Например: 05.03.2026, 5.3.2026 или 05.03.26.
    private static readonly string[] DateFormats =
    {
        "dd.MM.yyyy",
        "d.M.yyyy",
        "dd.MM.yy"
    };

    // Массив допустимых ответов, которые программа воспринимает как подтверждение.
    // Регистр букв при проверке не учитывается.
    private static readonly string[] YesAnswers = { "да", "д", "y" };

    // Массив допустимых ответов, которые программа воспринимает как отказ.
    private static readonly string[] NoAnswers = { "нет", "н", "n" };

    // Создаём стиль для текста, который вводит пользователь.
    // Используется лавандовый цвет из общей темы приложения.
    // Так введённые значения визуально отличаются от подсказок и сообщений системы.
    private static readonly Style Typed = new(Theme.LavenderC);

    // Формирует единый шаблон отображения текстового запроса.
    // text — название поля или вопрос, который необходимо показать пользователю.
    //
    // Theme.E экранирует специальные символы разметки Spectre.Console.
    // Это необходимо, чтобы введённый или переданный текст отображался как обычный текст,
    // а не интерпретировался как команда форматирования.
    //
    // Цветовые конструкции в квадратных скобках задают оформление:
    // Theme.Cocoa — декоративный разделитель;
    // Theme.Pink — основной текст запроса;
    // grey — подсказка о команде возврата.
    //
    // Метод используется другими методами класса, чтобы все запросы
    // имели одинаковое оформление.
    private static string Prompt(string text) =>
        $"[{Theme.Cocoa}]|[/] [{Theme.Pink}]> {Theme.E(text)}[/] [grey](:back - назад)[/]";

    /// <summary>
    /// Проверяет, не ввёл ли пользователь команду возврата.
    /// При обнаружении команды создаёт NavigationBackException,
    /// которая прерывает текущую цепочку ввода и позволяет вернуться к предыдущему меню.
    /// </summary>
    private static void ThrowIfBack(string? value)
    {
        // Trim удаляет пробелы в начале и конце строки.
        // StringComparison.OrdinalIgnoreCase выполняет сравнение без учёта регистра.
        //
        // Допускаются два варианта команды:
        // :back — основной вариант;
        // /back — альтернативный вариант.
        //
        // Если совпало хотя бы одно условие, создаётся исключение навигации.
        if (string.Equals(value?.Trim(), ":back", StringComparison.OrdinalIgnoreCase) ||
            string.Equals(value?.Trim(), "/back", StringComparison.OrdinalIgnoreCase))
            throw new NavigationBackException();
    }

    /// <summary>
    /// Запрашивает обязательную строку и проверяет её корректность.
    /// Пустые значения и строки длиннее max символов не принимаются.
    /// Команда :back позволяет вернуться в предыдущее меню.
    /// </summary>
    public static string Ask(string text, int max = 80)
    {
        // Создаём текстовый запрос для получения строки от пользователя.
        // Prompt(text) формирует его внешний вид.
        var prompt = new TextPrompt<string>(Prompt(text))

            // Устанавливаем стиль вводимого текста.
            .PromptStyle(Typed)

            // Validate задаёт функцию проверки ответа.
            // Она вызывается после каждого нажатия Enter.
            // Если проверка возвращает Error, Spectre.Console выводит ошибку
            // и предлагает пользователю повторить ввод.
            .Validate(s =>
            {
                // Сначала проверяем, не запросил ли пользователь возврат в меню.
                ThrowIfBack(s);

                // Проверяем, что строка не состоит только из пробелов
                // и не является пустой.
                if (string.IsNullOrWhiteSpace(s))
                    return ValidationResult.Error($"[{Theme.Berry}]Поле не может быть пустым[/]");

                // Удаляем лишние пробелы по краям строки и проверяем её длину.
                // Если количество символов превышает max, ввод отклоняется.
                if (s.Trim().Length > max)
                    return ValidationResult.Error($"[{Theme.Berry}]Максимум {max} символов[/]");

                // Если все проверки пройдены, подтверждаем корректность значения.
                return ValidationResult.Success();
            });

        // Показываем запрос пользователю и получаем введённую строку.
        // Trim удаляет пробелы по краям перед возвратом результата.
        return AnsiConsole.Prompt(prompt).Trim();
    }

    /// <summary>
    /// Запрашивает необязательную строку.
    /// Пользователь может оставить поле пустым, просто нажав Enter.
    /// При этом длина непустого значения всё равно проверяется.
    /// </summary>
    public static string AskOptional(string text, int max = 500)
    {
        // Создаём запрос для ввода строки.
        var prompt = new TextPrompt<string>(Prompt(text))

            // Устанавливаем стиль пользовательского ввода.
            .PromptStyle(Typed)

            // Разрешаем пустой ответ.
            // Без AllowEmpty Spectre.Console потребовал бы непустое значение.
            .AllowEmpty()

            // Добавляем проверку введённого значения.
            .Validate(s =>
            {
                // Проверяем команду возврата.
                ThrowIfBack(s);

                // Удаляем пробелы по краям и проверяем максимальную длину.
                // Если длина превышена, возвращаем сообщение об ошибке.
                // В противном случае подтверждаем корректность ввода.
                return (s ?? "").Trim().Length > max
                    ? ValidationResult.Error($"[{Theme.Berry}]Максимум {max} символов[/]")
                    : ValidationResult.Success();
            });

        // Показываем запрос и возвращаем результат без пробелов по краям.
        // Если пользователь нажал Enter без ввода текста, возвращается пустая строка.
        return AnsiConsole.Prompt(prompt).Trim();
    }

    /// <summary>
    /// Преобразует строку в дату, используя только заранее определённые форматы.
    /// CultureInfo.InvariantCulture обеспечивает независимость от региональных настроек ОС.
    /// Возвращает true, если дата успешно распознана, иначе false.
    /// </summary>
    public static bool TryParseDate(string? text, out DateTime date) =>
        // TryParseExact выполняет строгий разбор даты по указанным форматам.
        // text ?? "" заменяет null на пустую строку, чтобы избежать передачи null в метод.
        // Trim удаляет лишние пробелы по краям.
        // DateFormats содержит допустимые варианты записи даты.
        // InvariantCulture задаёт независимые от системы правила форматирования.
        // DateTimeStyles.None означает отсутствие дополнительных правил преобразования.
        // Результат записывается в переменную date через out.
        DateTime.TryParseExact(
            (text ?? "").Trim(),
            DateFormats,
            CultureInfo.InvariantCulture,
            DateTimeStyles.None,
            out date);

    /// <summary>
    /// Запрашивает дату выполнения задачи.
    /// Поддерживает формат дд.мм.гггг.
    /// Если пользователь нажимает Enter, срок выполнения не устанавливается.
    /// Даты, которые уже прошли, не принимаются.
    /// </summary>
    public static DateTime? AskDate(string text)
    {
        // Создаём текстовый запрос с дополнительной подсказкой.
        // Пользователю сообщается допустимый формат даты
        // и возможность оставить поле пустым.
        var prompt = new TextPrompt<string>(
                Prompt($"{text} (дд.мм.гггг, Enter - без срока)"))

            // Устанавливаем цвет вводимого значения.
            .PromptStyle(Typed)

            // Разрешаем пустой ответ, поскольку срок выполнения необязателен.
            .AllowEmpty()

            // Проверяем введённое значение перед его принятием.
            .Validate(s =>
            {
                // Если введена команда возврата, прерываем текущий ввод.
                ThrowIfBack(s);

                // Если строка пустая или состоит только из пробелов,
                // считаем это корректным ответом без срока выполнения.
                if (string.IsNullOrWhiteSpace(s))
                    return ValidationResult.Success();

                // Пытаемся преобразовать строку в дату.
                // Если формат не соответствует допустимым вариантам,
                // показываем пользователю пример правильной записи.
                if (!TryParseDate(s, out var date))
                    return ValidationResult.Error(
                        $"[{Theme.Berry}]Формат: дд.мм.гггг, например 25.12.2026[/]");

                // Сравниваем дату без учёта времени с сегодняшним днём.
                // Дата в прошлом не может быть установлена как новый срок выполнения.
                if (date.Date < DateTime.Today)
                    return ValidationResult.Error($"[{Theme.Berry}]Эта дата уже прошла[/]");

                // Если формат корректен и дата не находится в прошлом,
                // разрешаем принять значение.
                return ValidationResult.Success();
            });

        // Выводим запрос и получаем исходную строку.
        var raw = AnsiConsole.Prompt(prompt);

        // Повторно преобразуем строку в дату.
        // Проверка уже выполнялась в Validate, поэтому преобразование должно пройти успешно.
        // Однако дополнительная проверка защищает программу от неожиданного результата.
        // Если преобразование не удалось, возвращаем null — отсутствие срока выполнения.
        return TryParseDate(raw, out var parsed) ? parsed : null;
    }

    /// <summary>
    /// Преобразует продолжительность времени в минуты.
    /// Поддерживаются два формата:
    /// десятичные часы, например 1.5;
    /// часы и минуты через двоеточие, например 1:30.
    /// Допустимый диапазон результата — от 1 до 1440 минут.
    /// </summary>
    public static bool TryParseDuration(string? text, out int minutes)
    {
        // Изначально устанавливаем результат в 0.
        // Если преобразование не удастся, вызывающий метод получит безопасное значение.
        minutes = 0;

        // Проверяем, что строка не пустая и не состоит только из пробелов.
        // Без исходного значения преобразование невозможно.
        if (string.IsNullOrWhiteSpace(text))
            return false;

        // Удаляем пробелы по краям строки.
        // Заменяем русскую десятичную запятую на точку,
        // чтобы пользователь мог вводить 1,5 вместо 1.5.
        var value = text.Trim().Replace(',', '.');

        // Проверяем, содержит ли строка двоеточие.
        // Если да, предполагается формат часы:минуты.
        if (value.Contains(':'))
        {
            // Разделяем строку по двоеточию.
            // Для корректного формата должно получиться ровно две части:
            // первая — часы, вторая — минуты.
            var parts = value.Split(':');

            // Проверяем корректность обеих частей.
            // parts.Length != 2 означает неправильное количество частей.
            // TryParse преобразует строку в целое число.
            // NumberStyles.None запрещает знаки и дополнительные символы.
            // CultureInfo.InvariantCulture задаёт единые правила разбора.
            //
            // Дополнительно проверяем:
            // h < 0 — часы не могут быть отрицательными;
            // m < 0 — минуты не могут быть отрицательными;
            // m > 59 — количество минут в одной части не может превышать 59.
            //
            // Если хотя бы одно условие нарушено, возвращаем false.
            if (parts.Length != 2 ||
                !int.TryParse(parts[0], NumberStyles.None, CultureInfo.InvariantCulture, out var h) ||
                !int.TryParse(parts[1], NumberStyles.None, CultureInfo.InvariantCulture, out var m) ||
                h < 0 || m < 0 || m > 59)
                return false;

            // Проверяем верхнюю границу продолжительности.
            // Максимум составляет 24 часа.
            // Поэтому 24:00 допустимо, а 24:01 и больше — нет.
            if (h > 24 || (h == 24 && m > 0))
                return false;

            // Переводим часы в минуты и прибавляем оставшиеся минуты.
            // Например, 1:30 преобразуется в 1 * 60 + 30 = 90 минут.
            minutes = h * 60 + m;
        }
        else
        {
            // Если двоеточия нет, предполагается формат десятичных часов.
            // Например:
            // 1.5 — полтора часа;
            // 2 — два часа;
            // 0.5 — половина часа.
            //
            // NumberStyles.AllowDecimalPoint разрешает десятичную точку,
            // но не разрешает экспоненциальную запись и знаки.
            // CultureInfo.InvariantCulture обеспечивает разбор с точкой.
            // TryParse записывает результат в переменную hours.
            if (!double.TryParse(
                    value,
                    NumberStyles.AllowDecimalPoint,
                    CultureInfo.InvariantCulture,
                    out var hours) ||

                // Проверяем, что число является конечным.
                // Это исключает NaN и бесконечность.
                !double.IsFinite(hours) ||

                // Продолжительность не может быть отрицательной.
                hours < 0 ||

                // Максимальная продолжительность — 24 часа.
                hours > 24)
                return false;

            // Переводим десятичные часы в минуты.
            // Math.Round округляет результат до целого числа.
            // AwayFromZero означает округление половины в сторону от нуля.
            // Например, 1.5 часа преобразуется в 90 минут.
            minutes = (int)Math.Round(hours * 60, MidpointRounding.AwayFromZero);
        }

        // Итоговая проверка допустимого диапазона.
        // Продолжительность должна составлять не менее 1 минуты
        // и не более 1440 минут (24 часа).
        //
        // Оператор is позволяет компактно проверить попадание
        // значения в указанный диапазон.
        return minutes is >= 1 and <= 1440;
    }

    /// <summary>
    /// Запрашивает продолжительность времени у пользователя.
    /// Повторяет запрос, если значение введено неправильно.
    /// Возвращает результат в минутах.
    /// </summary>
    public static int AskDuration(string text)
    {
        // Создаём текстовый запрос для ввода продолжительности.
        var prompt = new TextPrompt<string>(Prompt(text))

            // Устанавливаем стиль вводимого текста.
            .PromptStyle(Typed)

            // Добавляем проверку корректности продолжительности.
            .Validate(s =>
            {
                // Проверяем, не хочет ли пользователь вернуться назад.
                ThrowIfBack(s);

                // Пытаемся преобразовать введённую строку в минуты.
                // Если преобразование успешно, запрос принимается.
                // Если нет, пользователю показывается пример допустимого формата.
                return TryParseDuration(s, out _)
                    ? ValidationResult.Success()
                    : ValidationResult.Error(
                        $"[{Theme.Berry}]Введи часы: 1.5 или 1:30 (от 1 минуты до 24 часов)[/]");
            });

        // Получаем окончательно проверенную строку из терминала.
        // Повторно преобразуем её в минуты.
        // out var minutes создаёт переменную, в которую записывается результат.
        TryParseDuration(AnsiConsole.Prompt(prompt), out var minutes);

        // Возвращаем продолжительность в минутах.
        return minutes;
    }

    /// <summary>
    /// Позволяет выбрать один элемент из переданной коллекции.
    /// Для каждого элемента отображается текст, сформированный функцией label.
    /// При необходимости добавляется пункт возврата в предыдущее меню.
    /// </summary>
    public static T Pick<T>(
        string title,
        IEnumerable<T> items,
        Func<T, string> label,
        bool allowBack = true)
        where T : notnull
    {
        // Преобразуем исходную коллекцию в список.
        // Это позволяет несколько раз обращаться к элементам
        // и проверять количество доступных вариантов.
        var values = items.ToList();

        // Если список пуст, отображать меню выбора невозможно.
        // Поэтому выбрасываем исключение с понятным описанием ошибки.
        if (values.Count == 0)
            throw new InvalidOperationException(
                "Для выбора не передано ни одного варианта.");

        // Создаём список объектов Choice<T>.
        // Каждый исходный элемент оборачивается в объект,
        // который хранит само значение и его отображаемое название.
        //
        // label(value) преобразует объект в понятную пользователю строку.
        // Например, вместо технического объекта задачи можно показать её название.
        var choices = values
            .Select(value => new Choice<T>(value, label(value)))
            .ToList();

        // Если параметр allowBack равен true,
        // добавляем дополнительный пункт для возврата в предыдущее меню.
        //
        // default! используется как техническое значение Value,
        // поскольку для пункта возврата реальное значение объекта не требуется.
        // IsBack = true позволяет отличить этот пункт от обычных вариантов.
        if (allowBack)
            choices.Add(new Choice<T>(default!, "<- Назад", true));

        // Создаём интерактивное меню выбора.
        // SelectionPrompt позволяет перемещаться между пунктами
        // с помощью стрелок клавиатуры и подтверждать выбор клавишей Enter.
        var prompt = new SelectionPrompt<Choice<T>>()

            // Устанавливаем заголовок меню.
            // Theme.E экранирует специальные символы в переданном названии.
            .Title($"[{Theme.Cocoa}]+-[/] [{Theme.Lavender}]* {Theme.E(title)} *[/]\n[{Theme.Cocoa}]+-[/]")

            // Определяем количество одновременно отображаемых пунктов.
            // Math.Clamp ограничивает размер страницы диапазоном от 6 до 14.
            // Theme.Width / 7 позволяет учитывать ширину терминала.
            .PageSize(Math.Clamp(Theme.Width / 7, 6, 14))

            // Выводим подсказку о перемещении по меню и подтверждении выбора.
            // Она отображается при наличии дополнительных пунктов для прокрутки.
            .MoreChoicesText("[grey](^/v - перемещение | Enter - выбор)[/]")

            // Устанавливаем стиль выделенного пункта.
            // Theme.PinkC задаёт цвет, а Decoration.Bold делает текст жирным.
            .HighlightStyle(new Style(Theme.PinkC, decoration: Decoration.Bold))

            // Преобразуем каждый объект Choice<T> в отображаемую строку.
            // Theme.E защищает названия от интерпретации как разметки Spectre.Console.
            .UseConverter(choice => Theme.E(choice.Label))

            // Передаём подготовленный список вариантов в меню.
            .AddChoices(choices);

        // Отображаем меню и получаем выбранный пользователем объект Choice<T>.
        var selected = AnsiConsole.Prompt(prompt);

        // Проверяем, не был ли выбран специальный пункт возврата.
        // Если IsBack равен true, прерываем текущую операцию
        // и передаём управление предыдущему меню через исключение.
        if (selected.IsBack)
            throw new NavigationBackException();

        // Возвращаем исходное значение выбранного элемента.
        // Пользователь получает объект типа T, а не его текстовую подпись.
        return selected.Value;
    }

    /// <summary>
    /// Позволяет выбрать несколько элементов из списка.
    /// Возвращает коллекцию выбранных значений.
    /// Если пользователь выбирает пункт возврата, возникает NavigationBackException.
    /// </summary>
    public static List<T> PickMany<T>(
        string title,
        IEnumerable<T> items,
        Func<T, string> label)
        where T : notnull
    {
        // Преобразуем каждый элемент исходной коллекции в Choice<T>.
        // Это позволяет связать отображаемое название с исходным значением.
        var choices = items
            .Select(value => new Choice<T>(value, label(value)))
            .ToList();

        // Добавляем специальный пункт возврата.
        // Его признак IsBack позволяет распознать его после выбора.
        choices.Add(new Choice<T>(default!, "<- Назад", true));

        // Создаём и сразу отображаем меню множественного выбора.
        // MultiSelectionPrompt позволяет отметить несколько пунктов.
        var selected = AnsiConsole.Prompt(
            new MultiSelectionPrompt<Choice<T>>()

                // Устанавливаем заголовок меню с лавандовым оформлением.
                // Theme.E защищает заголовок от специальных символов разметки.
                .Title($"[{Theme.Lavender}]{Theme.E(title)}[/]")

                // Разрешаем подтвердить выбор, даже если ни один пункт не отмечен.
                // Это необходимо для сценариев, в которых пустой выбор имеет смысл.
                .NotRequired()

                // Показываем подсказку по управлению меню.
                // Пробел отмечает или снимает отметку, Enter подтверждает выбор.
                .InstructionsText("[grey](пробел - отметить | Enter - готово)[/]")

                // Устанавливаем цвет выделенного пункта.
                .HighlightStyle(new Style(Theme.PinkC))

                // Определяем, какой текст будет показан для каждого пункта.
                // Theme.E экранирует специальные символы пользовательских названий.
                .UseConverter(choice => Theme.E(choice.Label))

                // Передаём подготовленный список элементов в меню.
                .AddChoices(choices));

        // Проверяем, присутствует ли среди выбранных пункт возврата.
        // Если да, прерываем текущий ввод и возвращаем пользователя в предыдущее меню.
        if (selected.Any(choice => choice.IsBack))
            throw new NavigationBackException();

        // Удаляем из результата специальный пункт возврата.
        // Затем извлекаем исходные значения Value из оставшихся объектов Choice<T>.
        // ToList формирует итоговый список выбранных элементов типа T.
        return selected
            .Where(choice => !choice.IsBack)
            .Select(choice => choice.Value)
            .ToList();
    }

    /// <summary>
    /// Позволяет выбрать значение перечисления или другого типа-структуры.
    /// Дополнительно предлагает вариант anyLabel.
    /// Если выбран этот вариант, метод возвращает null.
    /// </summary>
    public static T? PickOrAny<T>(
        string title,
        IEnumerable<T> items,
        Func<T, string> label,
        string anyLabel)
        where T : struct
    {
        // Создаём список кортежей.
        // Каждый кортеж хранит:
        // Value — выбранное значение типа T или null;
        // Label — название пункта для отображения в меню.
        //
        // Первым элементом добавляется вариант anyLabel.
        // Его Value равен null, то есть пользователь может выбрать отсутствие ограничения.
        var choices = new List<(T? Value, string Label)>
        {
            (null, anyLabel)
        };

        // Перебираем все переданные элементы.
        // Для каждого создаём кортеж из исходного значения и его отображаемого названия.
        foreach (var item in items)
            choices.Add((item, label(item)));

        // Используем универсальный метод Pick для отображения списка.
        // c => c.Label определяет, что пользователю показывается текст Label.
        //
        // После выбора извлекаем Value из выбранного кортежа.
        // Если пользователь выбрал anyLabel, результатом будет null.
        return Pick(title, choices, c => c.Label).Value;
    }

    /// <summary>
    /// Разбирает ответ пользователя на вопрос с вариантами «да» и «нет».
    /// true означает положительный ответ.
    /// false означает отрицательный ответ или пустую строку.
    /// null означает, что ответ не удалось распознать.
    /// Проверка выполняется без учёта регистра.
    /// </summary>
    public static bool? ParseYesNo(string? text)
    {
        // Удаляем пробелы по краям строки.
        // Если вместо строки передан null, используем пустую строку.
        var answer = (text ?? "").Trim();

        // Пустой ответ считается отказом.
        // Это безопасное значение по умолчанию для подтверждений.
        if (answer.Length == 0)
            return false;

        // Проверяем, входит ли ответ в массив допустимых положительных вариантов.
        // StringComparer.OrdinalIgnoreCase позволяет не учитывать регистр.
        // Например, "ДА", "Да" и "да" будут распознаны одинаково.
        if (YesAnswers.Contains(answer, StringComparer.OrdinalIgnoreCase))
            return true;

        // Проверяем, входит ли ответ в массив отрицательных вариантов.
        // Если совпадение найдено, возвращаем false.
        if (NoAnswers.Contains(answer, StringComparer.OrdinalIgnoreCase))
            return false;

        // Если строка не совпала ни с одним допустимым вариантом,
        // возвращаем null, чтобы вызывающий метод мог запросить повторный ввод.
        return null;
    }

    /// <summary>
    /// Запрашивает подтверждение действия у пользователя.
    /// Принимает варианты «да» и «нет».
    /// Пустой ввод считается отказом, то есть безопасным значением по умолчанию.
    /// Команда :back возвращает пользователя в предыдущее меню.
    /// </summary>
    public static bool Confirm(string text)
    {
        // Создаём запрос с подсказкой о допустимых вариантах ответа.
        var prompt = new TextPrompt<string>(Prompt($"{text} (да/нет)"))

            // Устанавливаем стиль вводимого текста.
            .PromptStyle(Typed)

            // Разрешаем пустой ввод.
            // В этом случае действие не будет подтверждено.
            .AllowEmpty()

            // Проверяем введённый ответ.
            .Validate(value =>
            {
                // Проверяем, не введена ли команда возврата.
                ThrowIfBack(value);

                // Вызываем ParseYesNo для определения значения ответа.
                // Если метод вернул null, значит пользователь ввёл непонятный вариант.
                // В таком случае просим ввести «да» или «нет».
                return ParseYesNo(value) is null
                    ? ValidationResult.Error($"[{Theme.Berry}]Введи да или нет[/]")
                    : ValidationResult.Success();
            });

        // Показываем запрос и получаем ответ.
        // ParseYesNo преобразует его в bool?:
        // true — подтверждение;
        // false — отказ или пустой ввод;
        // null — неизвестный ответ.
        //
        // Сравнение с true возвращает обычный bool.
        // Поэтому действие выполняется только при явном положительном ответе.
        return ParseYesNo(AnsiConsole.Prompt(prompt)) == true;
    }
