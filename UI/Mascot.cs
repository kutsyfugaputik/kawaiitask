// Подключаем пространство имён с моделями проекта.
// Здесь находится класс Project, содержащий список задач.
using KawaiiTasks.Models;

// Подключаем основную библиотеку Spectre.Console.
// Она позволяет оформлять текст, выводить цветные элементы и создавать интерфейс терминала.
using Spectre.Console;

// Подключаем пространство имён с компонентами для построения отображаемого содержимого.
using Spectre.Console.Rendering;

// Указываем пространство имён, к которому относится текущий файл.
// Класс Mascot является частью пользовательского интерфейса приложения.
namespace KawaiiTasks.UI;

// Перечисление Mood хранит возможные настроения талисмана.
// Каждое значение соответствует определённому состоянию проекта.
public enum Mood
{
    Sleepy,  // Сонное настроение: в проекте пока нет задач.
    Happy,   // Радостное настроение: задачи есть, но все сроки в порядке.
    Worried, // Обеспокоенное настроение: обнаружены просроченные задачи.
    Party    // Праздничное настроение: все задачи проекта выполнены.
}

/// <summary>
/// ASCII-талисман с короткими сообщениями о состоянии проекта.
/// Рисунки состоят только из обычных ASCII-символов: они гарантированно есть в любом шрифте терминала.
/// Класс отвечает за внешний вид талисмана, его настроение и приветственное сообщение.
/// </summary>
public static class Mascot
{
    // Массив фраз для сонного настроения.
    // Он используется, когда в проекте ещё нет ни одной задачи.
    private static readonly string[] Sleepy =
    {
        "Тут пока пусто. Давай добавим первую задачу?",
        "Я немного отдохну, пока ты придумываешь план."
    };

    // Массив поддерживающих фраз для обычного радостного настроения.
    // Эти сообщения отображаются, когда задачи существуют и просроченных задач нет.
    private static readonly string[] Happy =
    {
        "Ты отлично справляешься!",
        "Еще немного - и проект будет готов.",
        "Маленькие шаги тоже приближают к цели.",
        "Задача за задачей - и все получится!"
    };

    // Массив предупреждающих сообщений.
    // Используется, если в проекте есть задачи с истёкшим сроком выполнения.
    private static readonly string[] Worried =
    {
        "Есть просроченные задачи. Проверь сроки.",
        "Дедлайны близко. Давай расставим приоритеты."
    };

    // Массив праздничных сообщений.
    // Используется, когда все задачи проекта отмечены как выполненные.
    private static readonly string[] Party =
    {
        "Ура! Все задачи готовы! Отличная работа!",
        "Проект завершен. Можно праздновать результат!"
    };

    // Возвращает короткое текстовое изображение лица талисмана.
    // В зависимости от переданного настроения выбирается соответствующая ASCII-эмоция.
    // Выражение switch позволяет компактно обработать все варианты перечисления Mood.
    public static string Face(Mood mood) => mood switch
    {
        // Для сонного состояния возвращаем лицо с закрытыми глазами.
        Mood.Sleepy => "(-.-) zZ",

        // Для обеспокоенного состояния используем грустное выражение.
        Mood.Worried => "(T_T)",

        // Для праздничного состояния талисман изображён с поднятыми руками.
        Mood.Party => "(^_^)/",

        // Если настроение не совпало с предыдущими вариантами,
        // возвращаем стандартное радостное выражение.
        _ => "(^.^)"
    };

    // Возвращает более крупный ASCII-рисунок талисмана.
    // Рисунок состоит из нескольких строк, поэтому символы \n обозначают переходы на новую строку.
    public static string Art(Mood mood) => mood switch
    {
        // Рисунок для сонного настроения.
        // Символы формируют голову, глаза и нижнюю часть изображения.
        Mood.Sleepy => "  /\\_/\\\n ( -.- )\n  >   <", 

        // Рисунок для обеспокоенного настроения.
        // Отличается выражением лица с помощью символов T_T.
        Mood.Worried => "  /\\_/\\\n ( T_T )\n  >   <", 

        // Рисунок для праздничного настроения.
        // Символы по бокам нижней строки создают эффект поднятых рук.
        Mood.Party => "  /\\_/\\\n ( ^.^ )\n  > * <", 

        // Стандартный рисунок, используемый для остальных состояний.
        _ => "  /\\_/\\\n ( o.o )\n  >   <"
    };

    // Возвращает название цвета из темы оформления приложения.
    // Цвет зависит от настроения талисмана.
    // Значения берутся из класса Theme, чтобы оформление было единообразным.
    public static string ColorFor(Mood mood) => mood switch
    {
        // Для сонного настроения используется лавандовый цвет.
        Mood.Sleepy => Theme.Lavender,

        // Для обеспокоенного настроения используется ягодный цвет.
        Mood.Worried => Theme.Berry,

        // Для праздничного настроения используется лимонный цвет.
        Mood.Party => Theme.Lemon,

        // Для остальных состояний используется розовый цвет.
        _ => Theme.Pink
    };

    /// <summary>
    /// Определяет настроение талисмана на основе текущего состояния проекта.
    /// Сначала проверяется отсутствие задач, затем выполнение всех задач,
    /// после этого — наличие просроченных задач.
    /// Порядок проверок важен, поскольку от него зависит итоговое настроение.
    /// </summary>
    public static Mood MoodFor(Project project)
    {
        // Если список задач пуст, возвращаем сонное настроение.
        // Count показывает количество элементов в коллекции Tasks.
        if (project.Tasks.Count == 0)
            return Mood.Sleepy;

        // All проверяет, выполняется ли указанное условие для каждого элемента коллекции.
        // Если все задачи имеют IsDone == true, проект считается завершённым.
        if (project.Tasks.All(task => task.IsDone))
            return Mood.Party;

        // Any проверяет, существует ли хотя бы один элемент, удовлетворяющий условию.
        // Если хотя бы одна задача просрочена, талисман становится обеспокоенным.
        if (project.Tasks.Any(task => task.IsOverdue))
            return Mood.Worried;

        // Если задачи существуют, но все ещё не выполнены и просроченных нет,
        // возвращаем обычное радостное настроение.
        return Mood.Happy;
    }

    /// <summary>
    /// Выбирает случайную фразу из набора, соответствующего настроению талисмана.
    /// Random.Shared предоставляет общий генератор случайных чисел,
    /// который можно безопасно использовать из разных потоков.
    /// </summary>
    public static string Phrase(Mood mood)
    {
        // Выбираем массив сообщений в зависимости от переданного настроения.
        // Переменная pool будет ссылаться на один из четырёх массивов фраз.
        var pool = mood switch
        {
            // Для сонного настроения выбираем массив Sleepy.
            Mood.Sleepy => Sleepy,

            // Для обеспокоенного настроения выбираем массив Worried.
            Mood.Worried => Worried,

            // Для праздничного настроения выбираем массив Party.
            Mood.Party => Party,

            // Для остальных значений используем массив Happy.
            _ => Happy
        };

        // Next(pool.Length) генерирует случайный индекс от 0 до pool.Length - 1.
        // По этому индексу выбирается одна фраза из массива.
        // Благодаря этому при повторном отображении сообщения могут меняться.
        return pool[Random.Shared.Next(pool.Length)];
    }

    /// <summary>
    /// Создаёт приветственный блок для главного экрана приложения.
    /// Возвращает объект IRenderable, который можно передать компонентам Spectre.Console.
    /// </summary>
    public static IRenderable Greeting()
    {
        // Создаём объект Markup с ASCII-рисунком талисмана.
        // В качестве настроения передаём Happy, чтобы на приветствии талисман выглядел радостным.
        // Theme.E экранирует специальные символы разметки Spectre.Console,
        // чтобы рисунок отображался как обычный текст.
        // Конструкция [цвет]...[/] задаёт цвет содержимого.
        var art = new Markup($"[{Theme.Pink}]{Theme.E(Art(Mood.Happy))}[/]");

        // Создаём отдельный объект Markup для приветственного текста.
        // Markup позволяет использовать цветовую и текстовую разметку Spectre.Console.
        var text = new Markup(
            // Выводим приветствие жирным розовым текстом.
            $"[bold {Theme.Pink}]Привет! Я Нори-нори[/]\n" +

            // Добавляем описание назначения приложения серым цветом.
            "[grey]Твой помощник в мире больших проектов.\n" +

            // Продолжаем описание на следующей строке.
            "Следим за задачами, сроками и временем вместе![/]\n" +

            // Выводим мотивирующую фразу лавандовым цветом.
            $"[{Theme.Lavender}]Сегодня все получится. Начнем?[/]\n" +

            // Добавляем декоративный разделитель цветом Cocoa.
            $"[{Theme.Cocoa}]------------------------------[/]\n" +

            // Выводим заключительную подпись приветственного блока.
            $"[{Theme.Cocoa}]Это твой личный дневник проектов.[/]");

        // Создаём Grid — компонент Spectre.Console для размещения элементов в колонках.
        // В данном случае он нужен, чтобы поставить рисунок слева, а текст справа.
        // Сетка не создаёт видимых границ, поэтому элементы выглядят как единый блок.
        var grid = new Grid();

        // Добавляем первый столбец для изображения талисмана.
        // NoWrap = true запрещает переносить содержимое столбца на несколько строк.
        grid.AddColumn(new GridColumn { NoWrap = true });

        // Добавляем второй столбец для приветственного текста.
        // Его ширина рассчитывается Spectre.Console с учётом доступного пространства.
        grid.AddColumn();

        // Добавляем строку из двух элементов:
        // art помещается в первый столбец, text — во второй.
        grid.AddRow(art, text);

        // Передаём готовую сетку в Theme.Page.
        // Метод оформляет содержимое в общей стилистике приложения.
        // Параметры:
        // grid — содержимое страницы;
        // "ДОБРО ПОЖАЛОВАТЬ В ДНЕВНИК" — заголовок;
        // Theme.Pink — основной цвет оформления;
        // true — дополнительный параметр оформления страницы;
        // new Padding(3, 1) — внутренние отступы по горизонтали и вертикали.
        // Возвращаем готовый объект для последующего вывода в терминале.
        return Theme.Page(
            grid,
            "ДОБРО ПОЖАЛОВАТЬ В ДНЕВНИК",
            Theme.Pink,
            true,
            new Padding(3, 1));
    }
}