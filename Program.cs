
using System.Text;                  // Подключает классы для работы с текстом и кодировками, в частности UTF8Encoding.
using KawaiiTasks.Services;         // Подключает пространство имён с сервисами бизнес-логики приложения.
using KawaiiTasks.UI;               // Подключает пространство имён с компонентами пользовательского интерфейса.

// ===================== Точка входа приложения =====================
// Используются top-level statements (операторы верхнего уровня).
// Это возможность C#, позволяющая писать код запуска без явного объявления класса Program и метода Main.
// Компилятор автоматически формирует точку входа приложения.
// Последовательность выполнения важна: сначала настраивается консоль,
// затем создаются необходимые зависимости и запускается пользовательский интерфейс.

// Пытаемся изменить размеры окна классической консоли Windows (conhost).
// Метод TrySetSquareWindow() находится в классе ConsoleWindow.
// В современных терминалах, Linux и macOS изменение размеров может не поддерживаться.
ConsoleWindow.TrySetSquareWindow();

// Блок try используется для обработки возможных ошибок настройки консоли.
// Если терминал не поддерживает изменение кодировки или заголовка,
// программа продолжит работу без этих настроек.
try
{
    // Console.OutputEncoding задаёт кодировку данных, отправляемых программой в терминал.
    // UTF8Encoding(false) создаёт объект кодировки UTF-8 без BOM (Byte Order Mark).
    // BOM — специальная последовательность байтов в начале текстового потока.
    // Его отсутствие помогает избежать появления лишних символов при выводе текста.
    Console.OutputEncoding = new UTF8Encoding(false);

    // Console.InputEncoding задаёт кодировку символов, которые программа получает из терминала.
    // UTF-8 позволяет корректно обрабатывать русский текст и другие символы Unicode.
    Console.InputEncoding = new UTF8Encoding(false);

    // Console.IsOutputRedirected проверяет, перенаправлен ли стандартный вывод программы.
    // Например, вывод может направляться в текстовый файл вместо окна терминала.
    // В таком случае изменение заголовка окна не имеет смысла.
    if (!Console.IsOutputRedirected)

        // Console.Title задаёт заголовок окна консоли.
        // Название помогает пользователю определить, какое приложение запущено.
        Console.Title = "Kawaii Tasks - менеджер IT-проектов";
}

// Обрабатываем только ожидаемые ошибки настройки консоли.
// Фильтр when позволяет перехватывать исключение только в том случае,
// если оно относится к одному из перечисленных типов.
catch (Exception ex) when (
    ex is IOException or
    ArgumentException or
    InvalidOperationException or
    PlatformNotSupportedException)
{
    // Настройки консоли являются дополнительными и не влияют на основную логику приложения.
    // Поэтому при возникновении ошибки программа не прекращает выполнение.
}

// ===================== Создание зависимостей =====================
// На этом этапе вручную создаются объекты, необходимые для работы приложения.
// Такой подход называется Dependency Injection (внедрение зависимостей).
// Объекты передаются друг другу через конструкторы, а не создаются внутри каждого класса.
// Это упрощает тестирование, замену компонентов и разделение ответственности.

// Создаём объект JsonStorage, отвечающий за сохранение и загрузку данных.
// Этот компонент работает с JSON-файлом, в котором хранятся данные приложения.
var storage = new JsonStorage();

// Создаём ProjectService — сервис, содержащий основную бизнес-логику работы с проектами.
// В конструктор передаём storage, чтобы сервис мог обращаться к хранилищу данных.
// При создании сервиса также выполняется загрузка сохранённых данных из файла data.json.
var service = new ProjectService(storage);

// ===================== Запуск приложения =====================
// После создания зависимостей можно запускать пользовательский интерфейс.
// Отдельный блок try позволяет обработать ошибки, возникшие во время работы приложения.
try
{
    // Создаём объект App — главный компонент пользовательского интерфейса.
    // Первым параметром передаём service для взаимодействия с бизнес-логикой.
    // Вторым параметром передаём LoadWarning — предупреждение, которое могло появиться
    // при загрузке данных из хранилища.
    // LoadWarning читается после создания ProjectService, поскольку именно в процессе
    // инициализации сервиса выполняется загрузка данных.
    //
    // Метод Run() запускает основной цикл взаимодействия с пользователем.
    // Он отвечает за отображение интерфейса и обработку действий пользователя.
    new App(service, storage.LoadWarning).Run();
}

// Перехватываем непредвиденные исключения, которые не были обработаны
// внутри отдельных компонентов приложения.
catch (Exception ex)
{
    // Console.ResetColor() возвращает стандартные цвета текста и фона консоли.
    // Это необходимо, чтобы после аварийного завершения терминал не остался
    // с цветовым оформлением, установленным пользовательским интерфейсом.
    Console.ResetColor();

    // Console.Error представляет стандартный поток вывода ошибок.
    // В отличие от Console.WriteLine(), он предназначен для диагностических сообщений.
    Console.Error.WriteLine();

    // Выводим сообщение о критической ошибке.
    // Интерполяция строк ($) позволяет вставить текст исключения в сообщение.
    // ex.Message содержит описание ошибки без полного стека вызовов.
    Console.Error.WriteLine($"Критическая ошибка: {ex.Message}");

    // Устанавливаем код завершения приложения, равный 1.
    // Нулевой код обычно означает успешное завершение, ненулевой — наличие ошибки.
    // Операционная система и командная оболочка могут использовать этот код
    // для определения результата выполнения программы.
    Environment.ExitCode = 1;
}
