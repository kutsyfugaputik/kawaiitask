    // Проверяем, что каждая успешная операция изменения данных
    // приводит к сохранению информации в хранилище.
    public void EveryMutation_SavesData()
    {
        // Создаём сервис и получаем хранилище для подсчёта сохранений.
        var (service, storage) = NewService();

        // Создаём проект, в котором будут выполняться дальнейшие операции.
        var project = service.CreateProject("Проект", null);

        // Добавляем в проект участника команды с именем «Аня» и ролью «Тимлид».
        // Получаем созданного участника для дальнейшего использования.
        var member = service.AddMember(project, "Аня", "Тимлид");

        // Добавляем задачу в проект.
        // Указываем название, пустое описание, высокий приоритет,
        // тип задачи Bug, идентификатор исполнителя и отсутствие дополнительного значения.
        var task = service.AddTask(project, "Задача", "", Priority.High, TaskKind.Bug, member.Id, null);

        // Изменяем состояние задачи на InProgress, то есть «В работе».
        service.ChangeState(task, TaskState.InProgress);

        // Устанавливаем срок выполнения задачи на следующий день.
        // DateTime.Today возвращает сегодняшнюю дату без учёта времени,
        // а AddDays(1) прибавляет к ней один день.
        service.SetDeadline(task, DateTime.Today.AddDays(1));

        // Добавляем в задачу запись о затраченном времени.
        // Указываем 30 минут и комментарий «работа».
        service.LogTime(task, 30, "работа");

        // Снимаем назначенного исполнителя с задачи,
        // передавая null вместо объекта участника команды.
        service.Assign(project, task, null);

        // Выполняем изменение приоритета задачи с помощью метода Update().
        // Лямбда-выражение устанавливает низкий приоритет Low.
        service.Update(() => task.Priority = Priority.Low);

        // Удаляем созданную задачу из проекта.
        service.DeleteTask(project, task);

        // Удаляем участника команды из проекта.
        service.RemoveMember(project, member);

        // Проверяем общее количество сохранений.
        // 1 сохранение произошло при создании проекта,
        // ещё 9 сохранений — после каждой операции изменения данных выше.
        Assert.Equal(10, storage.SaveCount);
    }

