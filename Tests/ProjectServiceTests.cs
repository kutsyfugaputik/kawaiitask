    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что при создании ProjectService некорректные или устаревшие данные
    // автоматически приводятся к правильному состоянию.
    public void Constructor_NormalizesBrokenData()
    {
        // Создаём новое хранилище в оперативной памяти.
        var storage = new InMemoryStorage();

        // Создаём проект с идентификатором 7 и названием «Из файла».
        // Это имитирует ситуацию, когда проект уже был загружен из файла.
        var project = new Project { Id = 7, Name = "Из файла" };

        // Добавляем в проект задачу с идентификатором 10 и названием «Старая».
        // Указываем AssigneeId = 99, хотя участника с таким идентификатором не существует.
        project.Tasks.Add(new TaskItem { Id = 10, Title = "Старая", AssigneeId = 99 });

        // Добавляем подготовленный проект в коллекцию проектов хранилища.
        storage.Data.Projects.Add(project);

        // Устанавливаем следующий идентификатор проекта равным 1.
        // Это специально создаёт ошибочную ситуацию: счётчик меньше уже существующего ID 7.
        storage.Data.NextProjectId = 1;

        // Создаём сервис ProjectService и передаём ему хранилище с подготовленными некорректными данными.
        // Во время инициализации сервис должен проверить и нормализовать данные.
        var service = new ProjectService(storage);

        // Создаём новый проект с названием «Новый».
        // Сервис должен правильно определить следующий свободный идентификатор.
        var created = service.CreateProject("Новый", null);

        // Проверяем, что новому проекту присвоен идентификатор 8.
        // Он не должен получить 1, поскольку такой счётчик был устаревшим,
        // и не должен получить 7, поскольку этот идентификатор уже занят.
        Assert.Equal(8, created.Id);

        // Проверяем, что у задачи удалена ссылка на несуществующего исполнителя.
        // Индекс [0] обращается к первой задаче в коллекции Tasks.
        Assert.Null(project.Tasks[0].AssigneeId);

        // Проверяем, что следующий идентификатор задачи установлен в 11.
        // Поскольку существующая задача имеет ID 10,
        // следующая создаваемая задача должна получить ID 11.
        Assert.Equal(11, project.NextTaskId);
    }
