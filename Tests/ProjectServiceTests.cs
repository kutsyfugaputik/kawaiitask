    public void CreateProject_TrimsName_AssignsId_AndSaves()
    {
        // Создаём новый сервис и получаем используемое им хранилище.
        // Деконструкция кортежа позволяет сразу записать возвращённые объекты в две переменные.
        var (service, storage) = NewService();

        // Создаём проект, передавая название и описание с лишними пробелами по краям.
        var project = service.CreateProject("  Мой проект ", "  описание ");

        // Проверяем, что лишние пробелы в начале и конце названия были удалены.
        Assert.Equal("Мой проект", project.Name);

        // Проверяем, что лишние пробелы в начале и конце описания также были удалены.
        Assert.Equal("описание", project.Description);

        // Проверяем, что новому проекту автоматически присвоен идентификатор 1.
        Assert.Equal(1, project.Id);

        // Проверяем, что в коллекции проектов сервиса находится ровно один проект.
        Assert.Single(service.Projects);

        // Проверяем, что после создания проекта хранилище было вызвано для сохранения ровно один раз.
        Assert.Equal(1, storage.SaveCount);
