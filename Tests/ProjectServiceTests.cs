    // Проверяем, что если операция изменения данных внутри Update() вызывает исключение,
    // изменения не сохраняются в хранилище.
    public void Update_WhenChangeThrows_DoesNotSave()
    {
        // Создаём сервис и получаем его хранилище для подсчёта сохранений.
        var (service, storage) = NewService();

        // Создаём проект для проведения теста.
        var project = service.CreateProject("Проект", null);

        // Добавляем в проект задачу с названием «Задача».
        var task = service.AddTask(project, "Задача", "", Priority.Low, TaskKind.Chore, null, null);

        // Запоминаем количество сохранений до проверки ошибочной операции.
        var savesBefore = storage.SaveCount;

        // Передаём в Update() лямбда-выражение, которое пытается переименовать задачу в пустую строку.
        // Метод Rename() должен вызвать исключение KawaiiException,
