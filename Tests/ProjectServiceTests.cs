        // Проверяем, что после неудачного изменения количество сохранений не увеличилось.
        Assert.Equal(savesBefore, storage.SaveCount);

        // Проверяем, что первоначальное название задачи сохранилось
        // и не было заменено пустой строкой.
        Assert.Equal("Задача", task.Title);
    }

