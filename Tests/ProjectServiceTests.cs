    // InMemoryStorage используется для хранения данных в оперативной памяти без обращения к файлам.
    private static (ProjectService Service, InMemoryStorage Storage) NewService()
    {
        // Создаём новое хранилище, которое будет использоваться во время тестирования.
        var storage = new InMemoryStorage();

        // Создаём сервис ProjectService, передаём ему созданное хранилище
        // и возвращаем оба объекта в виде кортежа.
        return (new ProjectService(storage), storage);
    }

