    // Атрибут [Fact] указывает xUnit, что следующий метод является отдельным тестом без входных параметров.
    [Fact]
    // Проверяем, что загрузка данных при отсутствии файла возвращает пустые данные без предупреждения.
    public void Load_MissingFile_ReturnsEmptyData_WithoutWarning()
    {
        // Создаём временную папку для теста. При завершении использования объекта папка будет удалена.
        using var dir = new TempDir();

        // Получаем путь к файлу data.json внутри временной папки.
        var storage = new JsonStorage(dir.File("data.json"));

        // Вызываем загрузку данных из файла, которого ещё не существует.
        var data = storage.Load();

        // Проверяем, что список проектов пуст, поскольку файл с данными отсутствует.
        Assert.Empty(data.Projects);

        // Проверяем, что следующий идентификатор проекта начинается с единицы.
        Assert.Equal(1, data.NextProjectId);

        // Проверяем, что при отсутствии файла предупреждение не создаётся.
        Assert.Null(storage.LoadWarning);
    }

    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем, что после сохранения и повторной загрузки восстанавливаются все данные проекта.
    public void SaveThenLoad_RoundTripsEverything()
    {
        // Создаём временную папку, чтобы тест не изменял настоящие файлы приложения.
        using var dir = new TempDir();

        // Получаем путь к файлу data.json, в котором будут храниться данные.
        var path = dir.File("data.json");

        // Создаём объект AppData, представляющий все данные приложения.
        var data = new AppData();

        // Создаём проект с идентификатором, названием и описанием.
        var project = new Project { Id = 1, Name = "Проект «Зефирка»", Description = "Описание" };

        // Добавляем в проект участника команды с именем Аня и ролью Тимлид.
        var member = project.AddMember("Аня", "Тимлид");

        // Получаем текущую дату и прибавляем к ней пять дней для создания срока выполнения задачи.
        var deadline = DateTime.Today.AddDays(5);

        // Добавляем задачу с названием, подробностями, критическим приоритетом,
        // типом Bug, назначенным исполнителем и установленным сроком выполнения.
        var task = project.AddTask("Сделать макеты", "Подробности", Priority.Critical, TaskKind.Bug, member.Id, deadline);

        // Изменяем состояние задачи на Review (проверка).
        task.ChangeState(TaskState.Review);

        // Добавляем в историю учёта времени запись о 90 минутах работы с указанным описанием.
        task.LogTime(90, "первая сессия");

        // Добавляем созданный проект в общий список проектов приложения.
        data.Projects.Add(project);

        // Устанавливаем следующий идентификатор проекта равным двум,
        // поскольку проект с идентификатором 1 уже создан.
        data.NextProjectId = 2;

        // Создаём хранилище и сохраняем подготовленные данные в JSON-файл.
        new JsonStorage(path).Save(data);

        // Создаём новое хранилище и загружаем данные из только что сохранённого файла.
        var loaded = new JsonStorage(path).Load();

        // Проверяем, что после загрузки в списке находится ровно один проект,
        // и сохраняем ссылку на него в переменную p.
        var p = Assert.Single(loaded.Projects);

        // Проверяем, что название проекта сохранилось без изменений.
        Assert.Equal("Проект «Зефирка»", p.Name);

        // Проверяем, что значение следующего идентификатора проекта также сохранилось.
        Assert.Equal(2, loaded.NextProjectId);

        // Проверяем, что у проекта после загрузки находится ровно один участник команды.
        var m = Assert.Single(p.Team);

        // Проверяем, что имя участника команды сохранилось правильно.
        Assert.Equal("Аня", m.Name);

        // Проверяем, что роль участника команды сохранилась правильно.
        Assert.Equal("Тимлид", m.Role);

        // Проверяем, что у проекта после загрузки находится ровно одна задача.
        var t = Assert.Single(p.Tasks);

        // Проверяем, что название задачи сохранилось без изменений.
        Assert.Equal("Сделать макеты", t.Title);

        // Проверяем, что приоритет задачи после загрузки остался Critical.
        Assert.Equal(Priority.Critical, t.Priority);

        // Проверяем, что тип задачи после загрузки остался Bug.
        Assert.Equal(TaskKind.Bug, t.Kind);

        // Проверяем, что состояние задачи после загрузки осталось Review.
        Assert.Equal(TaskState.Review, t.State);

        // Проверяем, что идентификатор назначенного исполнителя сохранился правильно.
        Assert.Equal(member.Id, t.AssigneeId);

        // Проверяем, что установленный срок выполнения задачи сохранился.
        Assert.Equal(deadline, t.Deadline);

        // Проверяем, что количество затраченных минут сохранилось и равно 90.
        Assert.Equal(90, t.SpentMinutes);

        // Проверяем, что первая запись в журнале времени содержит исходное описание.
        Assert.Equal("первая сессия", t.TimeLog[0].Note);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что JSON-файл содержит читаемые названия перечислений и русские символы без лишнего экранирования.
    public void Save_WritesReadableJson_EnumsAsNames_AndCyrillicAsIs()
    {
        // Создаём временную папку для безопасного проведения теста.
        using var dir = new TempDir();

        // Получаем путь к JSON-файлу, в который будут записаны данные.
        var path = dir.File("data.json");

        // Создаём объект с данными приложения.
        var data = new AppData();

        // Создаём проект с идентификатором 1 и русскоязычным названием.
        var project = new Project { Id = 1, Name = "Русское имя" };

        // Добавляем задачу с высоким приоритетом и типом Docs.
        // Исполнитель и срок выполнения не назначаются, поэтому передаются значения null.
        project.AddTask("Задача", "", Priority.High, TaskKind.Docs, null, null);

        // Добавляем созданный проект в общий список проектов приложения.
        data.Projects.Add(project);

        // Сохраняем данные приложения в JSON-файл.
        new JsonStorage(path).Save(data);

        // Читаем всё содержимое сохранённого файла в виде обычной строки.
        var text = File.ReadAllText(path);

        // Проверяем, что русское название проекта записано непосредственно кириллицей,
        // а не преобразовано в последовательности вида \u04xx.
        Assert.Contains("Русское имя", text);

        // Проверяем, что значение перечисления Priority записано словом "High",
        // а не числовым значением.
        Assert.Contains("\"Priority\": \"High\"", text);

        // Проверяем, что значение перечисления Kind записано словом "Docs".
        Assert.Contains("\"Kind\": \"Docs\"", text);
    }

    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем, что хранилище самостоятельно создаёт отсутствующие папки и удаляет временный файл.
    public void Save_CreatesMissingFolders_AndLeavesNoTempFile()
    {
        // Создаём временную папку, которая будет автоматически удалена после завершения теста.
        using var dir = new TempDir();

        // Формируем путь к файлу data.json во вложенных папках a и b.
        // Эти папки изначально не существуют.
        var path = Path.Combine(dir.Path, "a", "b", "data.json");

        // Создаём хранилище и сохраняем в него пустые данные приложения.
        // При необходимости хранилище должно самостоятельно создать недостающие папки.
        new JsonStorage(path).Save(new AppData());

        // Проверяем, что после сохранения JSON-файл действительно появился по указанному пути.
        Assert.True(File.Exists(path));

        // Проверяем, что временный файл с расширением .tmp после завершения сохранения отсутствует.
        Assert.False(File.Exists(path + ".tmp"));
    }

    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем, что повторное сохранение заменяет содержимое предыдущего файла новыми данными.
    public void Save_Twice_OverwritesPreviousFile()
    {
        // Создаём временную папку для выполнения теста.
        using var dir = new TempDir();

        // Получаем путь к файлу data.json.
        var path = dir.File("data.json");

        // Создаём объект хранилища, который будет использоваться для двух сохранений.
        var storage = new JsonStorage(path);

        // Создаём пустые данные приложения.
        var data = new AppData();

        // Выполняем первое сохранение пустых данных в файл.
        storage.Save(data);

        // Добавляем в данные новый проект с идентификатором 1 и названием "Появился позже".
        data.Projects.Add(new Project { Id = 1, Name = "Появился позже" });

        // Выполняем второе сохранение, чтобы обновить содержимое существующего файла.
        storage.Save(data);

        // Загружаем данные из файла и проверяем, что в нём находится ровно один проект.
        // Это подтверждает, что повторное сохранение записало обновлённые данные.
        Assert.Single(new JsonStorage(path).Load().Projects);
    }

    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем обработку повреждённого JSON-файла, создание предупреждения и сохранение резервной копии.
    public void Load_CorruptFile_ReturnsEmptyData_SetsWarning_AndKeepsBackup()
    {
        // Создаём временную папку для тестирования обработки повреждённых данных.
        using var dir = new TempDir();

        // Получаем путь к файлу data.json.
        var path = dir.File("data.json");

        // Записываем в файл некорректную строку, которая не является правильным JSON.
        File.WriteAllText(path, "{ это не json ");

        // Создаём объект хранилища для работы с повреждённым файлом.
        var storage = new JsonStorage(path);

        // Пытаемся загрузить данные из повреждённого файла.
        var data = storage.Load();

        // Проверяем, что при ошибке загрузки приложение возвращает пустой список проектов.
        Assert.Empty(data.Projects);

        // Проверяем, что хранилище установило предупреждение о проблеме с загрузкой.
        Assert.NotNull(storage.LoadWarning);

        // Ищем в папке файлы резервных копий, название которых начинается с data.json.broken-.
        // Символ * означает любую последовательность символов после указанного префикса.
        var backups = Directory.GetFiles(dir.Path, "data.json.broken-*");

        // Проверяем, что была создана ровно одна резервная копия, и сохраняем её путь.
        var backup = Assert.Single(backups);

        // Проверяем, что в резервной копии сохранилось исходное содержимое повреждённого файла.
        Assert.Equal("{ это не json ", File.ReadAllText(backup)); // Проверяем, что исходные данные не потерялись.
    }

