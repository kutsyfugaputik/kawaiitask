    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем полный цикл работы приложения: создание данных, сохранение и восстановление после перезапуска.
    public void FullCycle_ServiceDataSurvivesRestart()
    {
        // Создаём временную папку, в которой будут храниться данные тестового приложения.
        using var dir = new TempDir();

        // Получаем путь к файлу, в который будут сохраняться данные приложения.
        var path = dir.File("data.json");

        // Создаём первый экземпляр ProjectService и подключаем к нему JSON-хранилище.
        // При создании сервиса данные загружаются из указанного файла.
        var first = new ProjectService(new JsonStorage(path));

        // Создаём новый проект через сервис, указывая его название и описание.
        var project = first.CreateProject("Переживёт перезапуск", "тест");

        // Добавляем участника команды через сервис и назначаем ему роль Разработчик.
        var member = first.AddMember(project, "Миша", "Разработчик");

        // Добавляем задачу в проект через сервис:
        // указываем название, описание, приоритет High, тип Feature,
        // идентификатор исполнителя и срок выполнения через два дня.
        first.AddTask(project, "Задача", "", Priority.High, TaskKind.Feature, member.Id, DateTime.Today.AddDays(2));

        // Создаём второй экземпляр сервиса с тем же путём к JSON-файлу.
        // Это имитирует повторный запуск приложения: новый сервис должен восстановить сохранённые данные.
        // «перезапуск программы» = новый сервис поверх того же файла
        var second = new ProjectService(new JsonStorage(path));

        // Проверяем, что после повторной загрузки в сервисе находится ровно один проект.
        var loaded = Assert.Single(second.Projects);

        // Проверяем, что название проекта сохранилось после перезапуска.
        Assert.Equal("Переживёт перезапуск", loaded.Name);

        // Проверяем, что в восстановленном проекте сохранился участник команды с именем Миша.
        Assert.Equal("Миша", Assert.Single(loaded.Team).Name);

        // Проверяем, что в восстановленном проекте сохранилась задача с названием "Задача".
        Assert.Equal("Задача", Assert.Single(loaded.Tasks).Title);

        // Проверяем, что следующий идентификатор задачи равен двум,
        // поскольку задача с идентификатором 1 уже была создана.
        Assert.Equal(2, loaded.NextTaskId);
    }
