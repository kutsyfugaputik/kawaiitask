    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем, что применение фильтрации и сортировки не изменяет исходный порядок задач проекта.
    public void Apply_DoesNotChangeProjectTaskOrder()
    {
        // Создаём демонстрационный проект.
        var project = Demo();

        // Получаем идентификаторы всех задач в исходном порядке
        // и сохраняем их в отдельный массив.
        var idsBefore = project.Tasks.Select(t => t.Id).ToArray();

        // Применяем сортировку по названию к задачам проекта.
        // Результат намеренно не сохраняется, поскольку здесь проверяется отсутствие
        // изменений в исходной коллекции project.Tasks.
        TaskQuery.Apply(project, new TaskFilter { Sort = SortKey.Title });

        // Повторно получаем идентификаторы задач проекта и сравниваем их с исходным массивом.
        // Если порядок не изменился, значит TaskQuery.Apply не сортирует исходную коллекцию напрямую.
        Assert.Equal(idsBefore, project.Tasks.Select(t => t.Id).ToArray());
    }
