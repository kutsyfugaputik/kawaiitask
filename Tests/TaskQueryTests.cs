    public void EmptyFilter_ReturnsAllTasks()
    {
        // Создаём демонстрационный проект с заранее подготовленными задачами.
        var project = Demo();

        // Применяем пустой фильтр к проекту.
        // Поскольку условия фильтрации не заданы, должны вернуться все задачи.
        var result = TaskQuery.Apply(project, new TaskFilter());

        // Проверяем, что количество найденных задач совпадает с количеством задач проекта.
        Assert.Equal(project.Tasks.Count, result.Count);
