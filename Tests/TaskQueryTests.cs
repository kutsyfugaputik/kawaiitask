    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем сортировку по приоритету: сначала наиболее важные задачи,
    // а при одинаковом приоритете — по возрастанию идентификатора.
    public void Sort_ByPriority_MostImportantFirst_TiesByIdAscending()
    {
        // Получаем демонстрационный проект и применяем сортировку по приоритету.
        var result = TaskQuery.Apply(Demo(), new TaskFilter { Sort = SortKey.Priority });

        // Перебираем результаты начиная со второго элемента,
        // чтобы сравнивать каждую задачу с предыдущей.
        for (var i = 1; i < result.Count; i++)
        {
            // Проверяем, что приоритет предыдущей задачи не меньше приоритета следующей.
            // Это означает, что задачи расположены от более высокого приоритета к более низкому.
            Assert.True(result[i - 1].Priority >= result[i].Priority);

            // Если приоритеты двух соседних задач одинаковые,
            // дополнительно проверяем порядок по идентификаторам.
            if (result[i - 1].Priority == result[i].Priority)

                // Проверяем, что идентификатор предыдущей задачи меньше идентификатора следующей.
                Assert.True(result[i - 1].Id < result[i].Id);
        }
    }

    // Атрибут [Fact] обозначает отдельный автоматический тест.
    [Fact]
    // Проверяем сортировку по сроку выполнения: ближайшие сроки должны находиться первыми,
    // а задачи без установленного срока — последними.
    public void Sort_ByDeadline_NearestFirst_WithoutDeadlineLast()
    {
        // Создаём новый пустой проект для проверки сортировки.
        var project = Make.NewProject();

        // Добавляем задачу без установленного срока выполнения.
        var noDeadline = Make.NewTask(project, "Без срока");

        // Добавляем задачу со сроком выполнения через десять дней.
        var far = Make.NewTask(project, "Далеко", deadline: DateTime.Today.AddDays(10));

        // Добавляем задачу со сроком выполнения через один день.
        var near = Make.NewTask(project, "Близко", deadline: DateTime.Today.AddDays(1));

        // Применяем к проекту сортировку по сроку выполнения.
        var result = TaskQuery.Apply(project, new TaskFilter { Sort = SortKey.Deadline });

        // Проверяем, что задачи расположены в правильном порядке:
        // сначала задача с ближайшим сроком, затем с более поздним сроком,
        // а последней — задача без срока выполнения.
        // Select получает идентификаторы задач, а ToArray преобразует результат в массив.
        Assert.Equal(new[] { near.Id, far.Id, noDeadline.Id }, result.Select(t => t.Id).ToArray());
    }

