    public void Sort_ByTime_MostTimeFirst()
    {
        // Получаем демонстрационный проект и сортируем задачи по затраченному времени.
        var result = TaskQuery.Apply(Demo(), new TaskFilter { Sort = SortKey.Time });

        // Проверяем, что первая задача имеет наибольшее затраченное время — 420 минут.
