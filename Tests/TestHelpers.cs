// Подключаем пространство имён Models, в котором находятся модели проекта,
// задачи, данные приложения и перечисления приоритетов и типов задач.
using KawaiiTasks.Models;

// Подключаем пространство имён Services, в котором объявлен интерфейс IStorage.
using KawaiiTasks.Services;

// Объявляем пространство имён, в котором располагаются автоматические тесты.
namespace KawaiiTasks.Tests;

/// <summary>
/// Хранилище в памяти: вместо файла просто считает, сколько раз вызвали Save.
/// </summary>
// Объявляем класс InMemoryStorage, который реализует интерфейс IStorage.
// Он имитирует обычное хранилище, но не записывает данные на диск.
public sealed class InMemoryStorage : IStorage
{
    // Свойство Data хранит данные приложения непосредственно в оперативной памяти.
    // set позволяет изменять содержимое хранилища.
    // new() создаёт новый пустой объект AppData при первоначальном создании хранилища.
    public AppData Data { get; set; } = new();

    // Счётчик SaveCount хранит количество вызовов метода Save.
    // private set означает, что изменять его можно только внутри самого класса.
    public int SaveCount { get; private set; }

    // Свойство Location возвращает строку "memory",
    // обозначающую, что данные находятся в памяти, а не в файле.
    public string Location => "memory";

    // Свойство LoadWarning всегда возвращает null,
    // поскольку это тестовое хранилище не обрабатывает ошибки чтения файлов.
    public string? LoadWarning => null;

    // Метод Load возвращает текущие данные, хранящиеся в свойстве Data.
    // Поскольку данные находятся в памяти, чтение файла не требуется.
    public AppData Load() => Data;

    // Метод Save принимает объект AppData, который необходимо сохранить.
    public void Save(AppData data)
    {
        // Заменяем текущие данные хранилища переданным объектом.
        Data = data;

        // Увеличиваем счётчик сохранений на единицу.
        // Это позволяет тестам проверить, сколько раз сервис вызывал сохранение.
        SaveCount++;
    }
}

/// <summary>
/// Временная папка, которая удаляется после теста (using var dir = new TempDir()).
/// </summary>
// Объявляем класс TempDir, который реализует интерфейс IDisposable.
// Он создаёт отдельную временную папку и удаляет её после завершения теста.
public sealed class TempDir : IDisposable
{
    // Свойство Path хранит полный путь к временной папке.
    // System.IO.Path.GetTempPath() возвращает системную папку для временных файлов.
    // "KawaiiTasksTests_" добавляется в начало имени, чтобы папку было легко распознать.
    // Guid.NewGuid() создаёт уникальный идентификатор, чтобы папки разных тестов не совпадали.
    // ToString("N") преобразует идентификатор в строку без дефисов.
    public string Path { get; } =
        System.IO.Path.Combine(System.IO.Path.GetTempPath(), "KawaiiTasksTests_" + Guid.NewGuid().ToString("N"));

    // Конструктор класса TempDir вызывается при создании объекта.
    // Directory.CreateDirectory(Path) создаёт временную папку по указанному пути.
    public TempDir() => Directory.CreateDirectory(Path);

    // Метод File принимает имя файла и возвращает полный путь к нему внутри временной папки.
    // System.IO.Path.Combine объединяет путь к папке и имя файла с учётом правил операционной системы.
    public string File(string name) => System.IO.Path.Combine(Path, name);

    // Метод Dispose вызывается при завершении использования объекта,
    // например автоматически при выходе из области действия using var dir.
    public void Dispose()
    {
        // Начинаем блок try, чтобы попытаться удалить временную папку вместе со всем её содержимым.
        try { Directory.Delete(Path, true); }

        // Перехватываем IOException, если при удалении возникла ошибка ввода-вывода.
        // Например, если какой-либо временный файл занят другой операцией.
        catch (IOException) { /* временный мусор не должен ронять тесты */ }

        // Перехватываем UnauthorizedAccessException, если программе не хватает прав для удаления папки.
        // Ошибка очистки временных файлов не должна приводить к падению теста.
        catch (UnauthorizedAccessException) { }
    }
}

/// <summary>
/// Готовые объекты для тестов.
/// </summary>
// Объявляем статический класс Make.
// Он содержит вспомогательные методы для быстрого создания проектов и задач в тестах.
// static означает, что методы можно вызывать без создания экземпляра класса.
public static class Make
{
    /// <summary>
    /// Проект с двумя участниками (Аня id=1, Миша id=2) и без задач.
    /// </summary>
    // Метод NewProject создаёт подготовленный проект для использования в тестах.
    public static Project NewProject()
    {
        // Создаём новый проект с идентификатором 1 и названием "Тестовый проект".
        var project = new Project { Id = 1, Name = "Тестовый проект" };

        // Добавляем в команду первого участника — Аню с ролью Тимлид.
        project.AddMember("Аня", "Тимлид");

        // Добавляем второго участника — Мишу с ролью Разработчик.
        project.AddMember("Миша", "Разработчик");

        // Возвращаем подготовленный проект с двумя участниками и без задач.
        return project;
    }

    // Метод NewTask создаёт новую задачу и добавляет её в переданный проект.
    // Параметры имеют значения по умолчанию, поэтому при вызове метода
    // необязательно указывать все аргументы.
    public static TaskItem NewTask(
        // Проект, в который необходимо добавить задачу.
        Project project,

        // Название задачи. По умолчанию используется строка "Задача".
        string title = "Задача",

        // Приоритет задачи. По умолчанию устанавливается Medium (средний).
        Priority priority = Priority.Medium,

        // Необязательный идентификатор исполнителя.
        // Если значение null, задача создаётся без назначенного исполнителя.
        int? assigneeId = null,

        // Необязательный срок выполнения задачи.
        // Если значение null, срок выполнения не устанавливается.
        DateTime? deadline = null)

        // Добавляем задачу в переданный проект.
        // В качестве описания передаётся пустая строка.
        // Тип задачи устанавливается Feature.
        // Остальные параметры передаются из аргументов метода.
        // Возвращается созданный объект TaskItem.
        => project.AddTask(title, "", priority, TaskKind.Feature, assigneeId, deadline);
}