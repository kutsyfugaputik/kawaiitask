    // Проверяем, что при удалении участника его задачи сохраняются,
    // но назначение этого участника в задачах снимается.
    public void RemoveMember_UnassignsTheirTasks_ButKeepsTasks()
    {
        // Создаём новый проект с помощью вспомогательного метода Make.NewProject().
        var project = Make.NewProject();

        // Получаем первого участника команды по индексу 0.
        // Индексация коллекции начинается с нуля.
        var anya = project.Team[0];

        // Создаём задачу и назначаем её участнику Ане.
        // Именованный аргумент assigneeId указывает идентификатор исполнителя.
        var task = Make.NewTask(project, assigneeId: anya.Id);

        // Удаляем участника Аню из команды проекта.
        project.RemoveMember(anya);

        // Проверяем, что удалённый участник больше не содержится в команде проекта.
        Assert.DoesNotContain(anya, project.Team);

        // Проверяем, что после удаления участника идентификатор исполнителя задачи сброшен в null.
        Assert.Null(task.AssigneeId);

        // Проверяем, что сама задача не была удалена и по-прежнему находится в проекте.
        Assert.Contains(task, project.Tasks);

        // Проверяем, что при отсутствии исполнителя метод AssigneeName() возвращает символ «-».
        Assert.Equal("-", project.AssigneeName(task));
    }

