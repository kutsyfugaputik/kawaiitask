    // Проверяем, что слишком длинное имя участника или его роль вызывают исключение,
    // при этом неудачные попытки не увеличивают счётчик идентификаторов.
    public void AddMember_TooLongNameOrRole_Throws_AndDoesNotConsumeId()
    {
        // Создаём новый объект проекта.
        var project = new Project();

        // Проверяем, что добавление участника с именем длиннее допустимого ограничения
        // вызывает исключение KawaiiException.
        // new string('я', Project.MaxMemberName + 1) создаёт строку,
        // состоящую из символов «я», длина которой на один символ больше разрешённой.
        Assert.Throws<KawaiiException>(() => project.AddMember(new string('я', Project.MaxMemberName + 1), null));

        // Проверяем, что добавление участника с ролью длиннее допустимого ограничения
        // также вызывает исключение KawaiiException.
        // new string('р', Project.MaxRole + 1) создаёт слишком длинную строку для роли.
        Assert.Throws<KawaiiException>(() => project.AddMember("Аня", new string('р', Project.MaxRole + 1)));

        // Повторно добавляем участника с корректным именем и без указанной роли.
        // Сохраняем созданный объект в переменную ok.
        var ok = project.AddMember("Аня", null);

        // Проверяем, что участнику присвоен идентификатор 1.
        // Это означает, что предыдущие неудачные попытки не использовали номера.
        Assert.Equal(1, ok.Id); // Неудачные попытки не «сжигают» номера.
    }

