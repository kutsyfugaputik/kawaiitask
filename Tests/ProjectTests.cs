    [Fact]

    // Проверяем, что при добавлении участников им автоматически назначаются
    // возрастающие идентификаторы и стандартная роль, если она не указана.
    public void AddMember_AssignsIncreasingIds_AndDefaultRole()
    {
        // Создаём новый объект проекта с начальными значениями по умолчанию.
        var project = new Project();

        // Добавляем участника с именем «Аня» без указанной роли.
        // Вместо роли передаётся null, поэтому должна использоваться стандартная роль.
        var a = project.AddMember("Аня", null);

        // Добавляем второго участника с именем «Миша».
        // Строка из пробелов также должна восприниматься как отсутствие роли.
        var b = project.AddMember("Миша", "   ");

        // Проверяем, что первому участнику присвоен идентификатор 1.
        Assert.Equal(1, a.Id);

        // Проверяем, что второму участнику присвоен следующий идентификатор 2.
        Assert.Equal(2, b.Id);

        // Проверяем, что при отсутствии указанной роли первому участнику назначается роль «Участник».
        Assert.Equal("Участник", a.Role);

        // Проверяем, что при передаче строки из пробелов второму участнику также назначается роль «Участник».
        Assert.Equal("Участник", b.Role);
    }

