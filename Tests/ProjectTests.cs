    [Fact]

    // Проверяем, что при добавлении задач увеличиваются их идентификаторы
    // и правильно сохраняются переданные параметры.
    public void AddTask_IncrementsIds_AndStoresFields()
    {
        // Создаём новый проект с помощью вспомогательного метода Make.NewProject().
        var project = Make.NewProject();

        // Получаем сегодняшнюю дату и прибавляем к ней два дня.
        // Полученная дата будет использоваться в качестве срока выполнения задачи.
        var deadline = DateTime.Today.AddDays(2);

        // Добавляем первую задачу с названием, описанием, высоким приоритетом,
        // типом Bug, идентификатором исполнителя 1 и установленным сроком выполнения.
        var first = project.AddTask("Первая", "Описание", Priority.High, TaskKind.Bug, 1, deadline);

        // Добавляем вторую задачу с названием «Вторая» через вспомогательный метод Make.NewTask().
        var second = Make.NewTask(project, "Вторая");

        // Проверяем, что первой задаче присвоен идентификатор 1.
        Assert.Equal(1, first.Id);

        // Проверяем, что второй задаче присвоен следующий идентификатор 2.
        Assert.Equal(2, second.Id);

        // Проверяем, что первой задаче правильно назначен высокий приоритет.
        Assert.Equal(Priority.High, first.Priority);

        // Проверяем, что тип первой задачи сохранён как Bug.
        Assert.Equal(TaskKind.Bug, first.Kind);

        // Проверяем, что первой задаче назначен исполнитель с идентификатором 1.
        Assert.Equal(1, first.AssigneeId);

        // Проверяем, что срок выполнения первой задачи совпадает с переданной датой.
        Assert.Equal(deadline, first.Deadline);

        // Проверяем, что новая задача автоматически получает состояние Todo (к выполнению).
        Assert.Equal(TaskState.Todo, first.State);
    }

