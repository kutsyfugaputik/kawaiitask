    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что метод Normalize() исправляет счётчики идентификаторов
    // и удаляет ссылки на исполнителей, которых больше нет в команде.
    public void Normalize_RepairsCountersAndDanglingAssignees()
    {
        // Создаём новый проект с помощью вспомогательного метода Make.NewProject().
        var project = Make.NewProject();

        // Создаём задачу и назначаем ей участника с идентификатором 1.
        var task = Make.NewTask(project, assigneeId: 1);

        // Имитируем повреждённые или некорректные данные, которые могли быть прочитаны из файла.
        // Сбрасываем счётчик следующего идентификатора задачи на значение 1,
        // хотя задача с таким идентификатором уже существует.
        project.NextTaskId = 1;

        // Сбрасываем счётчик следующего идентификатора участника на значение 1,
        // хотя участники с такими идентификаторами уже существуют.
        project.NextMemberId = 1;

        // Изменяем идентификатор исполнителя на 777.
        // Такого участника нет в команде проекта, поэтому ссылка становится недействительной.
        task.AssigneeId = 777;

        // Вызываем метод Normalize(), который должен исправить обнаруженные несоответствия.
        project.Normalize();

        // Проверяем, что следующий идентификатор задачи равен 2.
        // Максимальный существующий ID задачи равен 1, поэтому следующий ID должен быть 1 + 1.
        Assert.Equal(2, project.NextTaskId); // Максимальный ID задачи (1) + 1.

        // Проверяем, что следующий идентификатор участника равен 3.
        // Максимальный ID участника равен 2, поэтому следующий ID должен быть 2 + 1.
        Assert.Equal(3, project.NextMemberId); // Максимальный ID участника (2) + 1.

        // Проверяем, что ссылка на несуществующего исполнителя была удалена.
        Assert.Null(task.AssigneeId);
    }

