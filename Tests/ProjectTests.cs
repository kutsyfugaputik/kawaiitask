    // Проверяем, что процент выполнения проекта рассчитывается
    // на основании количества выполненных задач.
    public void Progress_IsPercentOfDoneTasks()
    {
        // Создаём новый проект.
        var project = Make.NewProject();

        // Проверяем, что у проекта без задач прогресс равен 0%.
        // Это также позволяет убедиться, что при отсутствии задач
