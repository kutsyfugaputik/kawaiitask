    [Fact]

    // Проверяем, что нормализация общих данных приложения
    // исправляет счётчик идентификаторов проектов.
    public void AppData_Normalize_RepairsProjectCounter()
    {
        // Создаём объект AppData с начальным значением следующего ID проекта, равным 1.
        // Это имитирует ситуацию, когда счётчик идентификаторов оказался устаревшим.
        var data = new AppData { NextProjectId = 1 };

        // Добавляем в коллекцию проект с идентификатором 5 и названием «Старый».
        data.Projects.Add(new Project { Id = 5, Name = "Старый" });

        // Вызываем метод Normalize(), который должен проверить и исправить данные приложения.
        data.Normalize();

        // Проверяем, что следующий идентификатор проекта установлен в 6.
        // Поскольку существующий проект имеет ID 5, следующий свободный ID должен быть 5 + 1.
        Assert.Equal(6, data.NextProjectId);
    }
