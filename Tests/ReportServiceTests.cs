    // Проверяем, что отчёт по демонстрационному проекту содержит заранее известные показатели.
    public void Build_DemoProject_MatchesKnownNumbers()
    {
        // Создаём демонстрационный проект с идентификатором 1
        // и формируем по нему отчёт со статистикой.
        var report = ReportService.Build(DemoData.Create(1));

        // Проверяем, что общее количество задач в демонстрационном проекте равно 9.
        Assert.Equal(9, report.Total);

        // Проверяем, что из девяти задач выполнены две.
        Assert.Equal(2, report.Done);

        // Проверяем, что процент выполнения рассчитывается как отношение двух выполненных задач
        // к общему количеству девяти задач, умноженное на 100.
        // Последний аргумент 6 указывает точность сравнения до шести знаков после запятой.
        Assert.Equal(2 * 100.0 / 9, report.Percent, 6);

        // Проверяем, что общее время выполнения задач составляет 1020 минут.
        // Значение складывается из времени отдельных записей:
        // 240 + 180 + 300 + 150 + 90 + 60 = 1020 минут.
        Assert.Equal(1020, report.TotalMinutes); // 240 + 180 + 300 + 150 + 90 + 60.

        // Проверяем, что одна задача не имеет назначенного исполнителя.
        // Это задача «Документация API».
        Assert.Equal(1, report.Unassigned); // «Документация API».

        // Проверяем, что общее количество баллов проекта равно 70.
        // Две выполненные задачи с высоким приоритетом в срок дают по 35 баллов каждая.
        Assert.Equal(70, report.CandyPoints); // Две выполненные High-задачи в срок: 2 x 35.

        // Проверяем, что четыре задачи находятся в состоянии Todo — «К выполнению».
        Assert.Equal(4, report.ByState[TaskState.Todo]);

        // Проверяем, что две задачи находятся в состоянии InProgress — «В работе».
        Assert.Equal(2, report.ByState[TaskState.InProgress]);

        // Проверяем, что одна задача находится в состоянии Review — «На проверке».
        Assert.Equal(1, report.ByState[TaskState.Review]);

        // Проверяем, что две задачи находятся в состоянии Done — «Выполнено».
        Assert.Equal(2, report.ByState[TaskState.Done]);

        // Проверяем, что в проекте имеется одна задача с низким приоритетом.
        Assert.Equal(1, report.ByPriority[Priority.Low]);

        // Проверяем, что в проекте имеются две задачи со средним приоритетом.
        Assert.Equal(2, report.ByPriority[Priority.Medium]);

        // Проверяем, что в проекте имеются четыре задачи с высоким приоритетом.
        Assert.Equal(4, report.ByPriority[Priority.High]);

        // Проверяем, что в проекте имеются две задачи с критическим приоритетом.
        Assert.Equal(2, report.ByPriority[Priority.Critical]);

        // Получаем единственную просроченную задачу из отчёта.
        // Assert.Single() одновременно проверяет, что в коллекции находится ровно один элемент.
        var overdue = Assert.Single(report.Overdue); // Намеренно просроченная задача «Настроить CI».

        // Проверяем, что найденная просроченная задача называется «Настроить CI».
        Assert.Equal("Настроить CI", overdue.Title);
    }

