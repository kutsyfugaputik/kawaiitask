    public void TaskPoints_DoneLate_NoBonus()
    {
        // Создаём новый тестовый проект.
        var project = Make.NewProject();

        // Добавляем задачу с высоким приоритетом без установленного срока выполнения.
        var task = Make.NewTask(project, priority: Priority.High);

        // Напрямую устанавливаем срок выполнения на три дня раньше сегодняшней даты.
