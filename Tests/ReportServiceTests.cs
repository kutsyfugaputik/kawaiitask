        // 420, 300 и 150 минут именно в таком порядке.
        // Select() извлекает значение SpentMinutes из каждого элемента коллекции.
        // t — текущий элемент коллекции, то есть статистика отдельного участника.
        // ToArray() преобразует полученную последовательность значений в массив.
