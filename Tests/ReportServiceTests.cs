        var b = Make.NewTask(project, priority: Priority.High);

        // Добавляем третью задачу с критическим приоритетом.
        // Её состояние не изменяется, поэтому она остаётся невыполненной и баллов не приносит.
        Make.NewTask(project, priority: Priority.Critical); // Не выполнена.

        // Переводим первую задачу в состояние Done.
        a.ChangeState(TaskState.Done);

        // Переводим вторую задачу в состояние Done.
        b.ChangeState(TaskState.Done);

        // Проверяем, что общее количество баллов равно 40:
        // 10 баллов за низкий приоритет и 30 баллов за высокий приоритет.
