    // Проверяем, что статистика отдельного участника команды рассчитывается правильно.
    public void Build_DemoProject_MemberStatsAreCorrect()
    {
        // Создаём демонстрационный проект и формируем по нему отчёт.
        var report = ReportService.Build(DemoData.Create(1));

        // Находим участника с именем «Миша» в списке статистики команды.
        // Single() возвращает один элемент, удовлетворяющий условию.
        // Если подходящих элементов нет или их несколько, проверка завершится ошибкой.
        // m — текущий элемент статистики участника.
        var misha = report.Members.Single(m => m.Name == "Миша");

        // Проверяем, что на Мишу назначено три задачи.
        Assert.Equal(3, misha.Assigned);

        // Проверяем, что из трёх назначенных задач одна выполнена.
        Assert.Equal(1, misha.Done);

        // Проверяем, что общее время работы Миши составляет 540 минут.
        // Оно складывается из 300 + 150 + 90 минут.
        Assert.Equal(540, misha.Minutes); // 300 + 150 + 90.

        // Проверяем, что в статистике присутствуют четыре участника команды.
        Assert.Equal(4, report.Members.Count);

        // Проверяем, что сумма назначенных участникам задач равна общему количеству задач
        // за вычетом задач, у которых отсутствует исполнитель.
        // Sum() складывает значения Assigned всех участников.
        // m — текущий участник статистики.
        Assert.Equal(report.Total - report.Unassigned, report.Members.Sum(m => m.Assigned));
    }

