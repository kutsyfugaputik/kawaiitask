// Подключаем пространство имён Models, в котором находятся классы задач,
// перечисления состояний и приоритетов, а также пользовательские исключения.
using KawaiiTasks.Models;

// Объявляем пространство имён для автоматических тестов приложения.
namespace KawaiiTasks.Tests;

// Объявляем класс TaskItemTests, содержащий тесты для проверки поведения отдельной задачи.
public class TaskItemTests
{
    // Атрибут [Fact] обозначает обычный тест без входных параметров.
    [Fact]
    // Проверяем, что метод Rename удаляет лишние пробелы в начале и конце названия задачи.
    public void Rename_TrimsSpaces()
    {
        // Создаём новый объект задачи со значениями по умолчанию.
        var task = new TaskItem();

        // Устанавливаем название задачи с лишними пробелами по краям.
        task.Rename("  Сделать отчёт  ");

        // Проверяем, что в названии остался только текст без пробелов по краям.
        Assert.Equal("Сделать отчёт", task.Title);
    }

    // Атрибут [Theory] обозначает параметризованный тест,
    // который будет выполнен несколько раз с разными входными значениями.
    [Theory]

    // Передаём значение null: название задачи отсутствует.
    [InlineData(null)]

    // Передаём пустую строку: название не содержит символов.
    [InlineData("")]

    // Передаём строку только из пробелов: после удаления пробелов название станет пустым.
    [InlineData("    ")]

    // Проверяем, что при попытке установить пустое название возникает исключение.
    public void Rename_EmptyTitle_Throws(string? title)
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Проверяем, что попытка переименовать задачу в null, пустую строку
        // или строку из пробелов вызывает исключение KawaiiException.
        Assert.Throws<KawaiiException>(() => task.Rename(title));
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем ограничение максимальной длины названия задачи.
    public void Rename_MaxLengthIsAllowed_OneMoreIsNot()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Создаём строку из символов "а" длиной ровно TaskItem.MaxTitle
        // и устанавливаем её в качестве названия задачи.
        task.Rename(new string('а', TaskItem.MaxTitle));

        // Проверяем, что название максимально допустимой длины успешно сохранилось.
        Assert.Equal(TaskItem.MaxTitle, task.Title.Length);

        // Создаём строку, длина которой на один символ превышает допустимый предел,
        // и проверяем, что попытка установить такое название вызывает исключение.
        Assert.Throws<KawaiiException>(() => task.Rename(new string('а', TaskItem.MaxTitle + 1)));
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что неудачная попытка переименования не изменяет прежнее название задачи.
    public void Rename_Failure_KeepsOldTitle()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Устанавливаем корректное первоначальное название задачи.
        task.Rename("Старое");

        // Пытаемся установить пустое название и проверяем, что возникает исключение.
        Assert.Throws<KawaiiException>(() => task.Rename(""));

        // Проверяем, что после ошибки прежнее название осталось без изменений.
        Assert.Equal("Старое", task.Title);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем обработку null и превышения максимально допустимой длины описания.
    public void Describe_NullBecomesEmpty_TooLongThrows()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Передаём null в метод Describe для проверки обработки отсутствующего описания.
        task.Describe(null);

        // Проверяем, что вместо null в описании сохраняется пустая строка.
        Assert.Equal("", task.Description);

        // Создаём строку, длина которой превышает максимально допустимую длину описания,
        // и проверяем, что метод Describe вызывает исключение KawaiiException.
        Assert.Throws<KawaiiException>(() => task.Describe(new string('x', TaskItem.MaxDescription + 1)));
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что установка срока выполнения в прошлом запрещена.
    public void SetDeadline_PastDate_Throws()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Получаем вчерашнюю дату и проверяем, что попытка установить её как срок выполнения
        // вызывает исключение KawaiiException.
        Assert.Throws<KawaiiException>(() => task.SetDeadline(DateTime.Today.AddDays(-1)));
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что сегодняшний и будущие сроки разрешены, а время суток не сохраняется.
    public void SetDeadline_TodayAndFuture_AreAllowed_AndTimeIsDropped()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Устанавливаем срок выполнения на сегодняшний день.
        task.SetDeadline(DateTime.Today);

        // Проверяем, что срок выполнения успешно установлен на сегодняшнюю дату.
        Assert.Equal(DateTime.Today, task.Deadline);

        // Устанавливаем срок на три дня вперёд с дополнительным временем 15:00.
        // Метод должен сохранить только дату, отбросив часы и минуты.
        task.SetDeadline(DateTime.Today.AddDays(3).AddHours(15));

        // Проверяем, что в сроке выполнения осталась только дата через три дня,
        // без времени суток.
        Assert.Equal(DateTime.Today.AddDays(3), task.Deadline);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что передача null удаляет ранее установленный срок выполнения.
    public void SetDeadline_Null_ClearsDeadline()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Устанавливаем срок выполнения на следующий день.
        task.SetDeadline(DateTime.Today.AddDays(1));

        // Передаём null, чтобы очистить срок выполнения задачи.
        task.SetDeadline(null);

        // Проверяем, что после очистки срок выполнения отсутствует.
        Assert.Null(task.Deadline);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что переход в состояние Done устанавливает дату завершения,
    // а возврат к другому состоянию очищает её.
    public void ChangeState_ToDone_SetsCompletedAt_AndBackClearsIt()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Переводим задачу в состояние Done (выполнена).
        task.ChangeState(TaskState.Done);

        // Проверяем, что свойство IsDone показывает выполнение задачи.
        Assert.True(task.IsDone);

        // Проверяем, что после завершения задачи установлена дата CompletedAt.
        Assert.NotNull(task.CompletedAt);

        // Переводим задачу обратно в состояние InProgress (в работе).
        task.ChangeState(TaskState.InProgress);

        // Проверяем, что после смены состояния задача больше не считается выполненной.
        Assert.False(task.IsDone);

        // Проверяем, что дата завершения очищена.
        Assert.Null(task.CompletedAt);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что повторная установка состояния Done не изменяет первоначальную дату завершения.
    public void ChangeState_SameStateAgain_DoesNotOverwriteCompletedAt()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Переводим задачу в состояние Done, чтобы установить дату завершения.
        task.ChangeState(TaskState.Done);

        // Сохраняем первоначальное значение даты завершения в отдельную переменную.
        var first = task.CompletedAt;

        // Повторно устанавливаем то же самое состояние Done.
        task.ChangeState(TaskState.Done);

        // Проверяем, что дата завершения не изменилась после повторного вызова метода.
        Assert.Equal(first, task.CompletedAt);
    }

    // Атрибут [Theory] обозначает параметризованный тест.
    [Theory]

    // Проверяем нулевое количество минут: такое значение недопустимо.
    [InlineData(0)]

    // Проверяем отрицательное количество минут: такое значение также недопустимо.
    [InlineData(-5)]

    // Проверяем значение 1441, которое превышает максимально допустимые 1440 минут.
    [InlineData(1441)]

    // Проверяем, что недопустимое количество минут вызывает исключение,
    // а некорректная запись не добавляется в журнал времени.
    public void LogTime_OutOfRange_Throws(int minutes)
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Передаём недопустимое количество минут и проверяем,
        // что метод LogTime вызывает исключение KawaiiException.
        Assert.Throws<KawaiiException>(() => task.LogTime(minutes));

        // Проверяем, что после ошибки журнал учёта времени остался пустым.
        Assert.Empty(task.TimeLog);
    }

    // Атрибут [Theory] обозначает параметризованный тест.
    [Theory]

    // Проверяем минимальное допустимое значение — одну минуту.
    [InlineData(1)]

    // Проверяем обычное значение — 90 минут.
    [InlineData(90)]

    // Проверяем максимальное допустимое значение — 1440 минут.
    [InlineData(1440)]

    // Проверяем, что граничные допустимые значения принимаются,
    // запись добавляется в журнал, а пробелы в заметке удаляются.
    public void LogTime_BoundaryValues_AreAccepted(int minutes)
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Добавляем запись о затраченном времени с переданным количеством минут.
        // В заметке намеренно присутствуют пробелы по краям для проверки их удаления.
        task.LogTime(minutes, "  заметка ");

        // Проверяем, что в журнале учёта времени появилась ровно одна запись.
        Assert.Single(task.TimeLog);

        // Проверяем, что общее затраченное время соответствует переданному значению.
        Assert.Equal(minutes, task.SpentMinutes);

        // Проверяем, что текст заметки сохранён без лишних пробелов по краям.
        Assert.Equal("заметка", task.TimeLog[0].Note);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что заметка, превышающая допустимую длину, не принимается.
    public void LogTime_TooLongNote_Throws()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Добавляем 10 минут работы, но передаём заметку длиной на один символ больше максимальной.
        // Проверяем, что метод LogTime вызывает исключение KawaiiException.
        Assert.Throws<KawaiiException>(() => task.LogTime(10, new string('x', TaskItem.MaxNote + 1)));
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем, что затраченное время рассчитывается как сумма всех записей журнала.
    public void SpentMinutes_IsSumOfAllEntries()
    {
        // Создаём новый объект задачи.
        var task = new TaskItem();

        // Добавляем первую запись о 30 минутах работы.
        task.LogTime(30);

        // Добавляем вторую запись о 45 минутах работы.
        task.LogTime(45);

        // Проверяем, что общее затраченное время равно сумме двух записей: 30 + 45 = 75 минут.
        Assert.Equal(75, task.SpentMinutes);
    }

    // Атрибут [Fact] обозначает отдельный тест.
    [Fact]
    // Проверяем правила определения просроченной задачи.
    public void IsOverdue_OnlyWhenNotDoneAndDeadlineIsBeforeToday()
    {
        // Создаём задачу, срок выполнения которой установлен на вчерашний день.
        // Инициализатор объекта позволяет задать свойство Deadline сразу при создании.
        var task = new TaskItem { Deadline = DateTime.Today.AddDays(-1) };

        // Проверяем, что задача с прошедшим сроком и незавершённым состоянием считается просроченной.
        Assert.True(task.IsOverdue);

        // Переводим задачу в состояние Done (выполнена).
        task.ChangeState(TaskState.Done);

        // Проверяем, что завершённая задача больше не считается просроченной,
        // даже если её срок выполнения уже прошёл.
        Assert.False(task.IsOverdue);

        // Создаём задачу со сроком выполнения на сегодняшний день.
        var today = new TaskItem { Deadline = DateTime.Today };

        // Проверяем, что задача со сроком на сегодня ещё не считается просроченной.
        Assert.False(today.IsOverdue);

        // Создаём задачу без установленного срока выполнения.
        var noDeadline = new TaskItem();

        // Проверяем, что задача без срока выполнения не считается просроченной.
        Assert.False(noDeadline.IsOverdue);
    }
}