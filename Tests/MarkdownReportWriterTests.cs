// Подключаем пространство имён Models, в котором находятся модели проекта и задач.
using KawaiiTasks.Models;

// Подключаем пространство имён Services, в котором находятся классы для работы с отчётами и данными.
using KawaiiTasks.Services;

// Объявляем пространство имён для тестов проекта KawaiiTasks.
namespace KawaiiTasks.Tests;

// Объявляем публичный класс с тестами для класса MarkdownReportWriter.
public class MarkdownReportWriterTests
{
    // Создаём вспомогательный метод для формирования отчёта и получения его содержимого.
    // TempDir dir — временная папка, в которой будут создаваться файлы.
    // Project project — проект, по которому необходимо сформировать отчёт.
    // out string text — выходной параметр, в который записывается текст созданного отчёта.
    // string — тип возвращаемого значения, в данном случае путь к файлу.
    private static string WriteReport(TempDir dir, Project project, out string text)
    {
        // Создаём объект MarkdownReportWriter и указываем папку reports,
        // в которой должен сохраняться сформированный отчёт.
        var writer = new MarkdownReportWriter(dir.File("reports"));

        // Формируем данные отчёта с помощью ReportService.Build()
        // и передаём их методу Write() для сохранения в Markdown-файл.
        var path = writer.Write(ReportService.Build(project));

        // Проверяем, что метод Write() успешно вернул путь к созданному файлу,
        // а не null.
        Assert.NotNull(path);

        // Считываем весь текст созданного файла и записываем его
        // в выходную переменную text.
        // Оператор ! сообщает компилятору, что здесь значение path не является null.
        text = File.ReadAllText(path!);

        // Возвращаем путь к созданному файлу отчёта.
        // Оператор ! указывает, что возвращаемое значение не равно null.
        return path!;
    }

    // Атрибут Fact обозначает обычный отдельный тест, который не требует входных параметров.
    [Fact]

    // Проверяем, что при создании отчёта автоматически создаются папка и файл
    // с правильным названием.
    public void Write_CreatesFolderAndFile_WithExpectedName()
    {
        // Создаём временную директорию для выполнения теста.
        // При завершении работы она будет автоматически удалена.
        using var dir = new TempDir();

        // Создаём отчёт на основе демонстрационного проекта с идентификатором 1.
        // out _ означает, что текст отчёта нам не нужен, поэтому мы его не сохраняем.
        var path = WriteReport(dir, DemoData.Create(1), out _);

        // Проверяем, что файл отчёта действительно существует по указанному пути.
        Assert.True(File.Exists(path));

        // Проверяем, что файл находится именно в папке reports внутри временной директории.
        Assert.Equal(dir.File("reports"), Path.GetDirectoryName(path));

        // Получаем только имя файла без полного пути к нему.
        var name = Path.GetFileName(path);

        // Проверяем, что имя файла начинается с report_.
        Assert.StartsWith("report_", name);

        // Проверяем, что файл имеет расширение .md (формат Markdown).
        Assert.EndsWith(".md", name);
    }

    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что отчёт сохраняется в кодировке UTF-8 с BOM,
    // чтобы Windows Блокнот правильно распознавал кириллицу.
    public void Write_UsesUtf8WithBom_ForWindowsNotepad()
    {
        // Создаём временную директорию для хранения тестового отчёта.
        using var dir = new TempDir();

        // Формируем отчёт для демонстрационного проекта с идентификатором 1.
        // Текст отчёта не сохраняем, так как для проверки нужны байты файла.
        var path = WriteReport(dir, DemoData.Create(1), out _);

        // Считываем содержимое файла в виде массива байтов.
        var bytes = File.ReadAllBytes(path);

        // Проверяем, что размер файла больше трёх байтов,
        // поскольку далее необходимо проверить наличие BOM.
        Assert.True(bytes.Length > 3);

        // Проверяем, что первые три байта файла соответствуют маркеру BOM кодировки UTF-8.
        // Значения EF BB BF обозначают наличие BOM в начале файла.
        Assert.Equal(new byte[] { 0xEF, 0xBB, 0xBF }, bytes.Take(3).ToArray());
    }

    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что отчёт содержит сводную информацию, команду и таблицы задач.
    public void Write_ContainsSummaryTeamAndTaskTables()
    {
        // Создаём временную директорию для сохранения отчёта.
        using var dir = new TempDir();

        // Формируем отчёт для демонстрационного проекта.
        // Его текст записываем в переменную text для последующей проверки.
        WriteReport(dir, DemoData.Create(1), out var text);

        // Проверяем, что в отчёте присутствует заголовок раздела «Сводка».
        Assert.Contains("## Сводка", text);

        // Проверяем, что в сводке указано общее количество задач — 9.
        Assert.Contains("| Всего задач | 9 |", text);

        // Проверяем, что в сводке указано количество просроченных задач — 1.
        Assert.Contains("| Просрочено | 1 |", text);

        // Проверяем, что в отчёте присутствует раздел «Команда».
        Assert.Contains("## Команда", text);

        // Проверяем наличие раздела со списком всех задач.
        Assert.Contains("## Все задачи", text);

        // Проверяем наличие раздела с просроченными задачами.
        Assert.Contains("## ! Просроченные задачи", text);

        // Проверяем, что в отчёте присутствует задача «Настроить CI».
        Assert.Contains("Настроить CI", text);
    }

    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что даже для пустого проекта создаётся корректный отчёт,
    // но необязательные разделы в нём отсутствуют.
    public void Write_EmptyProject_StillProducesValidReport_WithoutOptionalSections()
    {
        // Создаём временную директорию для сохранения отчёта.
        using var dir = new TempDir();

        // Создаём новый пустой проект с названием «Пустой».
        // Формируем для него отчёт и сохраняем текст в переменную text.
        WriteReport(dir, new Project { Name = "Пустой" }, out var text);

        // Проверяем, что в отчёте указано нулевое количество задач.
        Assert.Contains("| Всего задач | 0 |", text);

        // Проверяем, что раздел «Команда» отсутствует,
        // поскольку в пустом проекте нет участников команды.
        Assert.DoesNotContain("## Команда", text);

        // Проверяем, что раздел с просроченными задачами отсутствует,
        // поскольку в пустом проекте нет задач.
        Assert.DoesNotContain("Просроченные задачи", text);
    }

    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что символ вертикальной черты экранируется,
    // чтобы он не нарушал структуру таблиц Markdown.
    public void Write_EscapesPipeCharacters_SoTablesDoNotBreak()
    {
        // Создаём временную директорию для теста.
        using var dir = new TempDir();

        // Создаём новый тестовый проект с помощью вспомогательного класса Make.
        var project = Make.NewProject();

        // Добавляем в проект задачу с названием A|B,
        // в котором присутствует символ вертикальной черты.
        Make.NewTask(project, "A|B");

        // Формируем отчёт и сохраняем его содержимое в переменную text.
        WriteReport(dir, project, out var text);

        // Проверяем, что символ вертикальной черты был экранирован в Markdown.
        // Двойная обратная косая черта в строковом литерале C#
        // обозначает один символ обратной косой черты в итоговом тексте.
        Assert.Contains("A\\|B", text);
    }

    // Атрибут Fact обозначает отдельный тест без входных параметров.
    [Fact]

    // Проверяем, что при повторном создании отчёта первый файл не перезаписывается,
    // а для второго файла добавляется числовой суффикс.
    public void Write_SameReportTwice_DoesNotOverwrite_AddsNumericSuffix()
    {
        // Создаём временную директорию для хранения отчётов.
        using var dir = new TempDir();

        // Создаём объект MarkdownReportWriter и указываем папку reports.
        var writer = new MarkdownReportWriter(dir.File("reports"));

        // Формируем данные отчёта на основе демонстрационного проекта с идентификатором 1.
        var report = ReportService.Build(DemoData.Create(1));

        // Создаём первый файл отчёта и сохраняем его путь в переменную first.
        var first = writer.Write(report);

        // Повторно сохраняем тот же отчёт и получаем путь второго файла.
        // Второй файл должен получить другое имя, чтобы не перезаписать первый.
        var second = writer.Write(report);

        // Проверяем, что пути первого и второго файлов отличаются.
        Assert.NotEqual(first, second);

        // Проверяем, что имя второго файла заканчивается на _1.md.
        Assert.EndsWith("_1.md", second);

        // Проверяем, что первый файл отчёта по-прежнему существует.
        Assert.True(File.Exists(first));

        // Проверяем, что второй файл отчёта также был успешно создан.
        Assert.True(File.Exists(second));
    }

    // Атрибут Theory обозначает параметризованный тест,
    // который будет выполнен несколько раз с разными входными данными.
    [Theory]

    // Первый вариант входных данных: название содержит символы,
    // которые могут быть недопустимыми в имени файла Windows.
    [InlineData("Проект: <Тест>/1?")]

    // Второй вариант входных данных: зарезервированное системное имя CON.
    [InlineData("CON")]

    // Третий вариант входных данных: название состоит только из символов *.
    [InlineData("***")]

    // Проверяем, что название проекта безопасно преобразуется для использования в имени файла.
    // string projectName — название проекта, передаваемое в тест.
    public void Write_ProjectNameIsMadeSafeForFileSystem(string projectName)
    {
        // Создаём временную директорию для выполнения теста.
        using var dir = new TempDir();

        // Создаём новый проект с переданным названием projectName.
        // Формируем отчёт и не сохраняем его текст, так как он не требуется для проверки.
        var path = WriteReport(dir, new Project { Name = projectName }, out _);

        // Получаем имя созданного файла без полного пути к нему.
        var name = Path.GetFileName(path);

        // Проверяем, что в имени файла отсутствуют недопустимые для текущей
        // операционной системы символы.
        // Path.GetInvalidFileNameChars() возвращает массив запрещённых символов.
        // IndexOfAny() ищет наличие хотя бы одного такого символа.
        // Значение меньше 0 означает, что недопустимые символы не найдены.
        // Второй аргумент name выводится как дополнительная информация при ошибке теста.
        Assert.True(name.IndexOfAny(Path.GetInvalidFileNameChars()) < 0, name);

        // Проверяем, что файл отчёта действительно существует.
        Assert.True(File.Exists(path));
    }
}