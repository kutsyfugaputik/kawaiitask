
namespace KawaiiTasks.Models; // Указывает пространство имён, к которому относится класс TimeEntry.

/// <summary>
/// Запись о затраченном на задачу времени (одна сессия работы).
/// </summary>
public class TimeEntry
{
    /// <summary>
    /// Когда работали (для записей из фокус-таймера — момент сохранения).
    /// </summary>
    // Хранит дату и время, к которым относится запись.
    // DateTime.Now устанавливает текущее локальное время по умолчанию.
    public DateTime Date { get; set; } = DateTime.Now;

    /// <summary>
    /// Длительность в минутах, от 1 до 1440 (24 часа).
    /// Границы проверяет TaskItem.LogTime.
    /// </summary>
    // Хранит продолжительность рабочей сессии в минутах.
    // Проверка допустимого диапазона выполняется методом LogTime класса TaskItem.
    public int Minutes { get; set; }

    // Содержит дополнительную заметку о выполненной работе.
    // Например, описание того, над какой частью задачи работали.
    // По умолчанию используется пустая строка.
    public string Note { get; set; } = "";
}
