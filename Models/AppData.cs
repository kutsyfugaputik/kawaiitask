
// Объявляем пространство имён, к которому относится модель AppData.
// Пространство имён Models объединяет классы, предназначенные для хранения и представления данных приложения.
namespace KawaiiTasks.Models;

// XML-документация класса.
// Такие комментарии отображаются в подсказках IDE и могут использоваться при генерации документации проекта.
/// <summary>
/// Корневая модель данных приложения.
/// Весь объект AppData вместе с вложенными объектами сериализуется в JSON-файл.
/// Это позволяет сохранять все данные приложения одним вызовом метода сохранения.
/// </summary>
public class AppData
{
    // XML-документация свойства NextProjectId.
    /// <summary>
    /// Хранит следующий свободный идентификатор проекта.
    /// Значение увеличивается при создании проектов, чтобы идентификаторы не повторялись.
    /// </summary>

    // Свойство хранит идентификатор, который будет присвоен следующему создаваемому проекту.
    // get позволяет получить текущее значение, set — изменить его.
    // Значение 1 устанавливается по умолчанию при создании нового объекта AppData.
    public int NextProjectId { get; set; } = 1;

    // Коллекция всех проектов приложения.
    // List<Project> — типизированный список, в котором каждый элемент является объектом Project.
    // get позволяет получать список, set — заменять его.
    // new() создаёт пустой список при инициализации объекта AppData.
    public List<Project> Projects { get; set; } = new();

    // XML-документация метода Normalize.
    /// <summary>
    /// Проверяет и приводит загруженные данные к согласованному состоянию.
    /// Метод устраняет проблемы с отсутствующими списками и некорректным счётчиком ID.
    /// Также запускает нормализацию каждого проекта.
    /// </summary>

    // Метод Normalize не возвращает значение (void).
    // Его задача — проверить и при необходимости исправить состояние текущего объекта.
    // Обычно вызывается после загрузки данных из JSON-файла.
    public void Normalize()
    {
        // Оператор ??= проверяет значение Projects на null.
        // Если список отсутствует, вместо null создаётся новый пустой список.
        // Это предотвращает ошибки при последующей работе с коллекцией проектов.
        Projects ??= new();

        // Select(p => p.Id) преобразует коллекцию проектов в последовательность их идентификаторов.
        // p — текущий проект, а p.Id — его уникальный идентификатор.
        // DefaultIfEmpty(0) возвращает значение 0, если список проектов пуст.
        // Max() определяет наибольший существующий идентификатор проекта.
        // Результат сохраняется в переменную maxId с помощью var.
        var maxId = Projects.Select(p => p.Id).DefaultIfEmpty(0).Max();

        // Math.Max() возвращает большее из двух чисел.
        // Сравниваем текущее значение NextProjectId с maxId + 1.
        // Если сохранённый счётчик меньше следующего свободного ID,
        // исправляем его, чтобы при создании проекта не возникло повторения идентификаторов.
        NextProjectId = Math.Max(NextProjectId, maxId + 1);

        // foreach последовательно перебирает все проекты в коллекции Projects.
        // Переменная project представляет текущий объект Project на каждой итерации.
        foreach (var project in Projects)

            // Вызываем Normalize() у текущего проекта.
            // Это позволяет проверить и исправить вложенные данные самого проекта,
            // например его список задач и другие связанные свойства.
            // Таким образом, нормализация выполняется не только для AppData,
            // но и для каждого проекта внутри него.
            project.Normalize();
    }
}
