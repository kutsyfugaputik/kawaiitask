
// Объявляем пространство имён KawaiiTasks.Models.
// В нём размещаются модели данных и вспомогательные типы,
// которые используются для описания проектов и задач.
namespace KawaiiTasks.Models;

// XML-документация перечисления Priority.
// Она отображается в подсказках IDE при использовании данного типа.
/// <summary>
/// Перечисление приоритетов задач.
/// Числовые значения определяют уровень важности задачи.
// Значения также могут использоваться при сортировке и расчёте баллов.
/// </summary>

// enum (enumeration) позволяет задать ограниченный набор именованных значений.
// Каждое значение соответствует определённому уровню приоритета.
public enum Priority
{
    // Низкий приоритет.
    // Числовое значение 1 используется для сортировки и расчётов.
    Low = 1,

    // Средний приоритет.
    // Числовое значение 2 указывает на стандартную важность задачи.
    Medium = 2,

    // Высокий приоритет.
    // Числовое значение 3 обозначает задачу повышенной важности.
    High = 3,

    // Критический приоритет.
    // Числовое значение 4 обозначает наиболее срочную задачу.
    Critical = 4
}

// XML-документация перечисления TaskState.
/// <summary>
/// Перечисление возможных состояний задачи.
/// Порядок объявления значений соответствует порядку колонок на канбан-доске.
/// </summary>

// TaskState определяет этап выполнения задачи в рабочем процессе.
// В отличие от Priority, значения не имеют явно заданных чисел.
// По умолчанию C# присваивает им целочисленные значения начиная с 0.
public enum TaskState
{
    // Задача создана, но её выполнение ещё не началось.
    // Значение по умолчанию — 0.
    Todo,

    // Задача находится в процессе выполнения.
    // Значение — 1.
    InProgress,

    // Задача передана на проверку.
    // Значение — 2.
    Review,

    // Работа над задачей завершена.
    // Значение — 3.
    Done
}

// XML-документация перечисления TaskKind.
/// <summary>
/// Перечисление типов задач IT-проекта.
/// Позволяет классифицировать задачи по их назначению.
/// </summary>

// TaskKind ограничивает набор доступных категорий задач.
// Благодаря перечислению вместо произвольного текста
// в программе используются заранее определённые значения.
public enum TaskKind
{
    // Feature — новая функциональность или возможность приложения.
    Feature,

    // Bug — ошибка или неисправность, которую необходимо исправить.
    Bug,

    // Chore — техническая или вспомогательная задача.
    Chore,

    // Docs — задача, связанная с созданием или обновлением документации.
    Docs
}

// XML-документация статического класса EnumText.
/// <summary>
/// Содержит методы расширения для преобразования значений перечислений
/// в понятные пользователю русскоязычные подписи.
/// ASCII-префиксы позволяют сохранить единообразие отображения
/// в различных терминалах и средах выполнения.
/// </summary>

// static означает, что класс не предназначен для создания экземпляров.
// EnumText объединяет вспомогательные методы форматирования перечислений.
public static class EnumText
{
    // Метод расширения для перечисления Priority.
    // Ключевое слово this перед типом параметра позволяет вызывать метод
    // непосредственно у значения Priority, например priority.Text().
    // Тип string означает, что результатом работы метода будет текстовая строка.
    // Switch expression (выражение switch) выбирает подпись в зависимости от значения приоритета.
    public static string Text(this Priority value) => value switch
    {
        // Если приоритет Low, возвращаем подпись с ASCII-префиксом LOW.
        Priority.Low => "LOW - Низкий",

        // Если приоритет Medium, возвращаем подпись MED.
        Priority.Medium => "MED - Средний",

        // Если приоритет High, возвращаем подпись HIGH.
        Priority.High => "HIGH - Высокий",

        // Если приоритет Critical, возвращаем подпись URGENT.
        Priority.Critical => "URGENT - Срочно!",

        // Символ _ обозначает любое значение, которое не совпало с предыдущими вариантами.
        // ToString() преобразует неизвестное значение перечисления в обычную строку.
        _ => value.ToString()
    };

    // Метод расширения для перечисления TaskState.
    // Позволяет получать текстовое представление состояния задачи через вызов state.Text().
    // Выражение switch сопоставляет значение состояния с соответствующей подписью.
    public static string Text(this TaskState value) => value switch
    {
        // Состояние Todo: задача ожидает начала выполнения.
        TaskState.Todo => "TODO - Ждет",

        // Состояние InProgress: задача находится в работе.
        TaskState.InProgress => "WORK - В работе",

        // Состояние Review: задача ожидает проверки.
        TaskState.Review => "REVIEW - Проверка",

        // Состояние Done: задача выполнена.
        TaskState.Done => "DONE - Готово",

        // Если передано неизвестное значение, возвращаем его стандартное текстовое представление.
        _ => value.ToString()
    };

    // Метод расширения для перечисления TaskKind.
    // Преобразует категорию задачи в понятную пользователю текстовую подпись.
    // Вызывать метод можно непосредственно у значения TaskKind через kind.Text().
    public static string Text(this TaskKind value) => value switch
    {
        // Feature обозначает задачу по добавлению новой функциональности.
        TaskKind.Feature => "FEATURE - Фича",

        // Bug обозначает задачу по исправлению ошибки.
        TaskKind.Bug => "BUG - Баг",

        // Chore обозначает техническую или рутинную работу.
        TaskKind.Chore => "CHORE - Рутина",

        // Docs обозначает работу с документацией.
        TaskKind.Docs => "DOCS - Документация",

        // Для неизвестных значений возвращаем стандартное название перечисления.
        _ => value.ToString()
    };
}
