
// Подключаем пространство имён для работы с атрибутами сериализации JSON.
// JsonIgnore позволяет исключить отдельные свойства объекта из сохранения в JSON-файл.
using System.Text.Json.Serialization;

// Объявляем пространство имён KawaiiTasks.Models.
// Класс Project относится к моделям предметной области приложения.
namespace KawaiiTasks.Models;

// XML-документация класса Project.
/// <summary>
/// Представляет IT-проект, содержащий информацию о проекте, команду участников и задачи.
/// Отвечает за управление связанными объектами и проверку правил предметной области.
/// </summary>

// Объявляем публичный класс Project.
// Каждый экземпляр класса представляет отдельный проект в приложении.
// Класс объединяет данные проекта и методы для управления его содержимым.
public class Project
{
    // Максимально допустимая длина имени участника команды.
    // const означает, что значение является постоянным и не может изменяться во время выполнения программы.
    // Значение используется при проверке данных в методе AddMember().
    public const int MaxMemberName = 40;

    // Максимально допустимая длина названия роли участника.
    // Ограничение используется при добавлении нового участника в команду.
    public const int MaxRole = 30;

    // Уникальный идентификатор проекта.
    // int используется для хранения целого числа.
    // get позволяет получить ID, set — изменить его.
    public int Id { get; set; }

    // Название проекта.
    // Пустая строка устанавливается по умолчанию, чтобы свойство не содержало null.
    public string Name { get; set; } = "";

    // Текстовое описание проекта.
    // Может содержать дополнительную информацию о назначении и целях проекта.
    // По умолчанию описание пустое.
    public string Description { get; set; } = "";

    // Дата и время создания проекта.
    // DateTime.Now возвращает текущие локальные дату и время компьютера.
    // Инициализатор выполняется при создании нового объекта Project.
    public DateTime CreatedAt { get; set; } = DateTime.Now;

    // Список участников команды проекта.
    // List<Member> означает, что коллекция содержит объекты типа Member.
    // new() создаёт пустой список при создании проекта.
    public List<Member> Team { get; set; } = new();

    // Список задач, относящихся к данному проекту.
    // Каждый элемент коллекции представляет объект TaskItem.
    // При создании проекта список задач изначально пуст.
    public List<TaskItem> Tasks { get; set; } = new();

    // Счётчик следующего идентификатора задачи.
    // Начальное значение равно 1.
    // Счётчик сохраняется в JSON, чтобы после перезапуска приложения
    // новые задачи не получали ID ранее созданных и удалённых задач.
    public int NextTaskId { get; set; } = 1;

    // Счётчик следующего идентификатора участника команды.
    // ID участников формируются отдельно для каждого проекта.
    // Значение сохраняется в JSON и позволяет продолжать нумерацию после перезапуска.
    public int NextMemberId { get; set; } = 1;

    // XML-документация вычисляемого свойства Progress.
    /// <summary>
    /// Возвращает процент выполненных задач проекта.
    /// Значение вычисляется на основании общего количества задач и числа завершённых задач.
    /// Не сохраняется в JSON, поскольку может быть рассчитано повторно.
    /// </summary>

    // Атрибут JsonIgnore запрещает сериализатору включать свойство Progress в JSON-файл.
    // Это свойство является вычисляемым, поэтому хранить его отдельно не требуется.
    [JsonIgnore]

    // Вычисляемое свойство Progress возвращает процент выполнения проекта.
    // double используется для хранения чисел с плавающей точкой,
    // поскольку результат расчёта может содержать дробную часть.
    // Оператор => позволяет записать выражение свойства без отдельного блока get.
    public double Progress =>

        // Проверяем, содержит ли список Tasks хотя бы одну задачу.
        // Если задач нет, возвращаем 0, чтобы избежать деления на ноль.
        // Если задачи есть, вычисляем процент выполненных задач.
        Tasks.Count == 0 ? 0 :

        // Tasks.Count(t => t.IsDone) подсчитывает количество выполненных задач.
        // Count — общее количество задач в проекте.
        // Умножение на 100.0 переводит отношение в проценты.
        // Число 100.0 используется для получения дробного результата.
        Tasks.Count(t => t.IsDone) * 100.0 / Tasks.Count;

    // XML-документация метода AddMember.
    /// <summary>
    /// Добавляет нового участника в команду проекта.
    /// Проверяет корректность имени и роли, а также отсутствие дубликатов имён.
    /// При успешном добавлении назначает участнику уникальный идентификатор.
    /// </summary>

    // Метод добавляет участника в список Team и возвращает созданный объект Member.
    // string? означает, что параметр может содержать строку или значение null.
    // Параметр name содержит имя нового участника.
    // Параметр role содержит его роль в команде.
    public Member AddMember(string? name, string? role)
    {
        // Оператор ?? заменяет null на пустую строку.
        // Trim() удаляет пробелы и другие пробельные символы в начале и конце строки.
        // Результат сохраняется в локальную переменную value.
        var value = (name ?? "").Trim();

        // Проверяем, осталось ли имя пустым после удаления пробелов.
        // Если длина строки равна нулю, добавление участника запрещается.
        // throw прерывает выполнение метода и выбрасывает пользовательское исключение.
        if (value.Length == 0)

            // KawaiiException используется для передачи понятной пользователю ошибки.
            throw new KawaiiException("Имя участника не может быть пустым.");

        // Проверяем, не превышает ли длина имени установленное ограничение.
        // MaxMemberName содержит максимально допустимое количество символов — 40.
        if (value.Length > MaxMemberName)

            // При превышении ограничения выбрасываем исключение с указанием допустимой длины.
            // Интерполяция $ позволяет вставить значение константы в текст сообщения.
            throw new KawaiiException($"Имя слишком длинное (максимум {MaxMemberName} символов).");

        // Team.Any() проверяет, существует ли хотя бы один участник с таким же именем.
        // Лямбда-выражение m => обращается к каждому участнику списка Team.
        // string.Equals() сравнивает два имени с учётом выбранного режима сравнения.
        // StringComparison.OrdinalIgnoreCase выполняет сравнение без учёта регистра.
        // Поэтому имена "Александр" и "АЛЕКСАНДР" считаются одинаковыми.
        if (Team.Any(m => string.Equals(m.Name, value, StringComparison.OrdinalIgnoreCase)))

            // Запрещаем добавление участника с уже существующим именем.
            // В сообщение включается имя, которое пытались добавить.
            throw new KawaiiException($"Участник '{value}' уже есть в команде.");

        // Подготавливаем название роли участника.
        // IsNullOrWhiteSpace() проверяет, является ли строка null, пустой
        // или состоящей только из пробельных символов.
        // Если роль не указана, используется значение "Участник".
        // В противном случае Trim() удаляет лишние пробелы по краям.
        var roleValue = string.IsNullOrWhiteSpace(role) ? "Участник" : role.Trim();

        // Проверяем, не превышает ли название роли установленную длину.
        // MaxRole содержит максимально допустимое количество символов — 30.
        if (roleValue.Length > MaxRole)

            // Если название роли слишком длинное, выбрасываем пользовательское исключение.
            throw new KawaiiException($"Название роли слишком длинное (максимум {MaxRole} символов).");

        // Создаём новый объект Member — участника команды проекта.
        // Конструкция инициализатора объекта позволяет сразу присвоить значения свойствам.
        var member = new Member
        {
            // Присваиваем участнику текущий свободный ID.
            // Оператор ++ увеличивает NextMemberId на единицу после получения его значения.
            // Благодаря этому следующий участник получит другой идентификатор.
            Id = NextMemberId++,

            // Сохраняем проверенное и очищенное от лишних пробелов имя участника.
            Name = value,

            // Сохраняем подготовленное название роли.
            Role = roleValue
        };

        // Добавляем созданный объект Member в коллекцию участников проекта.
        Team.Add(member);

        // Возвращаем созданный объект участника.
        // Это позволяет вызывающему коду получить его ID, имя и роль.
        return member;
    }

    // XML-документация метода RemoveMember.
    /// <summary>
    /// Удаляет участника из команды проекта.
    /// Перед удалением снимает его назначение со всех связанных задач,
    /// чтобы не осталось ссылок на отсутствующего участника.
    /// </summary>

    // Метод принимает объект Member, который необходимо удалить.
    // void означает, что метод не возвращает результат.
    public void RemoveMember(Member member)
    {
        // Перебираем только те задачи, у которых исполнитель совпадает с ID удаляемого участника.
        // Where() фильтрует коллекцию Tasks по заданному условию.
        // t представляет текущую задачу, а t.AssigneeId — ID назначенного исполнителя.
        // Результатом является последовательность подходящих задач.
        foreach (var task in Tasks.Where(t => t.AssigneeId == member.Id))

            // Сбрасываем назначенного исполнителя.
            // null означает, что задача больше никому не назначена.
            // Это предотвращает сохранение некорректной связи с удалённым участником.
            task.AssigneeId = null;

        // Удаляем переданный объект участника из списка Team.
        // Remove() возвращает true, если элемент был найден и удалён,
        // и false, если такого элемента в коллекции не было.
        Team.Remove(member);
    }

    // XML-документация метода AddTask.
    /// <summary>
    /// Создаёт новую задачу в проекте.
    /// Перед созданием проверяет существование назначенного исполнителя.
    /// Проверка и заполнение полей выполняются до увеличения счётчика ID,
    /// чтобы не расходовать идентификаторы при неудачном создании задачи.
    /// </summary>

    // Метод AddTask создаёт задачу и возвращает объект TaskItem.
    // title — название задачи, description — её описание.
    // priority — приоритет задачи из перечисления Priority.
    // kind — категория задачи из перечисления TaskKind.
    // assigneeId — необязательный идентификатор исполнителя.
    // DateTime? deadline — необязательная дата и время завершения задачи.
    // Знак ? у значений int и DateTime позволяет передавать null.
    public TaskItem AddTask(
        string? title,
        string? description,
        Priority priority,
        TaskKind kind,
        int? assigneeId,
        DateTime? deadline)
    {
        // Проверяем, был ли указан исполнитель.
        // HasValue возвращает true, если assigneeId содержит числовое значение,
        // и false, если он равен null.
        // Если ID указан, вызываем FindMember() для поиска участника в команде.
        // Если исполнитель не найден, метод FindMember() вернёт null.
        if (assigneeId.HasValue && FindMember(assigneeId) is null)

            // Запрещаем создание задачи с несуществующим исполнителем.
            throw new KawaiiException("Такого исполнителя нет в команде.");

        // Создаём новый объект TaskItem.
        // Id получает текущее значение NextTaskId без его немедленного увеличения.
        // Priority и Kind заполняются значениями, переданными в метод.
        // Остальные свойства задачи устанавливаются через соответствующие методы ниже.
        var task = new TaskItem { Id = NextTaskId, Priority = priority, Kind = kind };

        // Устанавливаем название задачи через метод Rename().
        // Этот метод выполняет собственную проверку корректности названия.
        // При ошибке он выбрасывает KawaiiException.
        task.Rename(title);

        // Устанавливаем описание задачи через метод Describe().
        // Метод отвечает за проверку и сохранение текста описания.
        task.Describe(description);

        // Устанавливаем срок выполнения задачи через метод SetDeadline().
        // Метод отвечает за проверку допустимости указанной даты.
        task.SetDeadline(deadline);

        // Назначаем задаче ID исполнителя.
        // Если assigneeId равен null, задача остаётся без исполнителя.
        task.AssigneeId = assigneeId;

        // Увеличиваем счётчик следующего ID задачи.
        // Эта операция выполняется только после успешного прохождения проверок.
        NextTaskId++;

        // Добавляем полностью подготовленную задачу в список Tasks.
        Tasks.Add(task);

        // Возвращаем созданную задачу вызывающему коду.
        return task;
    }

    // Удаляет переданную задачу из коллекции Tasks.
    // Краткая форма записи метода с оператором => эквивалентна обычному блоку с фигурными скобками.
    // Remove() возвращает true, если задача была найдена и удалена.
    // void означает, что результат удаления вызывающему коду не передаётся.
    public void RemoveTask(TaskItem task) => Tasks.Remove(task);

    // Метод поиска участника команды по его идентификатору.
    // int? позволяет передать числовой ID или null.
    // Member? означает, что результатом может быть объект Member либо null.
    public Member? FindMember(int? id) =>

        // Проверяем наличие переданного идентификатора.
        // Если HasValue равно true, ищем участника с совпадающим ID.
        // FirstOrDefault() возвращает первый найденный объект или null,
        // если подходящего участника нет.
        // Если id равен null, сразу возвращаем null без поиска.
        id.HasValue ? Team.FirstOrDefault(m => m.Id == id.Value) : null;

    // XML-документация метода AssigneeName.
    /// <summary>
    /// Возвращает имя исполнителя задачи.
    /// Если исполнитель не назначен или отсутствует в команде, возвращает дефис.
    /// </summary>

    // Метод принимает объект TaskItem и возвращает строку с именем исполнителя.
    // FindMember() ищет участника по значению AssigneeId задачи.
    // Оператор ?. безопасно обращается к свойству Name только при наличии объекта.
    // Оператор ?? возвращает "-" в случае, если результат поиска равен null.
    public string AssigneeName(TaskItem task) => FindMember(task.AssigneeId)?.Name ?? "-";

    // XML-документация метода Normalize.
    /// <summary>
    /// Проверяет и восстанавливает согласованность данных проекта после загрузки из JSON.
    /// Исправляет отсутствующие коллекции, счётчики идентификаторов и ссылки на исполнителей.
    /// Также проверяет наличие списков учёта времени у задач.
    /// </summary>

    // Метод нормализации не возвращает результат.
    // Его задача — привести текущий объект Project к корректному состоянию.
    // Обычно вызывается при загрузке данных из хранилища.
    public void Normalize()
    {
        // Проверяем список участников Team.
        // Если JSON содержал null вместо коллекции, создаём новый пустой список.
        // Оператор ??= выполняет присваивание только при значении null.
        Team ??= new();

        // Аналогично проверяем список задач Tasks.
        // Это предотвращает ошибки при дальнейшем переборе коллекции.
        Tasks ??= new();

        // Восстанавливаем корректное значение счётчика участников.
        // Team.Select(m => m.Id) получает идентификаторы всех участников.
        // DefaultIfEmpty(0) возвращает 0, если список пуст.
        // Max() находит наибольший существующий ID.
        // К найденному значению прибавляется 1.
        // Math.Max() выбирает большее значение между сохранённым счётчиком
        // и минимальным допустимым следующим идентификатором.
        // Это предотвращает повторное использование уже занятых ID.
        NextMemberId = Math.Max(
            NextMemberId,
            Team.Select(m => m.Id).DefaultIfEmpty(0).Max() + 1
        );

        // Восстанавливаем корректное значение счётчика задач.
        // Аналогично предыдущему расчёту определяем максимальный ID существующей задачи.
        // Если сохранённый NextTaskId меньше следующего свободного значения,
        // счётчик увеличивается до необходимого значения.
        NextTaskId = Math.Max(
            NextTaskId,
            Tasks.Select(t => t.Id).DefaultIfEmpty(0).Max() + 1
        );

        // Перебираем все задачи проекта для проверки их внутренних данных.
        foreach (var task in Tasks)
        {
            // Проверяем список записей учёта времени задачи.
            // Если после загрузки из JSON свойство TimeLog оказалось null,
            // создаём пустой список для дальнейшей работы с ним.
            task.TimeLog ??= new();

            // Проверяем, назначен ли задаче исполнитель.
            // HasValue показывает, содержит ли AssigneeId числовое значение.
            // FindMember() проверяет, существует ли участник с таким ID в команде.
            // Если исполнитель указан, но не найден, назначение сбрасывается.
            if (task.AssigneeId.HasValue && FindMember(task.AssigneeId) is null)

                // Удаляем недействительную ссылку на исполнителя.
                // Задача остаётся в проекте, но становится неназначенной.
                task.AssigneeId = null;
        }
    }
}
