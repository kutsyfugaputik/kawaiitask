
// Объявляем пространство имён KawaiiTasks.Models.
// В нём находятся модели данных и вспомогательные классы приложения.
namespace KawaiiTasks.Models;

// XML-документация класса.
/// <summary>
/// Представляет пользовательское исключение предметной области.
/// Используется для сообщений об ошибках, связанных с некорректными данными
/// или нарушением правил работы приложения.
/// Пользовательский интерфейс может отдельно обрабатывать этот тип исключения,
/// показывая его сообщение без дополнительного преобразования.
/// </summary>

// Объявляем собственный класс исключения KawaiiException.
// Наследование от Exception позволяет использовать стандартный механизм
// обработки исключений языка C# (try-catch).
public class KawaiiException : Exception
{
    // Конструктор класса KawaiiException.
    // Параметр message содержит текстовое описание возникшей ошибки.
    // Тип string указывает, что сообщение передаётся в виде строки.
    public KawaiiException(string message)

        // Ключевое слово base вызывает конструктор родительского класса Exception.
        // Переданный параметр message сохраняется в свойстве Message базового класса.
        // Благодаря наследованию текст ошибки можно получить через ex.Message.
        : base(message)

    // Пустое тело конструктора.
    // Дополнительная логика не требуется, поскольку обработку сообщения
    // выполняет базовый класс Exception.
    { }
}
