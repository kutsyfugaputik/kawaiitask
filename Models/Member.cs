
// Объявляем пространство имён KawaiiTasks.Models.
// В нём располагаются классы, описывающие основные сущности приложения.
namespace KawaiiTasks.Models;

// XML-документация класса Member.
/// <summary>
/// Представляет участника команды проекта.
/// Объект хранит информацию о человеке, который может выступать исполнителем задач.
/// </summary>

// Объявляем публичный класс Member.
// public позволяет использовать этот класс из других компонентов приложения.
// Каждый созданный объект Member представляет отдельного участника команды.
public class Member
{
    // XML-документация свойства Id.
    /// <summary>
    /// Уникальный идентификатор участника внутри конкретного проекта.
    /// Идентификаторы участников разных проектов могут совпадать.
    /// </summary>

    // Хранит числовой идентификатор участника.
    // int — целочисленный тип данных.
    // get позволяет получить идентификатор, set — изменить его.
    public int Id { get; set; }

    // Хранит имя участника команды.
    // string — строковый тип данных для хранения текста.
    // Пустая строка "" устанавливается по умолчанию при создании объекта.
    // Это позволяет избежать начального значения null.
    public string Name { get; set; } = "";

    // Хранит роль участника в команде проекта.
    // Например: Разработчик, Тестировщик, Аналитик или Руководитель.
    // Если роль не указана при создании объекта, используется значение "Участник".
    public string Role { get; set; } = "Участник";
}
