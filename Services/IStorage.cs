// Подключает пространство имён Models, в котором находится класс AppData.
// Он используется для передачи данных между программой и хранилищем.
using KawaiiTasks.Models;

// Пространство имён Services объединяет интерфейсы и классы,
// отвечающие за выполнение сервисных операций проекта.
namespace KawaiiTasks.Services;

/// <summary>
/// Определяет общий контракт для компонентов, которые отвечают за хранение данных приложения.
///
/// Интерфейс отделяет основную бизнес-логику программы от конкретного способа хранения данных.
/// В текущей реализации данные могут сохраняться в JSON-файл, однако при необходимости
/// механизм хранения можно заменить на SQLite, XML или другую технологию.
///
/// ProjectService работает с абстракцией IStorage и не зависит от того,
/// где физически находятся данные и каким способом они сохраняются.
///
/// Такой подход позволяет использовать разные реализации хранилища:
/// - файловое хранилище для обычной работы приложения;
/// - хранилище в оперативной памяти для автоматизированного тестирования.
///
/// </summary>
public interface IStorage
{
    /// <summary>
    /// Возвращает расположение хранилища данных.
    /// Значение может содержать путь к файлу или другое описание места хранения.
    /// Используется, например, для отображения пользователю информации
    /// о расположении данных при завершении работы приложения.
    /// </summary>
    string Location { get; }

    /// <summary>
    /// Возвращает предупреждение, возникшее при загрузке данных.
    /// Например, сообщение о повреждённом или недоступном файле.
    /// Если загрузка прошла успешно и проблем не обнаружено,
    /// свойство возвращает null.
    /// </summary>
    string? LoadWarning { get; }

    // Загружает данные приложения из хранилища.
    // Возвращает объект AppData, содержащий информацию,
    // необходимую для восстановления состояния приложения.
    AppData Load();

    // Сохраняет переданные данные приложения в хранилище.
    // Параметр data содержит объект AppData со всеми данными,
    // которые необходимо сохранить.
    // Метод не возвращает значение, поскольку его задача —
    // выполнить операцию сохранения.
    void Save(AppData data);
}