// Подключает средства для настройки кодировки JSON.
// Используется для корректного отображения кириллицы в файле без Unicode-последовательностей.
using System.Text.Encodings.Web;

// Подключает основной функционал работы с JSON:
// преобразование объектов в JSON и обратно.
using System.Text.Json;

// Подключает дополнительные инструменты сериализации,
// включая преобразование перечислений (enum) в текстовый формат.
using System.Text.Json.Serialization;

// Подключает модели приложения, в частности AppData,
// в котором содержатся данные, подлежащие сохранению.
using KawaiiTasks.Models;

// Пространство имён Services объединяет компоненты,
// отвечающие за бизнес-операции и взаимодействие с хранилищами данных.
namespace KawaiiTasks.Services;

/// <summary>
/// Реализует интерфейс IStorage и обеспечивает сохранение данных приложения в JSON-файл.
///
/// JSON (JavaScript Object Notation) — текстовый формат представления структурированных данных.
/// Он позволяет сохранять объекты приложения в файл и восстанавливать их при следующем запуске.
///
/// Класс отвечает за три основные операции:
/// 1. Определение расположения файла с данными.
/// 2. Загрузку и десериализацию сохранённых данных.
/// 3. Сериализацию и сохранение актуальных данных.
///
/// В отличие от хранения данных в оперативной памяти, JSON-файл сохраняет информацию
/// между запусками приложения.
/// </summary>
public class JsonStorage : IStorage
{
    // Статическое поле содержит общие настройки сериализатора JSON.
    // Модификатор static означает, что поле принадлежит самому классу,
    // а не отдельному экземпляру JsonStorage.
    // readonly запрещает заменять ссылку на объект настроек после его инициализации.
    // Благодаря этому настройки создаются один раз и используются повторно.
    private static readonly JsonSerializerOptions Options = new()
    {
        // Включает форматирование JSON с отступами и переносами строк.
        // Благодаря этому содержимое файла удобно читать и редактировать вручную.
        WriteIndented = true,

        // Отключает стандартное экранирование кириллицы.
        // Русские символы записываются непосредственно в файл,
        // а не преобразуются в последовательности вида \u0414.
        Encoder = JavaScriptEncoder.UnsafeRelaxedJsonEscaping,

        // Добавляет преобразователь перечислений.
        // Значения enum сохраняются в виде строковых названий,
        // например "High", вместо числовых значений вроде 3.
        Converters = { new JsonStringEnumConverter() }
    };

    // Возвращает полный путь к JSON-файлу, используемому для хранения данных.
    // Значение задаётся в конструкторе и после создания объекта не изменяется.
    public string Location { get; }

    // Хранит сообщение о проблеме, обнаруженной при загрузке данных.
    // private set означает, что изменять значение может только сам класс JsonStorage.
    // Если проблем при загрузке не возникло, значение остаётся null.
    public string? LoadWarning { get; private set; }

    /// <summary>
    /// Создаёт экземпляр JSON-хранилища и определяет расположение файла данных.
    /// </summary>
    /// <param name="path">
    /// Необязательный пользовательский путь к файлу.
    /// Используется, например, в автоматизированных тестах для создания отдельного хранилища.
    /// Если значение равно null, выбирается стандартная системная папка приложения.
    /// </param>
    public JsonStorage(string? path = null)
    {
        // Проверяет, передал ли вызывающий код собственный путь к файлу.
        // Оператор is not null позволяет проверить отсутствие значения null.
        if (path is not null)
        {
            // Сохраняет переданный путь в свойстве Location.
            Location = path;

            // Завершает выполнение конструктора.
            // Стандартный путь в этом случае вычислять не требуется.
            return;
        }

        // Определяет стандартное расположение данных в зависимости от операционной системы:
        // Windows: %LOCALAPPDATA%\KawaiiTasks\data.json
        // Linux: ~/.local/share/KawaiiTasks/data.json
        // macOS: ~/Library/Application Support/KawaiiTasks/data.json

        // Получает путь к системной папке LocalApplicationData.
        // Эта папка предназначена для хранения локальных данных приложений текущего пользователя.
        var root = Environment.GetFolderPath(Environment.SpecialFolder.LocalApplicationData);

        // Проверяет, удалось ли получить корректный путь к системной папке.
        // IsNullOrWhiteSpace возвращает true, если строка пустая,
        // содержит только пробелы или равна null.
        if (string.IsNullOrWhiteSpace(root))

            // Если системный путь недоступен, используется папка,
            // из которой запускается приложение.
            root = AppContext.BaseDirectory;

        // Формирует полный путь к файлу данных.
        // Path.Combine автоматически объединяет части пути
        // с учётом правил текущей операционной системы.
        Location = Path.Combine(root, "KawaiiTasks", "data.json");
    }

    /// <summary>
    /// Загружает данные приложения из JSON-файла.
    /// </summary>
    /// <returns>
    /// Объект AppData с восстановленными данными приложения.
    /// Если файл отсутствует или не удалось корректно прочитать его содержимое,
    /// возвращается новый пустой объект AppData.
    /// </returns>
    public AppData Load()
    {
        // Проверяет существование файла по указанному пути.
        // Если файла нет, значит, приложение запускается впервые
        // либо данные ещё не были сохранены.
        if (!File.Exists(Location))

            // Возвращает новый объект с начальными значениями.
            // Создание файла на этом этапе не требуется.
            return new AppData();

        try
        {
            // Считывает всё содержимое JSON-файла в строковую переменную.
            // File.ReadAllText открывает файл, читает его содержимое и закрывает его.
            var json = File.ReadAllText(Location);

            // Преобразует JSON-строку обратно в объект AppData.
            // JsonSerializer.Deserialize выполняет десериализацию.
            // Options передаёт настройки преобразования, заданные выше.
            // Если результат десериализации оказался null,
            // оператор ?? создаёт новый пустой объект AppData.
            return JsonSerializer.Deserialize<AppData>(json, Options) ?? new AppData();
        }

        // Перехватывает только ожидаемые ошибки, связанные с чтением и обработкой JSON.
        // JsonException возникает при некорректной структуре JSON.
        // IOException возникает при проблемах ввода-вывода, например при повреждении или недоступности файла.
        // UnauthorizedAccessException возникает при отсутствии необходимых прав доступа.
        // Оператор or позволяет объединить несколько типов исключений в одном фильтре.
        catch (Exception ex) when (ex is JsonException or IOException or UnauthorizedAccessException)
        {
            // Формирует имя резервной копии повреждённого файла.
            // К исходному пути добавляется суффикс .broken и текущая дата со временем.
            // Формат yyyyMMddHHmmss обеспечивает удобную сортировку копий по времени создания.
            var backup = $"{Location}.broken-{DateTime.Now:yyyyMMddHHmmss}";

            // Пытается скопировать исходный файл в резервную копию.
            // Параметр true разрешает перезапись файла с таким же именем.
            try
            {
                File.Copy(Location, backup, true);
            }
            // Если резервную копию создать не удалось,
            // ошибка игнорируется, поскольку сохранение копии не является обязательным условием.
            catch
            {
                // Пустой блок намеренно оставлен:
                // основная обработка ошибки загрузки должна продолжиться,
                // даже если резервное копирование оказалось невозможным.
            }

            // Формирует предупреждение для пользователя.
            // В сообщение включается описание исходной ошибки,
            // а также имя файла, в который была сохранена резервная копия.
            LoadWarning = $"Файл данных не удалось прочитать ({ex.Message}). Начинаем с чистого листа, старый файл сохранён как {Path.GetFileName(backup)}.";

            // Возвращает пустой объект данных, чтобы приложение могло продолжить работу.
            // Исходный повреждённый файл при этом не удаляется.
            return new AppData();
        }
    }

    /// <summary>
    /// Сохраняет текущее состояние приложения в JSON-файл.
    /// Перед записью создаёт необходимую директорию, если она отсутствует.
    /// Использует временный файл для снижения риска потери данных при сбое записи.
    /// </summary>
    /// <param name="data">
    /// Объект AppData, содержащий актуальные данные приложения для сохранения.
    /// </param>
    public void Save(AppData data)
    {
        // Получает путь к папке, в которой должен находиться JSON-файл.
        // Например, из пути C:\Users\User\KawaiiTasks\data.json
        // будет получена директория C:\Users\User\KawaiiTasks.
        var folder = Path.GetDirectoryName(Location);

        // Проверяет, что путь к папке существует в виде непустой строки.
        // Если значение корректное, можно переходить к созданию директории.
        if (!string.IsNullOrEmpty(folder))

            // Создаёт директорию по указанному пути.
            // Если папка уже существует, повторный вызов не приводит к ошибке.
            Directory.CreateDirectory(folder);

        // Формирует путь к временному файлу.
        // Временный файл создаётся рядом с основным и имеет расширение .tmp.
        // Это позволяет сначала полностью подготовить новые данные,
        // не перезаписывая непосредственно основной файл.
        var temp = Location + ".tmp";

        // Преобразует объект AppData в JSON-строку с использованием заданных настроек.
        // JsonSerializer.Serialize выполняет сериализацию объекта.
        // File.WriteAllText записывает полученную строку во временный файл.
        // Если файл уже существует, его содержимое перезаписывается.
        File.WriteAllText(temp, JsonSerializer.Serialize(data, Options));

        // Перемещает временный файл на место основного файла.
        // Параметр true разрешает заменить существующий файл с таким же именем.
        // Благодаря этому новые данные сначала полностью записываются во временный файл,
        // а затем основной файл заменяется подготовленной версией.
        File.Move(temp, Location, true);
    }
}