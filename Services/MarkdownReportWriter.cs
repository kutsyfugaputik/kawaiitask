
// Подключает пространство имён System.Text.
// Содержит класс StringBuilder для эффективного формирования больших текстовых документов,
// а также UTF8Encoding для указания кодировки создаваемого файла.
using System.Text;

// Подключает модели приложения.
// Используется для работы с объектами ProjectReport и другими данными проекта.
using KawaiiTasks.Models;

// Пространство имён Services объединяет компоненты,
// отвечающие за бизнес-операции и формирование отчётов.
namespace KawaiiTasks.Services;

/// <summary>
/// Реализует интерфейс IReportWriter и отвечает за создание отчётов
/// о проекте в формате Markdown.
///
/// Markdown — текстовый формат разметки, который поддерживает заголовки,
/// списки, таблицы и другие элементы структурированного документа.
///
/// Создаваемый отчёт можно просматривать в GitHub, Visual Studio Code
/// и других редакторах, поддерживающих Markdown.
///
/// Класс получает уже подготовленные данные через ProjectReport,
/// формирует из них документ и сохраняет его в отдельный файл.
///
/// В отличие от ConsoleReportWriter, данный класс не выводит информацию
/// непосредственно в консоль. Вместо этого он возвращает путь к созданному файлу.
/// </summary>
public class MarkdownReportWriter : IReportWriter
{
    // Хранит путь к директории, в которой будут размещаться готовые отчёты.
    // Модификатор readonly запрещает изменять ссылку на папку после конструктора.
    private readonly string _folder;

    /// <summary>
    /// Создаёт объект для формирования Markdown-отчётов.
    /// </summary>
    /// <param name="folder">
    /// Путь к директории, в которую необходимо сохранять отчёты.
    /// </param>
    public MarkdownReportWriter(string folder) => _folder = folder;

    // Возвращает название текущего способа вывода отчёта.
    // Свойство реализует контракт интерфейса IReportWriter.
    public string Name => "Markdown-файл";

    /// <summary>
    /// Формирует Markdown-документ на основе переданных данных проекта
    /// и сохраняет его в файл.
    /// </summary>
    /// <param name="r">
    /// Объект ProjectReport с подготовленной статистикой проекта,
    /// сведениями о задачах, участниках и результатах работы.
    /// </param>
    /// <returns>
    /// Полный путь к созданному Markdown-файлу.
    /// </returns>
    public string? Write(ProjectReport r)
    {
        // Создаёт буфер для последовательного формирования текста отчёта.
        // StringBuilder эффективнее обычного сложения строк при большом количестве операций,
        // поскольку позволяет изменять содержимое общего буфера без постоянного
        // создания новых строковых объектов.
        var sb = new StringBuilder();

        // Сохраняет ссылку на объект проекта из отчёта.
        // Это позволяет обращаться к названию проекта, задачам и участникам
        // без повторного указания r.Project.
        var p = r.Project;

        // Добавляет главный заголовок Markdown-документа.
        // Символ # обозначает заголовок первого уровня.
        // В заголовке отображается название текущего проекта.
        sb.AppendLine($"# ОТЧЁТ О ПРОЕКТЕ: {p.Name}");

        // Добавляет пустую строку для визуального разделения заголовка и следующего блока.
        sb.AppendLine();

        // Добавляет дату и время формирования отчёта.
        // Формат dd.MM.yyyy HH:mm отображает дату и время в привычном виде.
        // Символы подчёркивания создают курсивное выделение в Markdown.
        sb.AppendLine($"_Сформирован: {r.GeneratedAt:dd.MM.yyyy HH:mm}_");

        // Проверяет, содержит ли описание проекта значимый текст.
        // Пустое описание или строка, состоящая только из пробелов, не выводятся.
        if (!string.IsNullOrWhiteSpace(p.Description))
        {
            // Добавляет пустую строку перед описанием для разделения блоков документа.
            sb.AppendLine();

            // Добавляет описание проекта в виде Markdown-цитаты.
            // Символ > обозначает цитату.
            // Метод Cell предварительно обрабатывает специальные символы и переносы строк.
            sb.AppendLine($"> {Cell(p.Description)}");
        }

        // Добавляет пустую строку перед следующим разделом отчёта.
        sb.AppendLine();

        // Создаёт заголовок второго уровня для раздела со сводной статистикой.
        sb.AppendLine("## Сводка");

        // Отделяет заголовок раздела от таблицы.
        sb.AppendLine();

        // Формирует заголовок таблицы Markdown.
        // Вертикальные черты разделяют столбцы таблицы.
        sb.AppendLine("| Показатель | Значение |");

        // Определяет разделительную строку Markdown-таблицы.
        // Три дефиса обозначают границу между заголовком и содержимым таблицы.
        sb.AppendLine("|---|---|");

        // Выводит общее количество задач в проекте.
        // r.Total содержит суммарное количество задач.
        sb.AppendLine($"| Всего задач | {r.Total} |");

        // Выводит количество выполненных задач и процент выполнения проекта.
        // r.Done содержит число завершённых задач.
        // r.Percent содержит процент выполнения, формат 0 округляет его до целого числа.
        sb.AppendLine($"| Выполнено | {r.Done} ({r.Percent:0}%) |");

        // Выводит количество просроченных задач.
        // Count возвращает число элементов в коллекции Overdue.
        sb.AppendLine($"| Просрочено | {r.Overdue.Count} |");

        // Выводит количество задач, у которых отсутствует назначенный исполнитель.
        sb.AppendLine($"| Без исполнителя | {r.Unassigned} |");

        // Выводит суммарное затраченное время по задачам проекта.
        // FormatMinutes преобразует количество минут в удобный текстовый формат.
        sb.AppendLine($"| Затрачено времени | {FormatMinutes(r.TotalMinutes)} |");

        // Получает уровень проекта и его текстовое название на основании накопленных баллов.
        // Метод Level принадлежит ReportService и возвращает два значения:
        // числовой уровень и соответствующее ему название.
        // Конструкция var (level, levelName) распаковывает возвращённый кортеж.
        var (level, levelName) = ReportService.Level(r.CandyPoints);

        // Добавляет в таблицу информацию о количестве баллов и текущем уровне проекта.
        sb.AppendLine($"| Баллы | {r.CandyPoints} (уровень {level}: {levelName}) |");

        // Добавляет пустую строку перед статистикой задач по статусам.
        sb.AppendLine();

        // Создаёт заголовок раздела со статистикой по состояниям задач.
        sb.AppendLine("## Задачи по статусам");

        // Отделяет заголовок раздела от таблицы.
        sb.AppendLine();

        // Формирует заголовки столбцов таблицы статусов.
        sb.AppendLine("| Статус | Количество |");

        // Добавляет разделитель между заголовком таблицы и её строками.
        sb.AppendLine("|---|---|");

        // Перебирает все пары ключ-значение из коллекции ByState.
        // Ключ содержит состояние задачи, значение — количество задач с таким состоянием.
        foreach (var pair in r.ByState)

            // Добавляет очередную строку таблицы.
            // pair.Key.Text() преобразует перечисление статуса в удобное текстовое представление.
            // pair.Value содержит количество задач соответствующего статуса.
            sb.AppendLine($"| {pair.Key.Text()} | {pair.Value} |");

        // Проверяет, есть ли в отчёте участники команды.
        // Если коллекция Members не пуста, формируется отдельный раздел.
        if (r.Members.Count > 0)
        {
            // Добавляет пустую строку перед новым разделом.
            sb.AppendLine();

            // Создаёт заголовок раздела с информацией о команде.
            sb.AppendLine("## Команда");

            // Отделяет заголовок от таблицы.
            sb.AppendLine();

            // Определяет столбцы таблицы участников:
            // имя участника, роль, количество назначенных задач,
            // количество выполненных задач и затраченное время.
            sb.AppendLine("| Участник | Роль | Задач | Готово | Время |");

            // Формирует разделительную строку таблицы.
            sb.AppendLine("|---|---|---|---|---|");

            // Последовательно перебирает всех участников, включённых в отчёт.
            foreach (var m in r.Members)

                // Добавляет строку с информацией о текущем участнике.
                // Cell защищает имя и роль от нарушения структуры Markdown-таблицы.
                // Assigned содержит количество назначенных задач.
                // Done содержит количество выполненных задач.
                // FormatMinutes преобразует затраченное время в читаемый формат.
                sb.AppendLine($"| {Cell(m.Name)} | {Cell(m.Role)} | {m.Assigned} | {m.Done} | {FormatMinutes(m.Minutes)} |");
        }

        // Проверяет, имеются ли в проекте просроченные задачи.
        // Если коллекция Overdue содержит элементы, добавляется специальный раздел.
        if (r.Overdue.Count > 0)
        {
            // Добавляет пустую строку перед разделом просроченных задач.
            sb.AppendLine();

            // Создаёт заголовок раздела.
            // Восклицательный знак визуально выделяет задачи, требующие внимания.
            sb.AppendLine("## ! Просроченные задачи");

            // Отделяет заголовок от списка задач.
            sb.AppendLine();

            // Перебирает все задачи, срок выполнения которых уже просрочен.
            foreach (var t in r.Overdue)

                // Добавляет задачу в виде элемента Markdown-списка.
                // Символ - обозначает отдельный пункт списка.
                // Id — идентификатор задачи.
                // Title — её название.
                // Deadline — установленный срок выполнения.
                // AssigneeName(t) определяет имя назначенного исполнителя.
                // Cell обрабатывает текстовые значения перед вставкой в документ.
                sb.AppendLine($"- #{t.Id} {Cell(t.Title)} - срок {t.Deadline:dd.MM.yyyy}, исполнитель: {Cell(p.AssigneeName(t))}");
        }

        // Добавляет пустую строку перед итоговым перечнем задач.
        sb.AppendLine();

        // Создаёт раздел со всеми задачами проекта независимо от их статуса.
        sb.AppendLine("## Все задачи");

        // Отделяет заголовок раздела от таблицы.
        sb.AppendLine();

        // Определяет структуру итоговой таблицы задач.
        // Для каждой задачи отображаются:
        // идентификатор, название, тип, приоритет, статус,
        // исполнитель, срок выполнения и затраченное время.
        sb.AppendLine("| # | Задача | Тип | Приоритет | Статус | Исполнитель | Срок | Время |");

        // Формирует разделительную строку таблицы из восьми столбцов.
        sb.AppendLine("|---|---|---|---|---|---|---|---|");

        // Получает задачи проекта и сортирует их по идентификатору.
        // OrderBy обеспечивает последовательное отображение задач по возрастанию Id.
        foreach (var t in p.Tasks.OrderBy(t => t.Id))
        {
            // Проверяет, установлен ли срок выполнения задачи.
            // HasValue возвращает true, если Deadline содержит дату.
            // Если дата есть, ToString преобразует её в формат dd.MM.yyyy.
            // Если срок не установлен, в отчёт записывается дефис.
            var due = t.Deadline.HasValue ? t.Deadline.Value.ToString("dd.MM.yyyy") : "-";

            // Добавляет строку с полной информацией о текущей задаче.
            // Id — идентификатор задачи.
            // Cell(t.Title) — название с обработкой специальных символов.
            // Kind.Text() — текстовое представление типа задачи.
            // Priority.Text() — текстовое представление приоритета.
            // State.Text() — текстовое представление текущего статуса.
            // AssigneeName(t) — имя назначенного исполнителя.
            // due — срок выполнения или дефис, если срок не установлен.
            // FormatMinutes — преобразование затраченного времени в читаемый вид.
            sb.AppendLine($"| {t.Id} | {Cell(t.Title)} | {t.Kind.Text()} | {t.Priority.Text()} | {t.State.Text()} | {Cell(p.AssigneeName(t))} | {due} | {FormatMinutes(t.SpentMinutes)} |");
        }

        // Создаёт директорию для сохранения отчётов.
        // Если папка уже существует, метод просто оставляет её без изменений.
        // Если папки нет, она будет создана автоматически.
        Directory.CreateDirectory(_folder);

        // Формирует базовую часть имени будущего файла.
        // SafeName удаляет недопустимые символы из названия проекта.
        // GeneratedAt добавляет дату и время формирования отчёта.
        // Это позволяет различать отчёты, созданные в разное время.
        var baseName = $"report_{SafeName(p.Name)}_{r.GeneratedAt:yyyyMMdd_HHmmss}";

        // Объединяет путь к директории и имя файла.
        // Расширение .md указывает на формат Markdown.
        var path = Path.Combine(_folder, baseName + ".md");

        // Проверяет, не существует ли уже файл с таким именем.
        // Это необходимо, если несколько отчётов создаются в одну секунду.
        // Вместо перезаписи предыдущего отчёта будет подобрано другое имя.
        var suffix = 1;

        // Повторяет проверку до тех пор, пока не будет найдено свободное имя файла.
        while (File.Exists(path))
        {
            // Добавляет к имени файла порядковый номер.
            // Например: report_Project_20261121_143300_1.md.
            path = Path.Combine(_folder, $"{baseName}_{suffix}.md");

            // Увеличивает номер для следующей попытки.
            suffix++;
        }

        // Записывает сформированный документ на диск.
        // sb.ToString() преобразует содержимое StringBuilder в обычную строку.
        // UTF8Encoding(true) задаёт кодировку UTF-8 с BOM.
        // BOM помогает некоторым текстовым редакторам Windows
        // правильно определить кодировку файла и отобразить кириллицу.
        File.WriteAllText(path, sb.ToString(), new UTF8Encoding(true));

        // Возвращает полный путь к созданному файлу.
        // Вызывающий компонент может использовать его для уведомления пользователя.
        return path;
    }

    /// <summary>
    /// Подготавливает текст для безопасного размещения внутри ячейки Markdown-таблицы.
    ///
    /// Вертикальная черта используется Markdown как разделитель столбцов,
    /// поэтому её необходимо экранировать.
    ///
    /// Переносы строк заменяются пробелами, чтобы текст не нарушал структуру таблицы.
    /// </summary>
    /// <param name="text">Исходный текст для обработки.</param>
    /// <returns>Текст, подготовленный для вставки в ячейку таблицы.</returns>
    private static string Cell(string text) => (text ?? "")
        // Экранирует обратную косую черту.
        // Это необходимо, поскольку обратная косая черта используется
        // в Markdown для экранирования специальных символов.
        .Replace("\\", "\\\\")

        // Экранирует вертикальную черту.
        // Без этого символа Markdown воспримет её как разделитель столбцов.
        .Replace("|", "\\|")

        // Заменяет символ возврата каретки пробелом.
        // Предотвращает некорректное форматирование строки таблицы.
        .Replace("\r", " ")

        // Заменяет символ перевода строки пробелом.
        // Благодаря этому содержимое остаётся в пределах одной строки таблицы.
        .Replace("\n", " ");

    /// <summary>
    /// Преобразует количество минут в удобный для чтения формат.
    ///
    /// Например, 135 минут преобразуются в строку "2ч 15м".
    /// Если значение равно нулю или меньше нуля, возвращается дефис.
    /// </summary>
    /// <param name="minutes">Количество затраченных минут.</param>
    /// <returns>Отформатированное время или дефис при отсутствии времени.</returns>
    private static string FormatMinutes(int minutes) =>

        // Проверяет, является ли количество минут положительным.
        // Если значение меньше или равно нулю, возвращает дефис.
        // Иначе выполняет преобразование минут в часы и оставшиеся минуты.
        minutes <= 0 ? "-" : $"{minutes / 60}ч {minutes % 60:00}м";

    /// <summary>
    /// Преобразует название проекта в безопасную часть имени файла.
    ///
    /// Оставляет только буквы и цифры, заменяя остальные символы подчёркиванием.
    /// Дополнительно обрабатывает зарезервированные имена Windows
    /// и ограничивает длину результата тридцатью символами.
    /// </summary>
    /// <param name="name">Исходное название проекта.</param>
    /// <returns>Безопасное имя для использования в пути к файлу.</returns>
    private static string SafeName(string name)
    {
        // Последовательно обрабатывает все символы исходного названия проекта.
        // char.IsLetterOrDigit определяет, является ли символ буквой или цифрой.
        // Допустимые символы сохраняются, остальные заменяются подчёркиванием.
        // string.Concat объединяет полученные символы в итоговую строку.
        var safe = string.Concat(name.Select(c => char.IsLetterOrDigit(c) ? c : '_'));

        // Удаляет подчёркивания в начале и конце полученной строки.
        // Это предотвращает появление лишних символов в имени файла.
        safe = safe.Trim('_');

        // Проверяет, осталось ли имя непустым после обработки.
        // Если исходное название состояло только из специальных символов,
        // используется стандартное имя project.
        if (safe.Length == 0) safe = "project";

        // Создаёт набор зарезервированных имён Windows.
        // StringComparer.OrdinalIgnoreCase выполняет сравнение без учёта регистра.
        // Это важно, поскольку CON, con и Con считаются одним и тем же именем.
        var reserved = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
        {
            // Стандартные зарезервированные системные имена Windows.
            "CON", "PRN", "AUX", "NUL",

            // Зарезервированные имена последовательных портов.
            "COM1", "COM2", "COM3", "COM4", "COM5", "COM6", "COM7", "COM8", "COM9",

            // Зарезервированные имена параллельных портов.
            "LPT1", "LPT2", "LPT3", "LPT4", "LPT5", "LPT6", "LPT7", "LPT8", "LPT9"
        };

        // Проверяет, совпадает ли сформированное имя с зарезервированным именем Windows.
        // Если совпадение найдено, добавляет суффикс _project,
        // чтобы избежать использования недопустимого системного имени.
        if (reserved.Contains(safe)) safe += "_project";

        // Ограничивает длину имени файла тридцатью символами.
        // Если строка длиннее, оператор диапазона [..30] возвращает первые 30 символов.
        // Если строка короче или равна 30 символам, возвращается исходное значение.
        return safe.Length > 30 ? safe[..30] : safe;
    }
}
