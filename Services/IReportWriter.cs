// Пространство имён Services объединяет классы и интерфейсы,
// отвечающие за выполнение сервисных операций в проекте KawaiiTasks.
namespace KawaiiTasks.Services;

/// <summary>
/// Определяет общий контракт для компонентов, которые отвечают за формирование и вывод отчётов.
///
/// Используется паттерн проектирования «Стратегия» (Strategy), который позволяет
/// выбирать способ вывода отчёта без изменения основной логики программы.
///
/// Реализации интерфейса могут выводить отчёт в консоль (ConsoleReportWriter)
/// или сохранять его в файл формата Markdown (MarkdownReportWriter).
///
/// Подготовкой данных для отчёта занимается ReportService,
/// а данный интерфейс определяет только способ его представления и вывода.
///
/// Метод Write возвращает путь к созданному файлу, если отчёт сохранялся на диск.
/// </summary>
public interface IReportWriter
{
    // Возвращает название текущего способа вывода отчёта.
    // Например, «Консоль» или «Markdown».
    string Name { get; }

    // Принимает готовый объект отчёта и выполняет его вывод.
    // ProjectReport содержит данные, которые необходимо представить пользователю.
    // Возвращает путь к созданному файлу, если отчёт был сохранён на диск.
    // Если файл не создавался, возвращает null.
    string? Write(ProjectReport report);
}