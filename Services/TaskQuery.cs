
using KawaiiTasks.Models; // Подключаем модели проекта, в частности TaskItem, TaskState и Priority.

namespace KawaiiTasks.Services; // Размещаем классы и перечисления в пространстве имён сервисов приложения.

/// <summary>
/// Определяет доступные варианты сортировки задач.
/// Значение перечисления выбирается пользователем в меню поиска и фильтрации.
/// </summary>
public enum SortKey
{
    Priority, // Сортировка по приоритету задачи.
    Deadline, // Сортировка по сроку выполнения.
    State,    // Сортировка по текущему статусу задачи.
    Title,    // Сортировка по названию задачи.
    Time      // Сортировка по затраченному на задачу времени.
}

/// <summary>
/// Хранит параметры поиска, фильтрации и сортировки задач.
/// Объект заполняется на основании выбора пользователя в меню «Поиск и фильтры».
/// </summary>
public class TaskFilter
{
    // Текстовая строка для поиска по названию, описанию и имени исполнителя.
    // Nullable (?) означает, что пользователь может не задавать текстовый запрос.
    public string? Text { get; set; }

    // Список статусов, по которым необходимо отфильтровать задачи.
    // Если список пустой, фильтр по статусу не применяется.
    // new() создаёт пустой список при создании объекта TaskFilter.
    public List<TaskState> States { get; set; } = new();

    // Приоритет, по которому необходимо отобрать задачи.
    // Nullable (?) позволяет не выбирать приоритет и оставить все варианты.
    public Priority? OnlyPriority { get; set; }

    // Идентификатор исполнителя, задачи которого требуется показать.
    // Если значение отсутствует, ограничение по исполнителю не применяется.
    public int? AssigneeId { get; set; }

    // Признак включения фильтра по просроченным задачам.
    // true — оставить только просроченные задачи.
    // false — не применять это ограничение.
    public bool OnlyOverdue { get; set; }

    // Выбранный способ сортировки результатов.
    // По умолчанию задачи сортируются по приоритету.
    public SortKey Sort { get; set; } = SortKey.Priority;
}

/// <summary>
/// Выполняет поиск, фильтрацию и сортировку задач проекта.
/// Получает исходные данные и параметры фильтрации, после чего возвращает новый список.
/// Не изменяет задачи проекта и не отвечает за отображение результатов пользователю.
/// </summary>
public static class TaskQuery
{
    /// <summary>
    /// Применяет указанные условия фильтрации и сортировки к задачам проекта.
    /// </summary>
    /// <param name="project">Проект, задачи которого необходимо обработать.</param>
    /// <param name="filter">Параметры поиска, фильтрации и сортировки.</param>
    /// <returns>Новый список задач, соответствующих заданным условиям.</returns>
    public static List<TaskItem> Apply(Project project, TaskFilter filter)
    {
        // Создаём переменную для последовательного построения LINQ-запроса.
        // IEnumerable<TaskItem> представляет последовательность задач.
        // Изначально в запрос включены все задачи проекта.
        //
        // LINQ использует отложенное выполнение: вызовы Where и OrderBy
        // формируют запрос, но фактический перебор элементов происходит позднее.
        IEnumerable<TaskItem> query = project.Tasks;

        // Проверяем, ввёл ли пользователь текст для поиска.
        // IsNullOrWhiteSpace возвращает true, если строка равна null,
        // пустая или содержит только пробельные символы.
        if (!string.IsNullOrWhiteSpace(filter.Text))
        {
            // Удаляем пробелы в начале и конце поисковой строки.
            // Это предотвращает ошибки поиска из-за случайных пробелов.
            var needle = filter.Text.Trim();

            // Добавляем условие текстового поиска.
            // В результате останутся задачи, у которых поисковая строка
            // встречается хотя бы в одном из трёх полей.
            query = query.Where(t =>
                // Проверяем наличие текста в названии задачи.
                // OrdinalIgnoreCase выполняет сравнение без учёта регистра
                // с использованием порядковых правил сравнения строк.
                t.Title.Contains(needle, StringComparison.OrdinalIgnoreCase) ||

                // Проверяем наличие текста в описании задачи.
                t.Description.Contains(needle, StringComparison.OrdinalIgnoreCase) ||

                // Получаем имя исполнителя через метод проекта AssigneeName().
                // Затем проверяем, содержит ли имя введённую поисковую строку.
                project.AssigneeName(t).Contains(needle, StringComparison.OrdinalIgnoreCase));
        }

        // Проверяем, выбрал ли пользователь хотя бы один статус.
        // Если список States не пустой, добавляем дополнительное условие.
        if (filter.States.Count > 0)

            // Оставляем только задачи, статус которых входит в выбранный список.
            // Contains проверяет наличие текущего статуса задачи в коллекции States.
            query = query.Where(t => filter.States.Contains(t.State));

        // Проверяем, установлен ли конкретный приоритет.
        // HasValue показывает, содержит ли nullable-переменная значение.
        if (filter.OnlyPriority.HasValue)

            // Оставляем задачи только с выбранным приоритетом.
            // Value извлекает значение из Priority?, когда оно присутствует.
            query = query.Where(t => t.Priority == filter.OnlyPriority.Value);

        // Проверяем, указан ли идентификатор исполнителя.
        if (filter.AssigneeId.HasValue)

            // Оставляем задачи, назначенные участнику с указанным идентификатором.
            query = query.Where(t => t.AssigneeId == filter.AssigneeId.Value);

        // Проверяем, включил ли пользователь режим отображения просроченных задач.
        if (filter.OnlyOverdue)

            // Если режим включён, оставляем только задачи,
            // для которых свойство IsOverdue возвращает true.
            query = query.Where(t => t.IsOverdue);

        // Объявляем переменную для уже отсортированной последовательности.
        // IOrderedEnumerable<TaskItem> представляет результат сортировки,
        // к которому можно дополнительно применить ThenBy.
        //
        // switch выбирает способ сортировки в зависимости от значения Sort.
        IOrderedEnumerable<TaskItem> ordered = filter.Sort switch
        {
            // Сортируем по приоритету в порядке убывания.
            // Задачи с более высоким приоритетом располагаются первыми.
            SortKey.Priority => query.OrderByDescending(t => t.Priority),

            // Сортируем по сроку выполнения в порядке возрастания.
            // Задачи с ближайшими сроками располагаются первыми.
            // Если Deadline отсутствует, вместо него используется DateTime.MaxValue,
            // поэтому задачи без установленного срока перемещаются в конец списка.
            SortKey.Deadline => query.OrderBy(t => t.Deadline ?? DateTime.MaxValue),

            // Сортируем по значению перечисления TaskState.
            // Порядок определяется числовыми значениями элементов перечисления.
            SortKey.State => query.OrderBy(t => t.State),

            // Сортируем по названию задачи в алфавитном порядке.
            // StringComparer.OrdinalIgnoreCase позволяет не учитывать регистр букв.
            SortKey.Title => query.OrderBy(t => t.Title, StringComparer.OrdinalIgnoreCase),

            // Сортируем по затраченному времени в порядке убывания.
            // Сначала отображаются задачи, на которые потратили больше всего минут.
            SortKey.Time => query.OrderByDescending(t => t.SpentMinutes),

            // Обрабатываем остальные значения перечисления, если они появятся.
            // В качестве резервного варианта используем сортировку по идентификатору.
            _ => query.OrderBy(t => t.Id)
        };

        // Добавляем вторичную сортировку по идентификатору задачи.
        // Она применяется, когда основные значения сортировки совпадают.
        // Например, если у нескольких задач одинаковый приоритет,
        // порядок между ними определяется по ID.
        //
        // ToList() выполняет построенный LINQ-запрос и создаёт итоговый список.
        // После этого результат можно передавать интерфейсу для отображения.
        return ordered.ThenBy(t => t.Id).ToList();
    }
}
