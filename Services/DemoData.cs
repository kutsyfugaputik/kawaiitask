
using KawaiiTasks.Models; // Подключает модели проекта, участников, задач, приоритетов и статусов.

namespace KawaiiTasks.Services; // Определяет пространство имён для сервисного слоя приложения.

/// <summary>
/// Готовый пример проекта — чтобы сразу было что показать на защите.
/// Здесь есть все интересные случаи: выполненные задачи с баллами, задачи в работе и на проверке,
/// задача без исполнителя и одна намеренно просроченная.
/// </summary>
public static class DemoData // Статический класс: его методы вызываются без создания экземпляра.
{
    /// <summary>
    /// Создаёт демонстрационный проект с участниками и заранее подготовленными задачами.
    /// </summary>
    /// <param name="id">Идентификатор создаваемого проекта.</param>
    /// <returns>Заполненный демонстрационными данными объект Project.</returns>
    public static Project Create(int id)
    {
        // Создаёт новый объект проекта и задаёт его основные свойства.
        var p = new Project
        {
            // Устанавливает идентификатор, полученный в параметре метода.
            Id = id,

            // Задаёт название демонстрационного проекта.
            Name = "Демо: приложение 'Зефирка'",

            // Записывает краткое описание проекта.
            Description = "Мобильное приложение для заказа сладостей - пример проекта с командой и задачами.",

            // Устанавливает дату создания проекта на 14 дней раньше текущей даты и времени.
            CreatedAt = DateTime.Now.AddDays(-14)
        };

        // Добавляет участника Аню с ролью тимлида.
        // Возвращаемый объект Member сохраняется в переменную anya.
        var anya = p.AddMember("Аня", "Тимлид");

        // Добавляет Мишу в команду в качестве разработчика.
        var misha = p.AddMember("Миша", "Разработчик");

        // Добавляет Сашу в команду в качестве тестировщика.
        var sasha = p.AddMember("Саша", "Тестировщик");

        // Добавляет Лину в команду в качестве дизайнера.
        var lina = p.AddMember("Лина", "Дизайнер");

        // Получает сегодняшнюю календарную дату без часов, минут и секунд.
        // Благодаря этому сроки демонстрационных задач рассчитываются относительно текущего дня.
        var today = DateTime.Today; // Все сроки считаются от сегодняшнего дня, поэтому демо не «стареет».

        // Создаёт первую задачу — подготовку макетов экранов.
        // Назначает высокий приоритет, тип Feature, исполнителя Лину и срок через 3 дня.
        var t1 = p.AddTask(
            "Нарисовать макеты экранов",
            "Главный экран, корзина и профиль в пастельной гамме.",
            Priority.High,
            TaskKind.Feature,
            lina.Id,
            today.AddDays(3));

        // Добавляет запись о 240 минутах работы над первыми набросками.
        // Дата записи устанавливается на 5 дней раньше сегодняшнего дня.
        t1.LogTime(240, "Первые наброски", today.AddDays(-5));

        // Добавляет ещё одну запись — 180 минут на исправления после ревью.
        // Дата записи устанавливается на 3 дня раньше сегодняшнего дня.
        t1.LogTime(180, "Правки после ревью", today.AddDays(-3));

        // Переводит первую задачу в состояние Done.
        // Вспомогательный метод Finish также устанавливает дату завершения в прошлом.
        Finish(t1, today.AddDays(-2));

        // Создаёт вторую задачу — реализацию авторизации по электронной почте.
        // Исполнитель — Миша, приоритет высокий, срок через 2 дня.
        var t2 = p.AddTask(
            "Авторизация по e-mail",
            "Регистрация, вход и восстановление пароля.",
            Priority.High,
            TaskKind.Feature,
            misha.Id,
            today.AddDays(2));

        // Записывает 300 минут работы над серверной частью и экраном входа.
        // Дата записи — 4 дня назад.
        t2.LogTime(300, "Бэкенд и экран входа", today.AddDays(-4));

        // Завершает вторую задачу и устанавливает дату завершения на вчерашний день.
        Finish(t2, today.AddDays(-1));

        // Создаёт третью задачу — каталог товаров с поиском.
        // Исполнитель — Миша, срок через 5 дней.
        var t3 = p.AddTask(
            "Каталог товаров с поиском",
            "Список сладостей, карточка товара, поиск по названию.",
            Priority.High,
            TaskKind.Feature,
            misha.Id,
            today.AddDays(5));

        // Добавляет запись о 150 минутах работы над списком и карточкой товара.
        // Дата записи — вчерашний день.
        t3.LogTime(150, "Список и карточка", today.AddDays(-1));

        // Переводит третью задачу в статус InProgress — в работе.
        t3.ChangeState(TaskState.InProgress);

        // Создаёт четвёртую задачу — разработку корзины и оформления заказа.
        // Устанавливает критический приоритет и назначает исполнителем Мишу.
        var t4 = p.AddTask(
            "Корзина и оформление заказа",
            "Добавление товаров, подсчёт суммы, подтверждение заказа.",
            Priority.Critical,
            TaskKind.Feature,
            misha.Id,
            today.AddDays(1));

        // Записывает 90 минут работы над моделью корзины.
        // Дата записи — сегодняшний день.
        t4.LogTime(90, "Модель корзины", today);

        // Устанавливает статус задачи InProgress.
        t4.ChangeState(TaskState.InProgress);

        // Создаёт пятую задачу — исправление ошибки при пустой корзине.
        // Устанавливает критический приоритет, тип Bug и назначает Сашу.
        var t5 = p.AddTask(
            "Баг: падение при пустой корзине",
            "Приложение закрывается при нажатии 'Оформить'.",
            Priority.Critical,
            TaskKind.Bug,
            sasha.Id,
            today);

        // Добавляет запись о 60 минутах воспроизведения и анализа ошибки.
        t5.LogTime(60, "Воспроизведение и анализ", today);

        // Переводит задачу в статус Review — на проверку.
        t5.ChangeState(TaskState.Review);

        // Создаёт задачу по подготовке тест-кейсов.
        // Исполнитель — Саша, приоритет средний, тип Chore, срок через 7 дней.
        p.AddTask(
            "Написать тест-кейсы",
            "Чек-лист для основных сценариев.",
            Priority.Medium,
            TaskKind.Chore,
            sasha.Id,
            today.AddDays(7));

        // Создаёт задачу по подготовке иконки и экрана загрузки.
        // Исполнитель — Лина, приоритет низкий, срок через 10 дней.
        p.AddTask(
            "Иконка и сплэш-экран",
            "Милая зефирка с глазками.",
            Priority.Low,
            TaskKind.Feature,
            lina.Id,
            today.AddDays(10));

        // Создаёт задачу по документации API.
        // Значение null означает, что исполнитель пока не назначен.
        // Срок выполнения — через 14 дней.
        p.AddTask(
            "Документация API",
            "Описание эндпоинтов для мобильной команды.",
            Priority.Medium,
            TaskKind.Docs,
            null,
            today.AddDays(14));

        // Создаёт девятую задачу — настройку автоматической сборки и тестирования.
        // Исполнитель — Аня, приоритет высокий, срок изначально установлен на завтра.
        var t9 = p.AddTask(
            "Настроить CI",
            "Автосборка и запуск тестов при каждом коммите.",
            Priority.High,
            TaskKind.Chore,
            anya.Id,
            today.AddDays(1));

        // SetDeadline запрещает устанавливать прошедшие даты.
        // Поэтому для демонстрационного сценария срок изменяется напрямую через свойство.
        t9.Deadline = today.AddDays(-2); // Намеренно просроченная задача для демонстрации предупреждений.

        // Возвращает полностью подготовленный проект вызывающему коду.
        return p;
    }

    /// <summary>
    /// Помечает задачу выполненной «задним числом».
    /// ChangeState устанавливает текущее время, поэтому дата завершения меняется отдельно.
    /// </summary>
    /// <param name="task">Задача, которую необходимо завершить.</param>
    /// <param name="when">Дата и время завершения задачи.</param>
    private static void Finish(TaskItem task, DateTime when)
    {
        // Изменяет статус задачи на Done.
        // Метод ChangeState автоматически устанавливает CompletedAt в текущее время.
        task.ChangeState(TaskState.Done);

        // Заменяет автоматически установленное время завершения
        // на дату, переданную в параметре when.
        task.CompletedAt = when;
    }
}
