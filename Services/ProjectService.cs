
// Подключает пространство имён Models, в котором находятся основные модели приложения:
// Project, Member, TaskItem, AppData, Priority, TaskKind и другие типы.
using KawaiiTasks.Models;

// Пространство имён Services объединяет компоненты,
// которые реализуют бизнес-логику и работу с данными приложения.
namespace KawaiiTasks.Services;

/// <summary>
/// Центральный сервис управления проектами, участниками команды и задачами.
///
/// ProjectService выступает посредником между пользовательским интерфейсом,
/// моделями приложения и механизмом хранения данных.
///
/// Основные обязанности класса:
/// 1. Создание, удаление и получение проектов.
/// 2. Управление участниками команды.
/// 3. Создание, изменение и удаление задач.
/// 4. Проверка корректности операций перед изменением данных.
/// 5. Сохранение изменений через интерфейс IStorage.
///
/// Консольный интерфейс взаимодействует с данными только через методы данного сервиса.
/// Это позволяет отделить пользовательский интерфейс от бизнес-логики
/// и не допускать прямого изменения файлов хранилища.
///
/// После каждой успешной операции изменения данных вызывается Save(),
/// который сохраняет актуальное состояние приложения.
/// </summary>
public class ProjectService
{
    // Максимально допустимая длина названия проекта.
    // Константа используется при проверке пользовательского ввода.
    public const int MaxProjectName = 60;

    // Максимально допустимая длина описания проекта.
    // Ограничение помогает контролировать размер вводимых данных.
    public const int MaxProjectDescription = 200;

    // Хранит ссылку на объект хранилища.
    // IStorage позволяет использовать разные способы хранения данных,
    // не привязывая сервис к конкретной реализации, например JsonStorage.
    // readonly запрещает заменять ссылку после создания объекта.
    private readonly IStorage _storage;

    // Содержит все загруженные данные приложения.
    // AppData объединяет список проектов и вспомогательную информацию,
    // необходимую для работы программы.
    private readonly AppData _data;

    /// <summary>
    /// Создаёт сервис управления проектами и загружает сохранённые данные.
    /// </summary>
    /// <param name="storage">
    /// Реализация интерфейса IStorage, используемая для загрузки и сохранения данных.
    /// </param>
    public ProjectService(IStorage storage)
    {
        // Сохраняет переданное хранилище для последующего использования.
        // Благодаря внедрению зависимости сервис не зависит от конкретного типа хранилища.
        _storage = storage;

        // Загружает ранее сохранённые данные приложения.
        // Метод Load() возвращает объект AppData с существующими проектами.
        // Если сохранённых данных нет, хранилище возвращает новый объект AppData.
        _data = storage.Load();

        // Нормализует загруженные данные.
        // Метод Normalize() проверяет и корректирует структуру данных,
        // например после ручного редактирования или частичного повреждения файла.
        // Это дополнительная защита перед началом работы приложения.
        _data.Normalize();
    }

    /// <summary>
    /// Возвращает список проектов только для чтения.
    /// Изменение коллекции через данное свойство запрещено:
    /// управление проектами должно выполняться методами сервиса.
    /// </summary>
    public IReadOnlyList<Project> Projects => _data.Projects;

    // Возвращает путь к используемому хранилищу.
    // Значение берётся непосредственно из свойства Location интерфейса IStorage.
    // Может использоваться интерфейсом для отображения расположения файла данных.
    public string StoragePath => _storage.Location;

    /// <summary>
    /// Возвращает путь к корневой директории проекта.
    ///
    /// При запуске из среды разработки используется папка исходного проекта.
    /// При запуске опубликованной версии без исходников используется директория приложения.
    /// </summary>
    public string ProjectFolder => FindProjectFolder();

    /// <summary>
    /// Формирует путь к директории для сохранения отчётов.
    /// Все отчёты размещаются в отдельной папке reports внутри проекта.
    /// </summary>
    public string ReportsFolder => Path.Combine(ProjectFolder, "reports");

    /// <summary>
    /// Определяет расположение корневой папки исходного проекта.
    ///
    /// Поиск начинается с директории запущенной сборки и текущей директории терминала.
    /// Далее программа последовательно проверяет родительские папки
    /// на наличие файла KawaiiTasks.csproj.
    ///
    /// Это позволяет сохранять отчёты в папке исходного проекта,
    /// а не в служебной директории bin/Debug/net8.0.
    ///
    /// Если файл проекта не найден, возвращается директория запуска приложения.
    /// </summary>
    /// <returns>Полный путь к корневой папке проекта.</returns>
    private static string FindProjectFolder()
    {
        // Формирует массив начальных директорий, от которых будет выполняться поиск.
        // AppContext.BaseDirectory содержит путь к директории запущенной сборки.
        // Environment.CurrentDirectory содержит текущую директорию терминала.
        // Проверка обоих вариантов повышает вероятность нахождения исходного проекта.
        var starts = new[]
        {
            // Директория, в которой находится исполняемая сборка приложения.
            AppContext.BaseDirectory,

            // Текущая рабочая директория, из которой была запущена программа.
            Environment.CurrentDirectory
        };

        // Перебирает все начальные директории поиска.
        // Каждая директория проверяется независимо от остальных.
        foreach (var start in starts)
        {
            // Объявляет переменную для хранения информации о текущей директории.
            // Nullable указывает, что значение может отсутствовать.
            DirectoryInfo? current;

            // Пытается получить объект DirectoryInfo для начальной директории.
            // Он предоставляет информацию о папке и позволяет переходить к её родителям.
            try
            {
                current = new DirectoryInfo(start);
            }

            // Обрабатывает ошибку некорректного пути.
            // Если переданная строка не может быть использована как путь,
            // поиск продолжается со следующей начальной директорией.
            catch (ArgumentException)
            {
                // Пропускает текущий вариант поиска.
                continue;
            }

            // Последовательно поднимается от текущей директории к родительским папкам.
            // Цикл завершится, когда будет найден корень файловой системы
            // и свойство Parent станет равным null.
            while (current is not null)
            {
                // Проверяет наличие файла проекта KawaiiTasks.csproj
                // непосредственно в текущей директории.
                // Path.Combine формирует корректный путь к проверяемому файлу.
                if (File.Exists(Path.Combine(current.FullName, "KawaiiTasks.csproj"))

                    // Если файл проекта найден, возвращает полный путь к его директории.
                    // FullName содержит абсолютный путь текущей папки.
                    )
                    return current.FullName;

                // Переходит на один уровень выше по файловой системе.
                // Если родительская папка отсутствует, current станет null
                // и цикл поиска завершится.
                current = current.Parent;
            }
        }

        // Если ни в одной из проверенных директорий файл проекта не найден,
        // используется папка запущенного приложения.
        // Это необходимо для опубликованной версии, в которой исходников может не быть.
        return AppContext.BaseDirectory;
    }

    // ------------------------------------------------------------
    // УПРАВЛЕНИЕ ПРОЕКТАМИ
    // ------------------------------------------------------------

    /// <summary>
    /// Создаёт новый проект, проверяет введённые данные и сохраняет результат.
    /// </summary>
    /// <param name="name">Название создаваемого проекта.</param>
    /// <param name="description">Описание проекта.</param>
    /// <returns>Созданный объект Project.</returns>
    public Project CreateProject(string? name, string? description)
    {
        // Проверяет полученное название проекта.
        // Если вместо строки передан null, используется пустая строка.
        // Trim удаляет пробелы в начале и конце значения.
        var value = (name ?? "").Trim();

        // Проверяет, что после удаления пробелов название не оказалось пустым.
        // Пустое название не допускается, поэтому выбрасывается пользовательское исключение.
        if (value.Length == 0)
            throw new KawaiiException("Название проекта не может быть пустым.");

        // Проверяет ограничение на максимальную длину названия.
        // Если длина превышает MaxProjectName, создание проекта прекращается.
        if (value.Length > MaxProjectName)
            throw new KawaiiException($"Название проекта слишком длинное (максимум {MaxProjectName} символов).");

        // Проверяет, существует ли проект с таким же названием.
        // Any возвращает true, если хотя бы один элемент удовлетворяет условию.
        // StringComparison.OrdinalIgnoreCase выполняет сравнение без учёта регистра.
        // Поэтому названия Project и PROJECT считаются одинаковыми.
        if (_data.Projects.Any(p => string.Equals(p.Name, value, StringComparison.OrdinalIgnoreCase)))
            throw new KawaiiException("Проект с таким названием уже существует.");

        // Подготавливает описание проекта.
        // Если значение равно null, используется пустая строка.
        // Trim удаляет лишние пробелы по краям.
        var text = (description ?? "").Trim();

        // Проверяет, не превышает ли описание установленный лимит символов.
        if (text.Length > MaxProjectDescription)
            throw new KawaiiException($"Описание проекта слишком длинное (максимум {MaxProjectDescription} символов).");

        // Создаёт новый объект проекта с помощью инициализатора свойств.
        var project = new Project
        {
            // Присваивает проекту уникальный идентификатор.
            // После использования счётчик NextProjectId автоматически увеличивается на единицу.
            Id = _data.NextProjectId++,

            // Сохраняет проверенное название проекта.
            Name = value,

            // Сохраняет подготовленное описание проекта.
            Description = text,

            // Записывает текущие дату и время создания проекта.
            CreatedAt = DateTime.Now
        };

        // Добавляет новый проект в общую коллекцию приложения.
        _data.Projects.Add(project);

        // Сохраняет обновлённые данные через подключённое хранилище.
        Save();

        // Возвращает созданный объект вызывающему коду.
        // Интерфейс может использовать его для отображения информации о проекте.
        return project;
    }

    /// <summary>
    /// Создаёт демонстрационный проект с заранее подготовленными данными.
    /// </summary>
    /// <returns>Созданный демонстрационный проект.</returns>
    public Project AddDemoProject()
    {
        // Создаёт демонстрационный проект с помощью класса DemoData.
        // Передаёт следующий доступный идентификатор проекта.
        // Внутри DemoData формируются примерные задачи и участники команды.
        var demo = DemoData.Create(_data.NextProjectId);

        // Проверяет, не был ли демонстрационный проект уже добавлен ранее.
        // Сравнение названий выполняется без учёта регистра.
        if (_data.Projects.Any(p => string.Equals(p.Name, demo.Name, StringComparison.OrdinalIgnoreCase)))
            throw new KawaiiException("Демо-проект уже создан.");

        // Увеличивает счётчик идентификаторов после успешной проверки.
        // Следующий создаваемый проект получит другой идентификатор.
        _data.NextProjectId++;

        // Добавляет демонстрационный проект в общую коллекцию.
        _data.Projects.Add(demo);

        // Сохраняет изменения в хранилище.
        Save();

        // Возвращает созданный демонстрационный проект.
        return demo;
    }

    /// <summary>
    /// Удаляет указанный проект из коллекции приложения.
    /// </summary>
    /// <param name="project">Проект, который необходимо удалить.</param>
    public void DeleteProject(Project project)
    {
        // Удаляет переданный объект проекта из коллекции.
        // Remove возвращает true, если элемент был найден и удалён.
        _data.Projects.Remove(project);

        // Сохраняет обновлённую коллекцию проектов.
        Save();
    }

    // ------------------------------------------------------------
    // УПРАВЛЕНИЕ УЧАСТНИКАМИ КОМАНДЫ
    // ------------------------------------------------------------

    /// <summary>
    /// Добавляет нового участника в команду выбранного проекта.
    /// </summary>
    /// <param name="project">Проект, в команду которого добавляется участник.</param>
    /// <param name="name">Имя участника.</param>
    /// <param name="role">Роль участника в проекте.</param>
    /// <returns>Созданный объект Member.</returns>
    public Member AddMember(Project project, string? name, string? role)
    {
        // Вызывает метод AddMember модели Project.
        // Проверка данных и создание участника выполняются непосредственно моделью проекта.
        // Результатом является новый объект Member.
        var member = project.AddMember(name, role);

        // Сохраняет проект с обновлённым составом команды.
        Save();

        // Возвращает созданного участника для дальнейшего использования интерфейсом.
        return member;
    }
    /// <summary>
    /// Удаляет участника из команды выбранного проекта.
    /// </summary>
    /// <param name="project">Проект, из которого удаляется участник.</param>
    /// <param name="member">Участник, которого необходимо удалить.</param>
    public void RemoveMember(Project project, Member member)
    {
        // Вызывает метод модели Project, отвечающий за удаление участника.
        project.RemoveMember(member);
        // Сохраняет изменения состава команды.
        Save();
    }
    // ------------------------------------------------------------
    // УПРАВЛЕНИЕ ЗАДАЧАМИ
    // ------------------------------------------------------------
    /// <summary>
    /// Создаёт новую задачу в указанном проекте.
    /// </summary>
    /// <param name="project">Проект, в который добавляется задача.</param>
    /// <param name="title">Название задачи.</param>
    /// <param name="description">Описание задачи.</param>
    /// <param name="priority">Приоритет выполнения.</param>
    /// <param name="kind">Тип задачи.</param>
    /// <param name="assigneeId">Идентификатор назначенного участника, если он указан.</param>
    /// <param name="deadline">Срок выполнения задачи, если он установлен.</param>
    /// <returns>Созданный объект TaskItem.</returns>
    public TaskItem AddTask(Project project, string? title, string? description, Priority priority,
                            TaskKind kind, int? assigneeId, DateTime? deadline)
    {
        // Передаёт параметры модели Project для создания новой задачи.
        // Сама модель отвечает за формирование объекта TaskItem
        // и выполнение предусмотренных в ней проверок.
        var task = project.AddTask(title, description, priority, kind, assigneeId, deadline);
        // Сохраняет проект с добавленной задачей.
        Save();
        // Возвращает созданную задачу вызывающему коду.
        return task;
    }
    /// <summary>
    /// Удаляет задачу из выбранного проекта.
    /// </summary>
    /// <param name="project">Проект, содержащий задачу.</param>
    /// <param name="task">Удаляемая задача.</param>
    public void DeleteTask(Project project, TaskItem task)
    {
        // Вызывает метод модели Project для удаления задачи из коллекции проекта.
        project.RemoveTask(task);
        // Сохраняет обновлённые данные приложения.
        Save();
    }
    /// <summary>
    /// Изменяет состояние задачи.
    /// </summary>
    /// <param name="task">Задача, состояние которой необходимо изменить.</param>
    /// <param name="state">Новое состояние задачи.</param>
    public void ChangeState(TaskItem task, TaskState state)
    {
        // Передаёт новое состояние непосредственно модели TaskItem.
        // Метод ChangeState может содержать дополнительные проверки
        // и связанные с изменением статуса действия.
        task.ChangeState(state);

        // Сохраняет обновлённое состояние задачи.
        Save();
    }
    /// <summary>
    /// Назначает задаче участника команды или снимает назначение.
    /// </summary>
    /// <param name="project">Проект, в котором находится задача.</param>
    /// <param name="task">Задача, для которой назначается исполнитель.</param>
    /// <param name="member">Новый исполнитель или null для снятия назначения.</param>
    public void Assign(Project project, TaskItem task, Member? member)
    {
        // Если участник передан, проверяет его наличие в команде текущего проекта.
        // Оператор is not null исключает ситуацию, когда назначение снимается.
        // FindMember выполняет поиск участника по его идентификатору.
        // Если участник не найден, назначение запрещается.
        if (member is not null && project.FindMember(member.Id) is null)
            throw new KawaiiException("Этот участник не состоит в команде проекта.");

        // Присваивает задаче идентификатор выбранного исполнителя.
        // Оператор ?. безопасно обращается к Id только при наличии объекта Member.
        // Если member равен null, AssigneeId также получает null,
        // что означает отсутствие назначенного исполнителя.
        task.AssigneeId = member?.Id;

        // Сохраняет изменение назначения задачи.
        Save();
    }
    /// <summary>
    /// Устанавливает или изменяет срок выполнения задачи.
    /// </summary>
    /// <param name="task">Задача, для которой устанавливается срок.</param>
    /// <param name="deadline">Новая дата выполнения или null для удаления срока.</param>
    public void SetDeadline(TaskItem task, DateTime? deadline)
    {
        // Передаёт новую дату модели TaskItem.
        // Логика установки и проверки срока находится внутри модели.
        task.SetDeadline(deadline);
        // Сохраняет обновлённые данные задачи.
        Save();
    }
    /// <summary>
    /// Регистрирует затраченное на задачу время.
    /// </summary>
    /// <param name="task">Задача, для которой учитывается время.</param>
    /// <param name="minutes">Количество добавляемых минут.</param>
    /// <param name="note">Дополнительный комментарий к записи времени.</param>
    public void LogTime(TaskItem task, int minutes, string? note)
    {
        // Вызывает метод модели TaskItem для регистрации затраченного времени.
        // Внутри модели обрабатываются количество минут и текстовое примечание.
        task.LogTime(minutes, note);

        // Сохраняет обновлённую информацию о времени выполнения задачи.
        Save();
    }
    /// <summary>
    /// Выполняет произвольное изменение данных и сохраняет результат.
    ///
    /// Метод принимает делегат Action, который содержит действие,
    /// выполняющее необходимые изменения.
    ///
    /// Сохранение запускается только после успешного завершения переданного действия.
    /// Если действие выбрасывает исключение, выполнение прекращается
    /// и вызов Save() не происходит.
    /// </summary>
    /// <param name="change">
    /// Делегат с операциями изменения данных проекта.
    /// </param>
    public void Update(Action change)
    {
        // Выполняет переданное действие.
        // Action позволяет передавать в метод различные операции без создания
        // отдельного метода сервиса для каждого небольшого изменения.
        // Если во время выполнения возникает исключение,
        // следующая строка не выполняется.
        change();
        // Сохраняет данные после успешного завершения операции изменения.
        Save();
    }
    /// <summary>
    /// Сохраняет текущее состояние всех данных приложения.
    ///
    /// Метод является единой точкой сохранения для операций сервиса.
    /// Благодаря этому отдельные методы не должны самостоятельно обращаться
    /// к файловой системе или знать формат хранения данных.
    /// </summary>
    private void Save() => _storage.Save(_data);
