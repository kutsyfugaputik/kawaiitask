
using KawaiiTasks.Models; // Подключаем модели проекта: Project, TaskItem, TaskState и Priority.

namespace KawaiiTasks.Services; // Размещаем классы в пространстве имён сервисов приложения.

/// <summary>
/// Статистика одного участника команды для включения в отчёт.
/// Хранит количество назначенных и выполненных задач, а также затраченное время.
/// </summary>
/// <param name="Name">Имя участника команды.</param>
/// <param name="Role">Роль участника в проекте.</param>
/// <param name="Assigned">Общее количество назначенных участнику задач.</param>
/// <param name="Done">Количество выполненных участником задач.</param>
/// <param name="Minutes">Общее количество минут, затраченных участником на задачи.</param>
public record MemberStat(
    string Name,
    string Role,
    int Assigned,
    int Done,
    int Minutes);

/// <summary>
/// Готовый снимок статистики проекта.
/// Содержит все данные, необходимые для формирования отчёта.
/// Один и тот же объект можно использовать для вывода в консоль и создания Markdown-файла.
/// </summary>
/// <param name="Project">Проект, по которому сформирована статистика.</param>
/// <param name="GeneratedAt">Дата и время создания отчёта.</param>
/// <param name="Total">Общее количество задач в проекте.</param>
/// <param name="Done">Количество выполненных задач.</param>
/// <param name="Percent">Процент выполненных задач от общего количества.</param>
/// <param name="ByState">Количество задач в каждом статусе.</param>
/// <param name="ByPriority">Количество задач с каждым уровнем приоритета.</param>
/// <param name="TotalMinutes">Суммарное время, затраченное на все задачи.</param>
/// <param name="Overdue">Список просроченных задач.</param>
/// <param name="Members">Статистика по каждому участнику команды.</param>
/// <param name="Unassigned">Количество задач без назначенного исполнителя.</param>
/// <param name="CandyPoints">Общее количество игровых баллов проекта.</param>
/// <param name="TopByTime">Три задачи с наибольшими затратами времени.</param>
public record ProjectReport(
    Project Project,
    DateTime GeneratedAt,
    int Total,
    int Done,
    double Percent,
    Dictionary<TaskState, int> ByState,
    Dictionary<Priority, int> ByPriority,
    int TotalMinutes,
    List<TaskItem> Overdue,
    List<MemberStat> Members,
    int Unassigned,
    int CandyPoints,
    List<TaskItem> TopByTime);

/// <summary>
/// Сервис формирования статистики проекта и расчёта игровых баллов.
/// Отвечает за обработку данных проекта, подсчёт показателей и подготовку отчёта.
/// Не занимается непосредственным отображением информации.
/// </summary>
public static class ReportService
{
    // Названия игровых уровней, которые присваиваются проекту в зависимости от количества баллов.
    // Индекс элемента соответствует порядковому номеру уровня минус один.
    private static readonly string[] LevelNames =
        { "Зефирка", "Маршмеллоу", "Пончик", "Единорожка", "Королева кода" };

    /// <summary>
    /// Рассчитывает количество игровых баллов за одну задачу.
    /// Баллы начисляются только за выполненные задачи.
    /// Размер награды зависит от приоритета, а за выполнение в срок добавляется бонус.
    /// </summary>
    /// <param name="task">Задача, для которой рассчитывается награда.</param>
    /// <returns>Количество начисляемых баллов.</returns>
    public static int TaskPoints(TaskItem task)
    {
        // Если задача ещё не выполнена, игровые баллы за неё не начисляются.
        if (!task.IsDone) return 0;

        // Проверяем, можно ли определить своевременность выполнения задачи.
        // Для этого должны быть заполнены обе даты: завершения и установленного срока.
        // Сравниваем только даты, не учитывая часы и минуты.
        var onTime = task.CompletedAt.HasValue && task.Deadline.HasValue
                     && task.CompletedAt.Value.Date <= task.Deadline.Value.Date;

        // Основная награда зависит от приоритета задачи: значение приоритета умножается на 10.
        // Если задача выполнена не позднее установленного срока, добавляем ещё 5 баллов.
        // Результат приводим к типу int, поскольку игровые баллы хранятся как целое число.
        return (int)task.Priority * 10 + (onTime ? 5 : 0);
    }

    /// <summary>
    /// Рассчитывает суммарное количество игровых баллов за все задачи проекта.
    /// </summary>
    /// <param name="project">Проект, для которого рассчитываются баллы.</param>
    /// <returns>Общая сумма баллов по всем задачам проекта.</returns>
    public static int CandyPoints(Project project) =>
        // Применяем TaskPoints к каждой задаче и складываем полученные значения.
        project.Tasks.Sum(TaskPoints);

    /// <summary>
    /// Определяет игровой уровень проекта на основании набранных баллов.
    /// Каждые 50 баллов открывают следующий уровень.
    /// После достижения максимального уровня его название больше не изменяется.
    /// </summary>
    /// <param name="points">Количество набранных игровых баллов.</param>
    /// <returns>Кортеж: порядковый номер уровня и его название.</returns>
    public static (int Level, string Name) Level(int points)
    {
        // Сначала ограничиваем количество баллов снизу нулём.
        // Затем делим на 50, чтобы определить индекс уровня.
        // Math.Min ограничивает индекс последним доступным элементом массива.
        // Благодаря этому даже очень большое количество баллов не приведёт к выходу за границы массива.
        var index = Math.Min(Math.Max(0, points) / 50, LevelNames.Length - 1);

        // Возвращаем уровень, начиная отсчёт с единицы, и соответствующее ему название.
        // Индексация массива начинается с нуля, поэтому к индексу прибавляется 1.
        return (index + 1, LevelNames[index]);
    }

    /// <summary>
    /// Формирует полный отчёт по проекту.
    /// Собирает общую статистику, распределение задач, данные команды,
    /// сведения о просроченных задачах и игровые показатели.
    /// </summary>
    /// <param name="project">Проект, данные которого необходимо проанализировать.</param>
    /// <returns>Объект ProjectReport со всеми рассчитанными показателями.</returns>
    public static ProjectReport Build(Project project)
    {
        // Получаем общее количество задач в проекте.
        var total = project.Tasks.Count;

        // Подсчитываем только те задачи, у которых установлен признак выполнения.
        var done = project.Tasks.Count(t => t.IsDone);

        // Перебираем ВСЕ значения перечисления TaskState,
        // а не только статусы, которые фактически встречаются в задачах.
        // Для каждого статуса подсчитываем количество соответствующих задач.
        // Это позволяет отображать в диаграммах и таблицах статусы с нулевыми значениями.
        var byState = Enum.GetValues<TaskState>()
            .ToDictionary(s => s, s => project.Tasks.Count(t => t.State == s));

        // Аналогично формируем статистику по приоритетам.
        // В словаре будут присутствовать все значения Priority,
        // даже если в проекте пока нет задач с определённым приоритетом.
        var byPriority = Enum.GetValues<Priority>()
            .ToDictionary(p => p, p => project.Tasks.Count(t => t.Priority == p));

        // Формируем статистику по каждому участнику команды.
        // Select преобразует каждого участника в отдельную запись MemberStat.
        var members = project.Team.Select(m =>
        {
            // Отбираем задачи, назначенные текущему участнику.
            // AssigneeId связывает задачу с идентификатором исполнителя.
            // ToList создаёт отдельный список найденных задач.
            var mine = project.Tasks.Where(t => t.AssigneeId == m.Id).ToList();

            // Создаём статистику участника:
            // m.Name — имя участника;
            // m.Role — его роль;
            // mine.Count — общее количество назначенных задач;
            // mine.Count(t => t.IsDone) — количество выполненных задач;
            // mine.Sum(t => t.SpentMinutes) — суммарное затраченное время.
            return new MemberStat(
                m.Name,
                m.Role,
                mine.Count,
                mine.Count(t => t.IsDone),
                mine.Sum(t => t.SpentMinutes));
        }).ToList(); // Преобразуем результаты Select в готовый список статистики участников.

        // Создаём итоговый объект отчёта, передавая в него все рассчитанные показатели.
        return new ProjectReport(
            project, // Исходный проект, к которому относится отчёт.

            DateTime.Now, // Запоминаем текущие дату и время формирования отчёта.

            total, // Общее количество задач.

            done, // Количество выполненных задач.

            total == 0 ? 0 : done * 100.0 / total, // Рассчитываем процент выполнения.
                                                    // Если задач нет, возвращаем 0, чтобы избежать деления на ноль.
                                                    // Умножение на 100.0 обеспечивает вычисление с плавающей точкой.

            byState, // Количество задач по каждому статусу.

            byPriority, // Количество задач по каждому приоритету.

            project.Tasks.Sum(t => t.SpentMinutes), // Складываем время, затраченное на все задачи проекта.

            // Отбираем просроченные задачи, сортируем их по сроку выполнения
            // и преобразуем результат в список.
            project.Tasks.Where(t => t.IsOverdue).OrderBy(t => t.Deadline).ToList(),

            members, // Передаём подготовленную статистику по участникам команды.

            // Подсчитываем задачи, у которых отсутствует идентификатор исполнителя.
            project.Tasks.Count(t => t.AssigneeId is null),

            CandyPoints(project), // Рассчитываем суммарное количество игровых баллов проекта.

            // Отбираем задачи, на которые было затрачено хотя бы несколько минут.
            // Сортируем их по убыванию затраченного времени.
            // Take(3) оставляет только три задачи с наибольшими затратами времени.
            project.Tasks.Where(t => t.SpentMinutes > 0)
                .OrderByDescending(t => t.SpentMinutes)
                .Take(3)
                .ToList());
    }
}
